// The query expressions OceanBase 4.3.5 takes, which are not MySQL's. OceanBase has
// no TABLE primary. A VALUES primary takes ORDER BY, LIMIT and a locking clause,
// and goes wherever a SELECT goes, including the left of a set operation. An INTO
// after a query expression is select_into's, so only one standing as a statement
// takes it. A parenthesized query takes a locking clause or an INTO only after an
// ORDER BY or LIMIT, and an unparenthesized operand ends before its own clauses.
//
// Ref: OceanBase 4.3.5 src/sql/parser/sql_parser_mysql_mode.y: select_stmt,
