// TestCastTypeForms holds the parser to the recorded verdicts without the server.
func TestCastTypeForms(t *testing.T) {
	for _, c := range castTypeFormCases {
		t.Run(c.sql, func(t *testing.T) {
			_, err := Parse(c.sql)
			if omniAccepts := err == nil; omniAccepts != c.accept {
				t.Errorf("omni accepts=%v, the record says %v for %q: %v", omniAccepts, c.accept, c.sql, err)
			}
		})
	}
}

func TestCastTypeFormsOceanBaseOracle(t *testing.T) {
	db := oceanBaseOracle(t)
	ctx := context.Background()
	for _, stmt := range []string{"DROP DATABASE IF EXISTS obcast", "CREATE DATABASE obcast", "USE obcast"} {
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			t.Fatalf("seed %q: %v", stmt, err)
		}
	}
	t.Cleanup(func() { _, _ = db.ExecContext(ctx, "DROP DATABASE IF EXISTS obcast") })
	for _, c := range castTypeFormCases {
		t.Run(c.sql, func(t *testing.T) {
			got, err := engineAccepts(ctx, db, c.sql)
			if err != nil {
				t.Fatalf("the oracle gave no verdict on %q: %v", c.sql, err)
			}
			if got != c.accept {
				t.Errorf("OceanBase accepts %q = %v, the record says %v", c.sql, got, c.accept)
			}
		})
	}
}
