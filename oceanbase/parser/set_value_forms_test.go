// SET's quoted user variables and a bare DEFAULT in an expression as OceanBase reads them, with
// the forms set_list_forms_test.go does not hold, every verdict measured with PREPARE on
// OceanBase CE 4.3.5.6 (oceanbase/oceanbase-ce:4.3.5-lts) on 2026-11-05: a 1064 is the parser's
// refusal, and any other answer is a statement that parsed.
//
// user_variable, sql_parser_mysql_mode.l:68, takes a quoted name from a short list of bytes, so
// `SET @'a_b' = 1` parses where `SET @'a b' = 1` and SET @`a b` = 1 are 1064s. 'user'@'host' keeps
// its own rule. An empty name parses: `SELECT @''` runs, and `SET @'' = 1` fails after parsing,
// with a 3061.
//
// set_expr_or_default, sql_parser_mysql_mode.y:18607, has DEFAULT beside expr and not inside it,
// so `SET a = (DEFAULT)` and `SET a = 1 + DEFAULT` are 1064s.
//
// Not in this table, because omni still disagrees and each is its own change. A bare @: `SELECT
// @` and `SELECT @ a` parse. PREPARE and EXECUTE, which answer 1064 under PREPARE however they
// are spelled.

// TestSetValueForms holds omni to the recorded verdicts without a server, so a run with no
// Docker still reports a widened or narrowed grammar.
func TestSetValueForms(t *testing.T) {
	for _, c := range setValueFormCases {
		t.Run(c.sql, func(t *testing.T) {
			got, err := parsesAsOneStatement(c.sql)
			if got != c.accept {
				t.Errorf("omni accepts=%v, want %v for %q: %v", got, c.accept, c.sql, err)
			}
		})
	}
}

