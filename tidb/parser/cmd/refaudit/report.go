package main

import (
	"fmt"
	"strings"
)

// renderReport renders the coverage report: the counts, then the list of rules
// no production cites. The list is what guides the grammar work — a rule with no
// citing production is a form omni may not implement, or implements without
// recording where. The report deliberately omits per-citation and raw-count
// detail so that editing a comment does not churn it; only a rule gaining its
// first citation or losing its last changes the file.
func renderReport(a Audit) string {
	uncited := a.uncitedRules()
	var b strings.Builder
	b.WriteString("# TiDB parser.y syntax-mapping coverage\n")
	b.WriteString("#\n")
	b.WriteString("# Generated by tidb/parser/cmd/refaudit from the vendored v8.5.5 parser.y\n")
	b.WriteString("# and omni's TiDB productions. It is a ledger, not a proof: a citation says\n")
	b.WriteString("# \"meant to implement\", not \"accepts exactly\" (design doc section 3.6).\n")
	b.WriteString("# Regenerate with: go test ./tidb/parser/cmd/refaudit -run TestCoverageReport -update\n")
	b.WriteString("#\n")
	fmt.Fprintf(&b, "# Grammar rules (v8.5.5):     %d\n", len(a.Rules))
	fmt.Fprintf(&b, "# Rules with a citation:      %d\n", len(a.Rules)-len(uncited))
	fmt.Fprintf(&b, "# Rules with no citation:     %d\n", len(uncited))
	b.WriteString("#\n")
	b.WriteString("# Rules with no citing production, in parser.y source order:\n")
	for _, name := range uncited {
		b.WriteString(name)
		b.WriteByte('\n')
	}
	return b.String()
}
