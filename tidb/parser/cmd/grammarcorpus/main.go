// Command grammarcorpus builds the parser.y completeness corpus: for every
// alternative of every rule in TiDB's grammar at a release tag, the shortest
// statement that exercises it. It writes the statements with placeholder
// verdicts; tidb/parser's TestTiDBParserYCorpus{Omni,Engine}Verdicts fill the
// omni and engine columns with -update, as they do for the pingcap corpus.
//
// It is a plain root-module command and imports nothing from omni or pingcap:
// it reads grammar text and emits SQL text. `go test ./...` compiles it but
// never runs it. By default it reads the vendored parser.y under testdata, so
// a normal run needs no network. Run it from the repo root:
//
//	go run ./tidb/parser/cmd/grammarcorpus # reads the vendored parser.y, rewrites the corpus
//
// To move to a new TiDB release, refresh the vendored copy and rerun:
//
//	curl -fsSL https://raw.githubusercontent.com/pingcap/tidb/<tag>/pkg/parser/parser.y \
//		-o tidb/parser/cmd/grammarcorpus/testdata/parser.y
//	go run ./tidb/parser/cmd/grammarcorpus -tag <tag>
package main

import (
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"
)

const defaultTag = "v8.5.5"

// defaultGrammar is the vendored copy of pingcap/tidb's pkg/parser/parser.y,
// read by default so a run needs no network. Refresh it to move to a new tag.
const defaultGrammar = "tidb/parser/cmd/grammarcorpus/testdata/parser.y"

func grammarURL(tag string) string {
	return fmt.Sprintf("https://raw.githubusercontent.com/pingcap/tidb/%s/pkg/parser/parser.y", tag)
}

func main() {
	tag := flag.String("tag", defaultTag, "the TiDB release tag the parser.y came from (recorded in the corpus header)")
	grammarPath := flag.String("grammar", defaultGrammar, "read parser.y from this file; set empty to fetch it at -tag over the network")
	out := flag.String("out", filepath.Join("tidb", "parser", "testdata", "parser_y_corpus.tsv"),
		"the corpus file to write")
	flag.Parse()

	src, source, err := loadGrammar(*grammarPath, *tag)
	if err != nil {
		fail(err)
	}
	g, err := parseGrammar(src)
	if err != nil {
		fail(fmt.Errorf("parse parser.y: %w", err))
	}
	rows, uncovered := g.generate()
	if len(rows) == 0 {
		fail(fmt.Errorf("no rows generated"))
	}
	if err := writeCorpus(*out, source, rows); err != nil {
		fail(err)
	}

	alts := 0
	for _, r := range g.rules {
		alts += len(r.alts)
	}
	fmt.Printf("parser.y %s: %d rules, %d alternatives\n", *tag, len(g.rules), alts)
	fmt.Printf("wrote %d rows to %s\n", len(rows), *out)
	if len(uncovered) > 0 {
		fmt.Printf("%d alternatives need a hand-written sentence (unreachable or non-terminating):\n", len(uncovered))
		for _, label := range uncovered {
			fmt.Printf("  %s\n", label)
		}
	}
}

// loadGrammar returns the text of parser.y, from a local file when one is
// given, otherwise fetched at the tag, along with a one-line provenance note.
func loadGrammar(path, tag string) (src, source string, err error) {
	if path != "" {
		b, err := os.ReadFile(path)
		if err != nil {
			return "", "", err
		}
		note := "local file " + path
		if path == defaultGrammar {
			note = "the vendored pkg/parser/parser.y (pingcap/tidb " + tag + ")"
		}
		return string(b), note, nil
	}
	url := grammarURL(tag)
	client := &http.Client{Timeout: 60 * time.Second}
	resp, err := client.Get(url)
	if err != nil {
		return "", "", fmt.Errorf("fetch %s: %w", url, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return "", "", fmt.Errorf("fetch %s: HTTP %d", url, resp.StatusCode)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		return "", "", fmt.Errorf("read %s: %w", url, err)
	}
	return string(b), url, nil
}

// writeCorpus writes the corpus file: a provenance header, then one tab-
// separated row per alternative with placeholder verdicts the oracle tests
// fill in. The statement stays in the last column so a tab or space in it, were
// there ever one, would survive the loader's split.
func writeCorpus(path, source string, rows []Row) error {
	var b strings.Builder
	fmt.Fprintf(&b, "# TiDB parser.y completeness corpus, one row per grammar alternative.\n")
	fmt.Fprintf(&b, "# Generated by tidb/parser/cmd/grammarcorpus from %s.\n", source)
	fmt.Fprintf(&b, "# Columns: omni verdict, engine verdict, Rule#alternative, statement.\n")
	fmt.Fprintf(&b, "# Verdicts start as placeholders; fill them with\n")
	fmt.Fprintf(&b, "#   go test ./tidb/parser -run TestTiDBParserYCorpusOmniVerdicts -update\n")
	fmt.Fprintf(&b, "#   go test ./tidb/parser -run TestTiDBParserYCorpusEngineVerdicts -update\n")
	for _, r := range rows {
		if strings.ContainsAny(r.stmt, "\t\n") {
			return fmt.Errorf("row %s has a tab or newline in its statement: %q", r.label, r.stmt)
		}
		fmt.Fprintf(&b, "reject\treject\t%s\t%s\n", r.label, r.stmt)
	}
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "grammarcorpus:", err)
	os.Exit(1)
}
