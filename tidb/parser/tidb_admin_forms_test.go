// tidbAdminRefusedWhileParsing are statements v8.5.5 refuses from a parser action,
// with the code it answers. Each answers the same code when a syntax error follows
// it, so the parser never reached the rest of the text. RECOMMEND INDEX's ids are
// `NUM` in the grammar and asserted to an int64 in its action, so one past that
// range fails there rather than as a 1064.
var tidbAdminRefusedWhileParsing = []struct {
	sql  string
	code uint16
}{
	{"recommend index apply 9223372036854775808", 1105},
	{"recommend index apply 18446744073709551615", 1105},
	{"recommend index ignore 18446744073709551615", 1105},
}

// TestTiDBAdminForms holds this parser to tidbAdminCases. It needs no container,
// so it guards the grammar wherever it runs.
func TestTiDBAdminForms(t *testing.T) {
	for _, c := range tidbAdminCases {
		t.Run(c.sql, func(t *testing.T) {
			_, err := Parse(c.sql)
			if accepts := err == nil; accepts != c.accept {
				t.Errorf("omni %ss %q, TiDB %s %ss it (err=%v)",
					verdictName(accepts), c.sql, tidbCorpusVersion, verdictName(c.accept), err)
			}
		})
	}
	for _, c := range tidbAdminRefusedWhileParsing {
		t.Run(c.sql, func(t *testing.T) {
			if _, err := Parse(c.sql); err == nil {
				t.Errorf("omni accepts %q, which TiDB %s refuses while parsing with %d",
					c.sql, tidbCorpusVersion, c.code)
			}
		})
	}
}

// TestTiDBAdminFormsSurviveTruncation parses every prefix of every case,
// the truncated input the engine contract says must fail cleanly.
func TestTiDBAdminFormsSurviveTruncation(t *testing.T) {
	for _, c := range tidbAdminCases {
		for i := range c.sql {
			_, _ = Parse(c.sql[:i])
		}
	}
}

// tidbAdminWordsAsNames are statements in which this family's words are ordinary
// names: a table, a column, an alias, an index, a variable. RECOMMEND, PAUSE, CANCEL,
// BR, APPLY, METADATA and TIDB are not registered in the lexer at all, and the
// implicit alias is the site that broke the last time a word was (#634): its branch
