// TiDB's RECOMMEND INDEX, SET CONFIG, KILL TIDB, FLUSH TIDB PLUGINS, ALTER RANGE
// and CANCEL DISTRIBUTION JOB statements, and the log backup task and BR job arms
// of BRIEStmt, read against a live pingcap/tidb:v8.5.5:
//
//	RECOMMEND INDEX RUN [FOR 'sql'] [WITH name = literal, ...]
//	RECOMMEND INDEX SHOW
//	RECOMMEND INDEX {APPLY | IGNORE} id
//	RECOMMEND INDEX SET name = literal, ...
//	SET CONFIG {type | 'instance'} item {= | :=} value
//	{PAUSE | RESUME | STOP} BACKUP LOGS
//	PURGE BACKUP LOGS FROM 'storage'
//	SHOW BACKUP LOGS STATUS
//	SHOW BACKUP [LOGS] METADATA FROM 'storage'
//	SHOW BR JOB [QUERY] id
//	CANCEL {BR | DISTRIBUTION} JOB id
//	KILL [TIDB] [CONNECTION | QUERY] number
//	KILL [TIDB] function_call
//	FLUSH [NO_WRITE_TO_BINLOG | LOCAL] TIDB PLUGINS name, ...
//	ALTER RANGE name PLACEMENT POLICY [=] {name | 'name' | DEFAULT}
//	ALTER RANGE name PLACEMENT POLICY SET DEFAULT
//
// The corpus holds almost nothing here but accepting rows, so the rejections are
// the point of this file: a reader that took too much would pass the whole corpus.
//
// Every case was measured against pingcap/tidb:v8.5.5 on 2026-11-05, through
// PREPARE, and the verdict is what that server answered, so an image upgrade that
// changes one fails TestTiDBAdminFormsMatchTiDB instead of passing silently. A
// statement whose parser action refuses it with a code other than 1064 is in
// tidbAdminRefusedWhileParsing instead, and the character sets the server looks up
// while parsing (1115 for `_utf16 'x'`) count as read, as everywhere in this package.
//
// Ref: TiDB v8.5.5 parser.y:14346-14426 (RecommendIndexStmt), 10781-10788,
// 10931-10940 (SET CONFIG), 5640-5705 (BRIEStmt), 3198-3204
// (CancelDistributionJobStmt), 15289-15331 (KillStmt), 4058-4081 (BuiltinFunction),
// 12147-12200 (FlushStmt), 13764-13769 (AlterRangeStmt), 2068-2084
// (PlacementPolicyOption); pkg/parser/lexer.go:323, 820, 881 (identifierDot).

