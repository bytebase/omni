import "testing"

// TABLESAMPLE as TiDB v8.5.5 reads it, every verdict measured with PREPARE on
// pingcap/tidb:v8.5.5 on 2026-11-05: a 1064 is the parser's refusal, and any other
// answer means the text parsed. Error 8128, which every method but REGIONS gets,
// comes from the planner, so those forms count as parsed.
//
// The clause is TableSampleOpt, parser.y:9332, and only TableFactor reads it
// (parser.y:9909): DELETE FROM and LOCK TABLES name a table some other way. The word
// is in no identifier rule, so it is reserved, with the exception every reserved
// word has: beside a dot (misc.go:1107) and after @@ (lexer.go:618) the lexer does
// not treat it as a keyword.
//
// Not in this table, because they do not depend on this clause or word, and omni
// does not match them yet: `t AS OF TIMESTAMP expr`, which omni does not read; and
// `DELETE FROM t a USING t` and `LOCK TABLES t a READ`, which it accepts and TiDB refuses.

// tableSampleCase is a statement and whether the engine's parser accepts it.
type tableSampleCase struct {
	sql    string
	accept bool
}

// parsesAsOneStatement is the acceptance these tables mean: the text parses, and
// as exactly one statement.
func parsesAsOneStatement(sql string) (bool, error) {
	list, err := Parse(sql)
	if err != nil {
		return false, err
	}
	return len(list.Items) == 1, nil
}

// TestTableSampleForms holds omni to the recorded verdicts without a server, so a
// run with no Docker still reports a widened or narrowed grammar.
func TestTableSampleForms(t *testing.T) {
	for _, c := range tableSampleCases {
		t.Run(c.sql, func(t *testing.T) {
			got, err := parsesAsOneStatement(c.sql)
			if got != c.accept {
				t.Errorf("omni accepts=%v, want %v for %q: %v", got, c.accept, c.sql, err)
			}
		})
	}
}

