// TestCastTypeForms holds the parser to the recorded verdicts without the server.
func TestCastTypeForms(t *testing.T) {
	for _, c := range castTypeFormCases {
		t.Run(c.sql, func(t *testing.T) {
			_, err := Parse(c.sql)
			if omniAccepts := err == nil; omniAccepts != c.accept {
				t.Errorf("omni accepts=%v, the record says %v for %q: %v", omniAccepts, c.accept, c.sql, err)
			}
		})
	}
}

func TestCastTypeFormsOracle(t *testing.T) {
	tc := startTiDB(t)
	assertTiDBVersion(t, tc)
	for i, c := range castTypeFormCases {
		t.Run(c.sql, func(t *testing.T) {
			previous := "<start of cases>"
			if i > 0 {
				previous = castTypeFormCases[i-1].sql
			}
			accepts, _, err := tc.syntaxVerdict(t, c.sql, previous)
			if err != nil {
				t.Fatalf("no verdict: %v", err)
			}
			if accepts != c.accept {
				t.Errorf("TiDB %s accepts=%v, the record says %v for %q", tidbCorpusVersion, accepts, c.accept, c.sql)
			}
		})
	}
}
