// TestBuiltins holds builtins.go to the pinned server's catalog: the
// functions and type names CockroachDB resolves without a schema. A replay
// renders the file from tapes/TestBuiltins.tape and fails on any difference;
// a recording (OMNI_RECORD=1) asks the server and rewrites the file.
func TestBuiltins(t *testing.T) {
	db := testcontainer.Open(t)
	functions := queryNames(t, db, `SELECT DISTINCT p.proname
FROM pg_catalog.pg_proc AS p JOIN pg_catalog.pg_namespace AS n ON n.oid = p.pronamespace
WHERE n.nspname = 'pg_catalog'
ORDER BY 1`)
	pgTypes := queryNames(t, db, `SELECT t.typname
FROM pg_catalog.pg_type AS t JOIN pg_catalog.pg_namespace AS n ON n.oid = t.typnamespace
WHERE n.nspname = 'pg_catalog' AND t.typtype = 'b' AND t.typcategory NOT IN ('A', 'X')
ORDER BY 1`)
	// CockroachDB spells some types its own way (text is STRING, bytea is
	// BYTES): a column of each type reports that spelling.
	for i, typ := range pgTypes {
		if _, err := db.Exec(fmt.Sprintf("CREATE TABLE t%d (c %s)", i, QuoteIdentifierIfNeeded(typ, false))); err != nil {
			t.Logf("type %s takes no column: %v", typ, err)
		}
	}
	crdbTypes := queryNames(t, db, `SELECT DISTINCT crdb_sql_type
FROM information_schema.columns
WHERE table_schema = 'public' AND column_name = 'c'
ORDER BY 1`)

	var types []string
	for _, typ := range slices.Concat(pgTypes, crdbTypes) {
		typ = strings.ToUpper(typ)
		if bareTypeName.MatchString(typ) && !slices.Contains(types, typ) {
			types = append(types, typ)
		}
	}
	slices.Sort(types)

	pin, err := enginetest.LoadPin(testcontainer.Pins, testcontainer.Default)
	if err != nil {
		t.Fatal(err)
	}
	got := renderBuiltins(t, pin.Image, functions, types)
	mode, err := enginetest.RunMode()
	if err != nil {
		t.Fatal(err)
	}
	if mode == enginetest.ModeRecord {
		if err := os.WriteFile("builtins.go", got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile("builtins.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("builtins.go differs from what tapes/TestBuiltins.tape renders; record it again with OMNI_RECORD=1")
	}
}

// bareTypeName is a type name that reads back unquoted, without modifiers.
var bareTypeName = regexp.MustCompile(`^[A-Z][A-Z0-9_]*$`)

func queryNames(t *testing.T, db *sql.DB, query string) []string {
	t.Helper()
	rows, err := db.Query(query)
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	var names []string
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			t.Fatal(err)
		}
		names = append(names, name)
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
	return names
}

func renderBuiltins(t *testing.T, image string, functions, types []string) []byte {
	t.Helper()
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by TestBuiltins from %s. DO NOT EDIT.\n\n", image)
	b.WriteString("package completion\n\n")
	b.WriteString("// builtinFunctions are the functions CockroachDB resolves without a\n// schema: the names pg_catalog holds in pg_proc.\n")
	writeList(&b, "builtinFunctions", functions)
	b.WriteString("\n// builtinTypes are the type names CockroachDB resolves without a schema:\n// pg_catalog's base types in pg_type, and the names CockroachDB reports\n// for columns of them.\n")
	writeList(&b, "builtinTypes", types)
	out, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func writeList(b *bytes.Buffer, name string, items []string) {
	fmt.Fprintf(b, "var %s = []string{\n", name)
	for _, item := range items {
		fmt.Fprintf(b, "\t%q,\n", item)
	}
	b.WriteString("}\n")
}
