package parser

import "testing"

// TestSecurityKeysByGrammar pins statements of the certificate and key family
// whose verdict SQL Server 2022 (the pinned image, under SET PARSEONLY ON)
// gave, beyond the samples compat.tsv holds.
func TestSecurityKeysByGrammar(t *testing.T) {
	accepted := []string{
		"CREATE CERTIFICATE a FROM BINARY = 0x00 WITH PRIVATE KEY (BINARY = 0x00, DECRYPTION BY PASSWORD = 'a')",
		"CREATE CERTIFICATE a FROM FILE = 'a' WITH FORMAT = 'PFX', PRIVATE KEY (DECRYPTION BY PASSWORD = 'x')",
		"CREATE CERTIFICATE a FROM FILE = 'a' WITH PRIVATE KEY (FILE = 'b'), FORMAT = 'PFX'",
		"CREATE CERTIFICATE a ENCRYPTION BY PASSWORD = 'x' WITH START_DATE = '20200101', SUBJECT = 'a' ACTIVE FOR BEGIN_DIALOG = OFF",
		"ALTER CERTIFICATE a WITH PRIVATE KEY (ENCRYPTION BY PASSWORD = 'y', FILE = 'a')",
		"ALTER CERTIFICATE a ATTESTED BY N'a'",
		"BACKUP CERTIFICATE a TO FILE = 'a' WITH PRIVATE KEY (BINARY = 0x00, FILE = 'a')",
		"BACKUP CERTIFICATE a TO FILE = 'a' WITH FORMAT = 'PFX', PRIVATE KEY (FILE = 'b', ENCRYPTION BY PASSWORD = 'x', ALGORITHM = 'AES_256')",
		"CREATE SYMMETRIC KEY a FROM PROVIDER a WITH IDENTITY_VALUE = 'a'",
		"CREATE SYMMETRIC KEY a FROM PROVIDER a WITH ALGORITHM = RSA_512",
		"CREATE ASYMMETRIC KEY a FROM PROVIDER a WITH ALGORITHM = DES",
		"CREATE ASYMMETRIC KEY a WITH ALGORITHM = rsa_4096",
		"CREATE DATABASE SCOPED CREDENTIAL a WITH IDENTITY = 'a' FOR CRYPTOGRAPHIC PROVIDER p",
		"CREATE COLUMN MASTER KEY a WITH (KEY_PATH = 'b', KEY_STORE_PROVIDER_NAME = 'a', ENCLAVE_COMPUTATIONS (SIGNATURE = 0x01))",
		"CREATE COLUMN ENCRYPTION KEY a WITH VALUES (ALGORITHM = 'RSA_OAEP', COLUMN_MASTER_KEY = b, ENCRYPTED_VALUE = 0x01)",
		"RESTORE MASTER KEY FROM URL = 'a' DECRYPTION BY PASSWORD = 'x' ENCRYPTION BY PASSWORD = 'y'",
		"ADD SIGNATURE TO a BY SYMMETRIC KEY a",
		"ADD SIGNATURE TO b.dbo.a BY PASSWORD = 'x'",
		"DROP DATABASE ENCRYPTION",
		"DROP DATABASE SCOPED",
	}
	rejected := []string{
		"CREATE CERTIFICATE a WITH [SUBJECT] = 'a'",
		"CREATE CERTIFICATE a WITH SUBJECT = 'a', SUBJECT = 'b'",
		"CREATE CERTIFICATE a FROM ASSEMBLY a WITH PRIVATE KEY (FILE = 'b')",
		"CREATE CERTIFICATE a FROM FILE = 'a' WITH PRIVATE KEY (FILE = 'b', BINARY = 0x00)",
		"CREATE CERTIFICATE a FROM FILE = 'a' WITH PRIVATE KEY (FILE = 'b', ALGORITHM = 'AES_256')",
		"ALTER CERTIFICATE a WITH FORMAT = 'PFX', PRIVATE KEY (FILE = 'a')",
		"BACKUP CERTIFICATE a TO FILE = 'a' WITH PRIVATE KEY (ENCRYPTION BY PASSWORD = 'x')",
		"BACKUP CERTIFICATE a TO URL = 'a'",
		"CREATE SYMMETRIC KEY a WITH ALGORITHM = DES ENCRYPTION BY PASSWORD = 'x'",
		"CREATE SYMMETRIC KEY a WITH ALGORITHM = AES_256",
		"CREATE SYMMETRIC KEY a FROM PROVIDER a WITH KEY_SOURCE = 'a'",
		"CREATE ASYMMETRIC KEY a WITH ALGORITHM = RSA_1024",
		"CREATE ASYMMETRIC KEY a WITH ALGORITHM = [RSA_4096]",
		"CREATE ASYMMETRIC KEY a FROM PROVIDER a",
		"CREATE ASYMMETRIC KEY a FROM PROVIDER a WITH IDENTITY_VALUE = 'a'",
		"ALTER ASYMMETRIC KEY a WITH PRIVATE KEY (FILE = 'x')",
		"CREATE MASTER KEY",
		"ALTER MASTER KEY ADD ENCRYPTION BY CERTIFICATE a",
		"OPEN SYMMETRIC KEY a DECRYPTION BY SYMMETRIC KEY a WITH PASSWORD = 'x'",
		"ALTER CREDENTIAL a WITH IDENTITY = 'a' FOR CRYPTOGRAPHIC PROVIDER p",
		"CREATE CREDENTIAL a WITH SECRET = 'b'",
		"ALTER CRYPTOGRAPHIC PROVIDER a FROM FILE = 'a' ENABLE",
		"CREATE DATABASE ENCRYPTION KEY WITH ALGORITHM = TRIPLE_DES_3KEY ENCRYPTION BY SERVER CERTIFICATE a",
		"ALTER DATABASE ENCRYPTION KEY REGENERATE WITH ALGORITHM = AES_256 ENCRYPTION BY SERVER CERTIFICATE a",
		"CREATE COLUMN MASTER KEY a WITH (KEY_STORE_PROVIDER_NAME = 'a')",
		"CREATE COLUMN MASTER KEY a WITH (ENCLAVE_COMPUTATIONS (SIGNATURE = 0x01), KEY_STORE_PROVIDER_NAME = 'a', KEY_PATH = 'b')",
		"CREATE COLUMN ENCRYPTION KEY a WITH VALUES (COLUMN_MASTER_KEY = b, ALGORITHM = 'RSA_OAEP')",
		"ALTER COLUMN ENCRYPTION KEY a DROP VALUE (COLUMN_MASTER_KEY = b, ALGORITHM = 'RSA_OAEP', ENCRYPTED_VALUE = 0x01)",
		"ALTER SERVICE MASTER KEY WITH OLD_ACCOUNT = 'a', NEW_PASSWORD = 'b'",
		"BACKUP SERVICE MASTER KEY TO URL = 'a' ENCRYPTION BY PASSWORD = 'x'",
		"RESTORE MASTER KEY FROM FILE = 'a' DECRYPTION BY PASSWORD = 'x'",
		"ADD SIGNATURE TO a BY CERTIFICATE a WITH SIGNATURE = 'x'",
		"ADD SIGNATURE TO SCHEMA::a BY CERTIFICATE a",
		"DROP DATABASE ENCRYPTION KEY a",
		"DROP DATABASE SCOPED a",
	}
	for _, sql := range accepted {
		if _, err := Parse(sql); err != nil {
			t.Errorf("Parse(%q): %v, want acceptance", sql, err)
		}
	}
	for _, sql := range rejected {
		if _, err := Parse(sql); err == nil {
			t.Errorf("Parse(%q) accepted, want rejection", sql)
		}
	}
}
