// triggerEventIsDatabaseLevel reports whether the event type or group name is
// DDL_DATABASE_LEVEL_EVENTS or held by it.
func triggerEventIsDatabaseLevel(name string) bool {
	for n := name; n != ""; n = triggerEventParents[n] {
		if n == "DDL_DATABASE_LEVEL_EVENTS" {
			return true
		}
	}
	return false
}

// triggerEventHolds reports whether the event group group is the event type
// or group name or holds it.
func triggerEventHolds(group, name string) bool {
	for n := name; n != ""; n = triggerEventParents[n] {
		if n == group {
			return true
		}
	}
	return false
}
