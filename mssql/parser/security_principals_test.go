package parser

import "testing"

// TestSecurityPrincipalsRejected checks principal statements SQL Server 2022
// refuses: an option a statement does not take, a value of the wrong form
// (a quoted name, a hex SID written as a name, ON for a database), a repeated
// option, a hex password without HASHED, a bracketed keyword, a missing
// action, and IF EXISTS or a list where the DROP takes neither.
func TestSecurityPrincipalsRejected(t *testing.T) {
	for _, sql := range []string{
		"CREATE LOGIN a WITH PASSWORD = 0x00",
		"CREATE LOGIN a WITH PASSWORD = 'x' HASHED HASHED",
		"CREATE LOGIN a WITH PASSWORD = 'x', SID = a",
		"CREATE LOGIN a WITH PASSWORD = 'x', CHECK_POLICY = a",
		"CREATE LOGIN a WITH PASSWORD = 'x', DEFAULT_DATABASE = ON",
		"CREATE LOGIN a WITH PASSWORD = 'x', DEFAULT_DATABASE = 'a'",
		"CREATE LOGIN a WITH PASSWORD = 'x', DEFAULT_LANGUAGE = 1033",
		"CREATE LOGIN a WITH PASSWORD = 'x', CHECK_POLICY = ON, CHECK_POLICY = OFF",
		"CREATE LOGIN a WITH PASSWORD = 'x', NAME = b",
		"CREATE LOGIN a WITH PASSWORD = 'x', [CHECK_POLICY] = ON",
		"CREATE LOGIN a WITH [PASSWORD] = 'x'",
		"CREATE LOGIN a WITH PASSWORD = 'x', CHECK_POLICY = [ON]",
		"CREATE LOGIN a WITH PASSWORD = 'x' UNLOCK",
		"CREATE LOGIN a WITH PASSWORD = 'x', DEFAULT_DATABASE = NULL",
		"CREATE LOGIN a WITH PASSWORD = 'x', DEFAULT_DATABASE = a.b",
		"CREATE LOGIN a FROM WINDOWS WITH CREDENTIAL = a",
		"CREATE LOGIN a FROM WINDOWS WITH DEFAULT_DATABASE = a, DEFAULT_DATABASE = b",
		"CREATE LOGIN a FROM EXTERNAL PROVIDER WITH TYPE = 'E'",
		"CREATE LOGIN a FROM EXTERNAL PROVIDER WITH OBJECT_ID = a",
		"CREATE LOGIN a FROM CERTIFICATE c WITH DEFAULT_DATABASE = d",
		"CREATE LOGIN a FROM ASYMMETRIC k",
		"CREATE LOGIN a",
		"CREATE LOGIN a FROM [WINDOWS]",
		"ALTER LOGIN a [ENABLE]",
		"ALTER LOGIN a WITH PASSWORD = 0x01",
		"ALTER LOGIN a WITH PASSWORD = 'x' UNLOCK UNLOCK",
		"ALTER LOGIN a WITH PASSWORD = 'x' OLD_PASSWORD = 'y' UNLOCK",
		"ALTER LOGIN a WITH NO CREDENTIAL, NO CREDENTIAL",
		"ALTER LOGIN a WITH CREDENTIAL = c, NO CREDENTIAL",
		"ALTER LOGIN a WITH SID = 0x01",
		"ALTER LOGIN a",
		"ALTER LOGIN a WITH PASSWORD = 'x', PASSWORD = 'y'",
		"ALTER LOGIN a WITH PASSWORD = 0x01 HASHED OLD_PASSWORD = 'y'",
		"ALTER LOGIN a ENABLE WITH NAME = b",
		"CREATE USER a FOR b",
		"CREATE USER a FOR ASYMMETRIC k",
		"CREATE USER a FROM EXTERNAL PROVIDER WITH OBJECT_ID = 'x'",
		"CREATE USER a FOR LOGIN b WITH PASSWORD = 'x'",
		"CREATE USER a WITH DEFAULT_SCHEMA = NULL",
		"CREATE USER a WITH DEFAULT_LANGUAGE = 'x'",
		"CREATE USER a WITH ALLOW_ENCRYPTED_VALUE_MODIFICATIONS = 1",
		"CREATE USER a WITH PASSWORD = 0x01",
		"CREATE USER a WITH PASSWORD = 'x' HASHED",
		"CREATE USER a WITH DEFAULT_SCHEMA = s, SID = 0x01, SID = 0x02",
		"CREATE USER a WITH DEFAULT_LANGUAGE = 2147483648",
		"ALTER USER a",
		"ALTER USER a WITH PASSWORD = 0x01 HASHED",
		"ALTER USER a WITH ALLOW_ENCRYPTED_VALUE_MODIFICATIONS = a",
		"ALTER USER a WITH SID = 0x01",
		"ALTER USER a WITH NAME = b, NAME = c",
		"CREATE ROLE r AUTHORIZATION 'o'",
		"CREATE ROLE default",
		"ALTER ROLE r WITH NAME = 'n'",
		"ALTER ROLE r",
		"ALTER ROLE r ADD [MEMBER] m",
		"ALTER ROLE r ADD MEMBER public",
		"DROP ROLE r, s",
		"DROP USER u, v",
		"DROP LOGIN IF EXISTS l",
		"CREATE APPLICATION ROLE r",
		"CREATE APPLICATION ROLE r WITH PASSWORD = 'x', NAME = n",
		"CREATE APPLICATION ROLE r WITH PASSWORD = 0x01",
		"ALTER APPLICATION ROLE r WITH DEFAULT_SCHEMA = NULL",
		"ALTER APPLICATION ROLE r",
		"DROP APPLICATION ROLE IF EXISTS r",
		"ALTER SERVER ROLE r",
		"ALTER SERVER ROLE r ADD m",
		"DROP SERVER ROLE IF EXISTS r",
	} {
		t.Run(sql, func(t *testing.T) {
			if _, err := Parse(sql); err == nil {
				t.Errorf("Parse(%q): want an error, SQL Server refuses it", sql)
			}
		})
	}
}

// TestSecurityPrincipalsAccepted checks forms SQL Server 2022 takes that the
// rejections above sit beside.
func TestSecurityPrincipalsAccepted(t *testing.T) {
	for _, sql := range []string{
		"CREATE LOGIN a WITH PASSWORD = 'x'",
		"CREATE LOGIN a WITH PASSWORD = 0x00 HASHED",
		"CREATE LOGIN a WITH PASSWORD = 'x' HASHED",
		"CREATE LOGIN a WITH PASSWORD = N'x'",
		"CREATE LOGIN a WITH PASSWORD = 'x' MUST_CHANGE, CHECK_EXPIRATION = ON",
		"CREATE LOGIN a WITH PASSWORD = 'x' MUST_CHANGE HASHED",
		"CREATE LOGIN a WITH PASSWORD = 'x', DEFAULT_DATABASE = a, DEFAULT_LANGUAGE = us_english, CHECK_EXPIRATION = OFF, CHECK_POLICY = ON, CREDENTIAL = c, SID = 0x01",
		"CREATE LOGIN a WITH PASSWORD = 'x', DEFAULT_DATABASE = [ON]",
		"CREATE LOGIN a WITH PASSWORD = 'x', check_policy = on",
		"CREATE LOGIN [d\\a] FROM WINDOWS",
		"CREATE LOGIN a FROM WINDOWS WITH DEFAULT_DATABASE = a, DEFAULT_LANGUAGE = b",
		"CREATE LOGIN a FROM EXTERNAL PROVIDER",
		"CREATE LOGIN a FROM EXTERNAL PROVIDER WITH OBJECT_ID = 'x'",
		"CREATE LOGIN a FROM EXTERNAL PROVIDER WITH TYPE = E, SID = 0x01",
		"CREATE LOGIN a FROM EXTERNAL PROVIDER WITH OBJECT_ID = 'x', TYPE = E, SID=0x01, DEFAULT_DATABASE = a, DEFAULT_LANGUAGE = b",
		"CREATE LOGIN a FROM EXTERNAL PROVIDER WITH TYPE = [E]",
		"CREATE LOGIN a FROM CERTIFICATE c",
		"CREATE LOGIN a FROM CERTIFICATE c WITH CREDENTIAL = d",
		"CREATE LOGIN a FROM ASYMMETRIC KEY k",
		"CREATE LOGIN a FROM ASYMMETRIC KEY k WITH CREDENTIAL = d",
		"CREATE LOGIN a WITH PASSWORD = 'x', SID = 0x",
		"CREATE LOGIN a WITH PASSWORD = 0x HASHED",
		"ALTER LOGIN a ENABLE",
		"ALTER LOGIN a DISABLE",
		"ALTER LOGIN a WITH PASSWORD = 'x' OLD_PASSWORD = 'y'",
		"ALTER LOGIN a WITH PASSWORD = 'x' MUST_CHANGE UNLOCK",
		"ALTER LOGIN a WITH PASSWORD = 'x' UNLOCK MUST_CHANGE",
		"ALTER LOGIN a WITH PASSWORD = 0x01 HASHED",
		"ALTER LOGIN a WITH PASSWORD = 'x' HASHED MUST_CHANGE",
		"ALTER LOGIN a WITH DEFAULT_DATABASE = a, DEFAULT_LANGUAGE = b, NAME = c, CHECK_POLICY = ON, CHECK_EXPIRATION = OFF, CREDENTIAL = d",
		"ALTER LOGIN a WITH NO CREDENTIAL",
		"ALTER LOGIN a ADD CREDENTIAL c",
		"ALTER LOGIN a DROP CREDENTIAL c",
		"ALTER LOGIN a WITH DEFAULT_DATABASE = a, PASSWORD = 'x' MUST_CHANGE",
		"ALTER LOGIN a WITH NAME = [b], DEFAULT_DATABASE = [ON]",
		"CREATE USER a",
		"CREATE USER a FOR LOGIN b",
		"CREATE USER a FROM LOGIN b",
		"CREATE USER a FOR CERTIFICATE c",
		"CREATE USER a FROM ASYMMETRIC KEY k",
		"CREATE USER a FROM EXTERNAL PROVIDER",
		"CREATE USER a FOR EXTERNAL PROVIDER",
		"CREATE USER a WITHOUT LOGIN WITH DEFAULT_SCHEMA = s",
		"CREATE USER a WITH PASSWORD = 'x', DEFAULT_SCHEMA = s, DEFAULT_LANGUAGE = us_english, SID = 0x01, ALLOW_ENCRYPTED_VALUE_MODIFICATIONS = ON",
		"CREATE USER a FOR LOGIN b WITH DEFAULT_SCHEMA = s, ALLOW_ENCRYPTED_VALUE_MODIFICATIONS = OFF",
		"CREATE USER a WITH DEFAULT_LANGUAGE = NONE",
		"CREATE USER a WITH DEFAULT_LANGUAGE = 1033",
		"CREATE USER a WITH TYPE = E",
		"CREATE USER a WITH ALLOW_ENCRYPTED_VALUE_MODIFICATIONS = a",
		"CREATE USER a WITH ALLOW_ENCRYPTED_VALUE_MODIFICATIONS = [ON]",
		"CREATE USER a FROM EXTERNAL PROVIDER WITH TYPE = E",
		"CREATE USER a WITHOUT LOGIN WITH ALLOW_ENCRYPTED_VALUE_MODIFICATIONS = ON",
		"ALTER USER a WITH NAME = b, LOGIN = c, DEFAULT_SCHEMA = s, DEFAULT_LANGUAGE = x, ALLOW_ENCRYPTED_VALUE_MODIFICATIONS = OFF",
		"ALTER USER a WITH DEFAULT_SCHEMA = NULL",
		"ALTER USER a WITH DEFAULT_LANGUAGE = NONE",
		"ALTER USER a WITH DEFAULT_LANGUAGE = 1033",
		"ALTER USER a WITH PASSWORD = 'x' OLD_PASSWORD = 'y'",
		"ALTER USER a WITH PASSWORD = 0x01",
		"ALTER USER a WITH PASSWORD = 0x01 OLD_PASSWORD = 'y'",
		"ALTER USER a WITH DEFAULT_LANGUAGE = [x]",
		"CREATE ROLE r AUTHORIZATION o",
		"CREATE ROLE [default]",
		"ALTER ROLE r ADD MEMBER m",
		"ALTER ROLE r DROP MEMBER [m]",
		"ALTER ROLE r WITH name = n",
		"DROP ROLE IF EXISTS r",
		"DROP USER IF EXISTS u",
		"DROP LOGIN l",
		"CREATE APPLICATION ROLE r WITH PASSWORD = 'x', DEFAULT_SCHEMA = s",
		"CREATE APPLICATION ROLE r WITH DEFAULT_SCHEMA = s, PASSWORD = 'x'",
		"CREATE APPLICATION ROLE r WITH DEFAULT_SCHEMA = s",
		"ALTER APPLICATION ROLE r WITH PASSWORD = 'x', NAME = n, DEFAULT_SCHEMA = s",
		"ALTER APPLICATION ROLE r WITH LOGIN = n",
		"ALTER APPLICATION ROLE r WITH NAME = [n]",
		"DROP APPLICATION ROLE r",
		"CREATE SERVER ROLE r AUTHORIZATION [o]",
		"ALTER SERVER ROLE r ADD MEMBER m",
		"ALTER SERVER ROLE r DROP MEMBER m",
		"ALTER SERVER ROLE r WITH NAME = n",
		"DROP SERVER ROLE r",
	} {
		t.Run(sql, func(t *testing.T) {
			ParseAndCheck(t, sql)
		})
	}
}
