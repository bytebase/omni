type srsRange struct {
	lo, hi     int
	geographic bool
}

// lookupSRS reports whether srid names a spatial reference system and
// whether that system is geographic.
func lookupSRS(srid int) (exists, geographic bool) {
	lo, hi := 0, len(srsRanges)
	for lo < hi {
		mid := (lo + hi) / 2
		switch r := srsRanges[mid]; {
		case srid < r.lo:
			hi = mid
		case srid > r.hi:
			lo = mid + 1
		default:
			return true, r.geographic
		}
	}
	return false, false
}
