// TestInsertForms holds the parser to the verdicts above. An accepted statement
// must read as one: Parse takes statements with no separator between them, so a
// tail the grammar should refuse could otherwise pass as a second one.
func TestInsertForms(t *testing.T) {
	for _, c := range insertFormCases {
		t.Run(c.sql, func(t *testing.T) {
			list, err := Parse(c.sql)
			if got := err == nil; got != c.accept {
				t.Fatalf("Parse(%q) accepts = %v, the engine answered %v (err: %v)", c.sql, got, c.accept, err)
			}
			if err == nil && len(list.Items) != 1 {
				t.Errorf("Parse(%q) read %d statements, want 1", c.sql, len(list.Items))
			}
		})
	}
}
