// TestOperatorForms holds this parser to the recorded verdicts, with no container.
func TestOperatorForms(t *testing.T) {
	for _, c := range operatorFormCases {
		t.Run(c.sql, func(t *testing.T) {
			_, err := Parse(c.sql)
			if got := err == nil; got != c.accept {
				t.Errorf("Parse(%q) accepts = %v, the engine answered %v (err: %v)", c.sql, got, c.accept, err)
			}
		})
	}
}
