package deparse_test

import "testing"

// The ML and AI objects read by their documented shape round-trip.
func TestDeparse_AiObjects(t *testing.T) {
	for _, sql := range []string{
		// CORTEX SEARCH SERVICE
		"CREATE OR REPLACE CORTEX SEARCH SERVICE db.s.svc ON body PRIMARY KEY (id, k) ATTRIBUTES region, kind WAREHOUSE = wh TARGET_LAG = '1 hour' REFRESH_MODE = INCREMENTAL AS SELECT body, region, kind FROM t",
		"CREATE CORTEX SEARCH SERVICE IF NOT EXISTS svc ON body ATTRIBUTES a WAREHOUSE = wh TARGET_LAG = '1 day' COMMENT = 'c' AS SELECT 1",
		"CREATE CORTEX SEARCH SERVICE svc TEXT INDEXES a, b VECTOR INDEXES v1, v2 ATTRIBUTES a WAREHOUSE = wh TARGET_LAG = '1 day' AS SELECT a, b FROM t",
		"CREATE CORTEX SEARCH SERVICE svc TEXT INDEXES a VECTOR INDEXES v1 (model = 'e5'), \"v 2\", v3 (query_model = 'q') ATTRIBUTES a WAREHOUSE = wh TARGET_LAG = '1 day' AS SELECT 1",
		"ALTER CORTEX SEARCH SERVICE IF EXISTS s SUSPEND INDEXING",
		"ALTER CORTEX SEARCH SERVICE s REFRESH",
		"ALTER CORTEX SEARCH SERVICE s SET TARGET_LAG = '1 hour' PRIMARY KEY = (a, b) REQUEST_LOGGING = TRUE",
		"ALTER CORTEX SEARCH SERVICE s UNSET PRIMARY KEY",
		"ALTER CORTEX SEARCH SERVICE s SET ATTRIBUTES (a, b)",
		"ALTER CORTEX SEARCH SERVICE s UNSET ATTRIBUTES",
		"ALTER CORTEX SEARCH SERVICE s ADD SCORING PROFILE IF NOT EXISTS p '{\"a\": 1}'",
		"ALTER CORTEX SEARCH SERVICE s DROP SCORING PROFILE IF EXISTS p",
		"ALTER CORTEX SEARCH SERVICE s SET TAG t = 'v'",
		"DROP CORTEX SEARCH SERVICE s",
		// AGENT, EXTERNAL AGENT
		"CREATE OR REPLACE AGENT a COPY GRANTS SECURE = TRUE COMMENT = 'c' FROM SPECIFICATION 'models: {}'",
		"CREATE AGENT IF NOT EXISTS a PROFILE = '{}' FROM SPECIFICATION 's'",
		"ALTER AGENT a SET COMMENT = 'c' PROFILE = '{}'",
		"CREATE OR REPLACE AGENT a COPY GRANTS COMMENT = 'c' FROM @my_stage/agents/my_agent",
		"ALTER AGENT a MODIFY LIVE VERSION SET SPECIFICATION = 's'",
		"ALTER AGENT a UNSET TAG t, u",
		"DROP AGENT IF EXISTS a",
		"CREATE OR REPLACE EXTERNAL AGENT e WITH VERSION v1 COMMENT = 'c'",
		"ALTER EXTERNAL AGENT IF EXISTS e ADD VERSION v2",
		"DROP EXTERNAL AGENT e",
		// MODEL, MODEL MONITOR
		"CREATE OR REPLACE MODEL m WITH VERSION v1 FROM MODEL db.s.src VERSION v0",
		"CREATE MODEL IF NOT EXISTS m WITH VERSION v1 FROM @db.s.stage/models/m",
		"ALTER MODEL m ADD VERSION v2 FROM @stage/path",
		"ALTER MODEL IF EXISTS m SET COMMENT = 'c' DEFAULT_VERSION = 'v1'",
		"ALTER MODEL m VERSION v1 SET ALIAS = best",
		"ALTER MODEL m VERSION v1 UNSET ALIAS",
		"ALTER MODEL m RENAME TO n",
		"ALTER MODEL m ADD VERSION v2 FROM MODEL src VERSION v0",
		"ALTER MODEL m DROP VERSION v1",
		"ALTER MODEL m MODIFY VERSION v1 SET COMMENT = 'c' METADATA = '{}'",
		"DROP MODEL m",
		"CREATE MODEL MONITOR mm WITH MODEL = db.s.m GATEWAY = g FUNCTION = 'predict' WAREHOUSE = wh REFRESH_INTERVAL = '1 day' AGGREGATION_WINDOW = '1 day' ID_COLUMNS = ('id')",
		"ALTER MODEL MONITOR IF EXISTS mm RESUME",
		"ALTER MODEL MONITOR mm SET BASELINE = 'b'",
		"ALTER MODEL MONITOR mm UNSET BASELINE, COMMENT",
		"ALTER MODEL MONITOR mm ADD SEGMENT_COLUMN = 'c'",
		"DROP MODEL MONITOR IF EXISTS mm",
		// EXPERIMENT
		"CREATE OR REPLACE EXPERIMENT e",
		"ALTER EXPERIMENT e ADD RUN r",
		"ALTER EXPERIMENT e COMMIT RUN r WITH STATUS = 'FAILED'",
		"ALTER EXPERIMENT e MODIFY RUN r SET STATUS = 'PAUSED'",
		"DROP EXPERIMENT e",
		// ONLINE FEATURE TABLE
		"CREATE OR REPLACE ONLINE FEATURE TABLE f PRIMARY KEY (id, k) TARGET_LAG = '1 minute' WAREHOUSE = wh REFRESH_MODE = AUTO COMMENT = 'c' WITH TAG (t = 'v') FROM src",
		"ALTER ONLINE FEATURE TABLE IF EXISTS f SUSPEND",
		"ALTER ONLINE FEATURE TABLE f SET TARGET_LAG = '1 day' WAREHOUSE = wh",
		"ALTER ONLINE FEATURE TABLE f RENAME TO g",
		"DROP ONLINE FEATURE TABLE IF EXISTS f",
	} {
		assertRoundTrip(t, sql)
	}
}
