package deparse_test

import "testing"

// TASK GRAPH (an ast.ObjectStmt) round-trips, commas and parenthesized groups
// included.
func TestDeparse_TaskGraph(t *testing.T) {
	for _, sql := range []string{
		"CREATE OR REPLACE TASK GRAPH db.s.g WITH TAG (t = 'v') WITH CONTACT (STEWARD = c1, SUPPORT = c2) SCHEDULE = 'USING CRON 0 * * * * UTC' ROOTS = (t_root) FINALIZER = db.s.fin OVERLAP_POLICY = NO_OVERLAP CONFIG = '{}' COMMENT = 'c' TASK_DEFAULTS (WAREHOUSE = wh, LOG_LEVEL = 'INFO') WHEN x > 1",
		"CREATE TASK GRAPH IF NOT EXISTS g TASK_AUTO_RETRY_ATTEMPTS = 2 SUSPEND_TASK_AFTER_NUM_FAILURES = 3",
		"CREATE OR ALTER TASK GRAPH g SCHEDULE = '5 MINUTES' ROOTS = (t) ERROR_INTEGRATION = i SUCCESS_INTEGRATION = j",
		"ALTER TASK GRAPH IF EXISTS g COMMIT",
		"ALTER TASK GRAPH g REVERT",
		"ALTER TASK GRAPH g RESUME",
		"ALTER TASK GRAPH g SUSPEND",
		"ALTER TASK GRAPH g MODIFY WHEN SYSTEM$STREAM_HAS_DATA('s')",
		"ALTER TASK GRAPH g REMOVE WHEN",
		"ALTER TASK GRAPH g SET SCHEDULE = '30 SECONDS', COMMENT = 'c'",
		"ALTER TASK GRAPH g UNSET CONFIG, FINALIZER",
		"ALTER TASK GRAPH g SET TASK_DEFAULTS (WAREHOUSE = new_wh, USER_TASK_TIMEOUT_MS = 100)",
		"ALTER TASK GRAPH g UNSET TASK_DEFAULTS (LOG_LEVEL, COMMENT)",
		"ALTER TASK GRAPH g SET TAG t = 'v', u = 'w'",
		"ALTER TASK GRAPH g UNSET TAG t, u",
		"ALTER TASK GRAPH g SET CONTACT STEWARD = c, SUPPORT = d",
		"ALTER TASK GRAPH g UNSET CONTACT STEWARD, SUPPORT",
		"DROP TASK GRAPH IF EXISTS db.s.g",
	} {
		assertRoundTrip(t, sql)
	}
}
