package deparse_test

import "testing"

// Native Apps objects (APPLICATION, APPLICATION PACKAGE, APPLICATION SERVICE,
// APPLICATION ROLE and the ALTER APPLICATION subcommands) round-trip.
func TestDeparse_Application(t *testing.T) {
	for _, sql := range []string{
		// APPLICATION
		"CREATE APPLICATION app FROM APPLICATION PACKAGE pkg USING VERSION v1 PATCH 2 DEBUG_MODE = TRUE COMMENT = 'c' WITH TAG (t = 'v') WITH FEATURE POLICY = db.s.fp",
		"CREATE APPLICATION app FROM APPLICATION PACKAGE pkg USING '@stage/v1'",
		"CREATE APPLICATION app FROM APPLICATION PACKAGE pkg USING RELEASE CHANNEL QA",
		"CREATE APPLICATION app FROM LISTING l USING RELEASE CHANNEL DEFAULT BACKGROUND_INSTALL = TRUE",
		"ALTER APPLICATION IF EXISTS a SET COMMENT = 's' DEBUG_MODE = TRUE",
		"ALTER APPLICATION a UNSET COMMENT, DEBUG_MODE",
		"ALTER APPLICATION a RENAME TO b",
		"ALTER APPLICATION a SET FEATURE POLICY db.s.p FORCE",
		"ALTER APPLICATION a UNSET MAINTENANCE POLICY",
		"ALTER APPLICATION a SET TAG t = 'v', u = 'w'",
		"ALTER APPLICATION a UNSET TAG t, u",
		"ALTER APPLICATION a SET SHARED TELEMETRY EVENTS ('SNOWFLAKE$ALL', 'SNOWFLAKE$TRACES')",
		"ALTER APPLICATION a UNSET REFERENCES ('r', 'alias')",
		"ALTER APPLICATION a UPGRADE",
		"ALTER APPLICATION a UPGRADE USING '@s/v2'",
		"ALTER APPLICATION a UPGRADE USING VERSION v2 PATCH 1",
		"ALTER APPLICATION a APPROVE SPECIFICATION spec SEQUENCE_NUMBER = 3",
		"ALTER APPLICATION a SET CONFIGURATION cfg VALUE = 'x'",
		"ALTER APPLICATION a UNSET CONFIGURATION cfg",
		"ALTER APPLICATION SET SPECIFICATION eai TYPE = EXTERNAL_ACCESS LABEL = 'l' DESCRIPTION = 'd' HOST_PORTS = ('h:443', 'i')",
		"ALTER APPLICATION DROP SPECIFICATION eai",
		"ALTER APPLICATION SET CONFIGURATION DEFINITION c TYPE = SECRET_AUTHORIZATION SECRET = db.sec LABEL = 'l' DESCRIPTION = 'd' APPLICATION_ROLES = (r1, r2)",
		"ALTER APPLICATION DROP CONFIGURATION DEFINITION c",
		"DROP APPLICATION IF EXISTS a CASCADE",
		// APPLICATION ROLE
		"CREATE OR REPLACE APPLICATION ROLE app_admin COMMENT = 'c'",
		"CREATE OR ALTER APPLICATION ROLE r",
		"ALTER APPLICATION ROLE IF EXISTS app.r RENAME TO app.s",
		"ALTER APPLICATION ROLE r UNSET COMMENT",
		"DROP APPLICATION ROLE app.r",
		// APPLICATION PACKAGE
		"CREATE APPLICATION PACKAGE IF NOT EXISTS pkg DATA_RETENTION_TIME_IN_DAYS = 1 DISTRIBUTION = EXTERNAL MULTIPLE_INSTANCES = TRUE WITH TAG (t = 'v')",
		"ALTER APPLICATION PACKAGE p UNSET DEFAULT_DDL_COLLATION, DISTRIBUTION",
		"ALTER APPLICATION PACKAGE p ADD VERSION v1 USING '@s/v1' LABEL = 'l'",
		"ALTER APPLICATION PACKAGE p ADD VERSION USING '@s/v1'",
		"ALTER APPLICATION PACKAGE p DROP VERSION v1 ASYNC",
		"ALTER APPLICATION PACKAGE p ADD PATCH 3 FOR VERSION v1 USING '@s/v1'",
		"ALTER APPLICATION PACKAGE p ADD PATCH FOR VERSION USING '@s/v1'",
		"ALTER APPLICATION PACKAGE p REGISTER VERSION v1 USING '@s/v1' LABEL = 'l'",
		"ALTER APPLICATION PACKAGE p DEREGISTER VERSION v1",
		"ALTER APPLICATION PACKAGE p MODIFY RELEASE CHANNEL QA ADD VERSION v1",
		"ALTER APPLICATION PACKAGE p MODIFY RELEASE CHANNEL QA ADD ACCOUNTS = (o.a, o.b)",
		"ALTER APPLICATION PACKAGE p MODIFY RELEASE CHANNEL QA SET ACCOUNTS = (o.a)",
		"ALTER APPLICATION PACKAGE p MODIFY RELEASE CHANNEL QA SET DEFAULT RELEASE DIRECTIVE VERSION = v1 PATCH = 0 UPGRADE_AFTER = 't'",
		"ALTER APPLICATION PACKAGE p MODIFY RELEASE CHANNEL QA UNSET RELEASE DIRECTIVE d",
		"ALTER APPLICATION PACKAGE p MODIFY RELEASE DIRECTIVE d ADD ACCOUNTS = (o.a) VERSION = v1 PATCH = 0 FORCE",
		"ALTER APPLICATION PACKAGE p SET RELEASE DIRECTIVE d ACCOUNTS = (o.a) VERSION = v1 PATCH = 0 FORCE",
		"DROP APPLICATION PACKAGE p",
		// APPLICATION SERVICE
		"CREATE APPLICATION SERVICE IF NOT EXISTS db.s.svc FROM ARTIFACT REPOSITORY db.s.repo PACKAGE pkg VERSION v1 EXTERNAL_ACCESS_INTEGRATIONS = (i1, i2) MIN_INSTANCES = 1",
		"CREATE OR ALTER APPLICATION SERVICE svc FROM ARTIFACT REPOSITORY r PACKAGE p SPECIFICATION = 's'",
		"ALTER APPLICATION SERVICE s UPGRADE TO VERSION v2",
		"ALTER APPLICATION SERVICE s SET AUTO_RESUME = TRUE COMMENT = 'c'",
		"DROP APPLICATION SERVICE db.s.x",
	} {
		assertRoundTrip(t, sql)
	}
}
