package deparse_test

import "testing"

// SERVICE, EXECUTE [ INFERENCE ] JOB SERVICE, IMAGE REPOSITORY and ARTIFACT
// REPOSITORY round-trip.
func TestDeparse_ServiceObjects(t *testing.T) {
	for _, sql := range []string{
		"CREATE SERVICE IF NOT EXISTS db.s.svc IN COMPUTE POOL p FROM SPECIFICATION 'spec: x' MIN_INSTANCES = 1 MAX_INSTANCES = 2 AUTO_RESUME = TRUE EXTERNAL_ACCESS_INTEGRATIONS = (a, \"B\") QUERY_WAREHOUSE = wh LOG_LEVEL = 'INFO' WITH TAG (t = 'v') COMMENT = 'c''s'",
		"CREATE SERVICE s IN COMPUTE POOL p FROM SPECIFICATION $$spec: {{ x }}$$",
		"CREATE SERVICE s IN COMPUTE POOL p FROM SPECIFICATION_FILE = 'a.yaml'",
		"CREATE SERVICE s IN COMPUTE POOL p FROM SPECIFICATION_TEMPLATE 't' USING (x => 'v', \"Mixed\" => 2, y => TRUE, z => -1)",
		"CREATE SERVICE s IN COMPUTE POOL p FROM SPECIFICATION_TEMPLATE_FILE = 't.yaml' USING (x => 1) COMMENT = 'c'",
		"ALTER SERVICE IF EXISTS s SUSPEND",
		"ALTER SERVICE s RESUME",
		"ALTER SERVICE s FROM SPECIFICATION 'x'",
		"ALTER SERVICE s FROM SPECIFICATION_TEMPLATE_FILE = 't' USING (a => 'b', c => d)",
		"ALTER SERVICE s SET MIN_INSTANCES = 1 COMMENT = 'c'",
		"ALTER SERVICE s SET TAG t = 'v', u = 'w'",
		"ALTER SERVICE s UNSET MIN_INSTANCES, COMMENT",
		"DROP SERVICE IF EXISTS s",
		"EXECUTE JOB SERVICE IN COMPUTE POOL p FROM SPECIFICATION 'x' NAME = db.s.job ASYNC = TRUE REPLICAS = 2 EXTERNAL_ACCESS_INTEGRATIONS = (e)",
		"EXECUTE JOB SERVICE IN COMPUTE POOL p FROM SPECIFICATION_TEMPLATE 'x' USING (a => 1)",
		"EXECUTE JOB SERVICE IN COMPUTE POOL p NAME = j ASYNC = TRUE FROM SPECIFICATION_TEMPLATE 'x' USING (tag_name => 'latest', Port => 8080) REPLICAS = 2",
		"EXECUTE INFERENCE JOB SERVICE IN COMPUTE POOL p WITH SPECIFICATION 's' FROM (SELECT a FROM t WHERE b > 1) MODEL = db.s.m VERSION = v1 FUNCTION = 'predict' REPLICAS = 1",
		"CREATE OR REPLACE IMAGE REPOSITORY r ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE') COMMENT = 'c' WITH TAG (t = 'v')",
		"CREATE IMAGE REPOSITORY IF NOT EXISTS db.s.r",
		"ALTER IMAGE REPOSITORY IF EXISTS r SET COMMENT = 'c'",
		"ALTER IMAGE REPOSITORY r SET TAG t = 'v'",
		"ALTER IMAGE REPOSITORY r UNSET TAG t, u",
		"ALTER IMAGE REPOSITORY r UNSET COMMENT",
		"DROP IMAGE REPOSITORY r",
		"CREATE ARTIFACT REPOSITORY r TYPE = PYPI API_INTEGRATION = 'i' INDEX_URL = 'u' AUTHENTICATION_SECRET = db.s.sec PACKAGE_RETENTION = ON_OBJECT_CREATION COMMENT = 'c'",
		"CREATE OR REPLACE ARTIFACT REPOSITORY r TYPE = APPLICATION",
		"ALTER ARTIFACT REPOSITORY r SET INDEX_URL = 'u' AUTHENTICATION_SECRET = s",
		"ALTER ARTIFACT REPOSITORY r UNSET PACKAGE_RETENTION",
		"ALTER ARTIFACT REPOSITORY r UNSET TAG t",
		"DROP ARTIFACT REPOSITORY IF EXISTS r",
	} {
		assertRoundTrip(t, sql)
	}
}
