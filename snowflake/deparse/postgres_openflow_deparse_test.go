package deparse_test

import "testing"

// POSTGRES INSTANCE and the Openflow objects (ast.ObjectStmt) round-trip.
func TestDeparse_PostgresInstanceOpenflow(t *testing.T) {
	for _, sql := range []string{
		"CREATE POSTGRES INSTANCE IF NOT EXISTS pg COMPUTE_FAMILY = 'STANDARD_M' STORAGE_SIZE_GB = 10 AUTHENTICATION_AUTHORITY = EXTERNAL_OAUTH " +
			"AUTHENTICATION_PROPERTIES = (ISSUER = 'i', AUDIENCE = 'a', ACCEPTED_TOKENS = ((MAPPING_CLAIM = 'm', SCOPES_CLAIM = 's', SCOPES = ('x', 'y')), " +
			"(MAPPING_CLAIM = 'm', SCOPES_CLAIM = 's', SCOPES = 'z'))) POSTGRES_VERSION = 17 HIGH_AVAILABILITY = TRUE COMMENT = 'c''s' WITH TAG (db.s.t = 'v')",
		"CREATE POSTGRES INSTANCE a FORK b",
		"CREATE POSTGRES INSTANCE a FORK b AT (TIMESTAMP => '2025-01-01') COMMENT = 'c'",
		"CREATE POSTGRES INSTANCE a FORK b BEFORE (OFFSET => -60) STORAGE_SIZE_GB = 10 TAG (t = 'v')",
		"CREATE POSTGRES INSTANCE a FORK b AT (TIMESTAMP => '2025-01-15 12:00:00'::TIMESTAMP_NTZ)",
		"CREATE POSTGRES INSTANCE a FORK b BEFORE (OFFSET => -30 * 60)",
		"ALTER POSTGRES INSTANCE IF EXISTS a SUSPEND",
		"ALTER POSTGRES INSTANCE a RESUME",
		"ALTER POSTGRES INSTANCE a RENAME TO b",
		"ALTER POSTGRES INSTANCE a RESET ACCESS FOR 'snowflake_admin'",
		"ALTER POSTGRES INSTANCE a SET NETWORK_POLICY = 'np' MAINTENANCE_WINDOW_START = 3",
		"ALTER POSTGRES INSTANCE a SET POSTGRES_VERSION = 18 APPLY IMMEDIATELY",
		"ALTER POSTGRES INSTANCE a SET POSTGRES_SETTINGS = '{}' APPLY ON '2025-01-01'",
		"ALTER POSTGRES INSTANCE a SET APPLY IMMEDIATELY",
		"ALTER POSTGRES INSTANCE a UNSET COMMENT, NETWORK_POLICY",
		"ALTER POSTGRES INSTANCE a SET TAG t = 'v', u = 'w'",
		"ALTER POSTGRES INSTANCE a UNSET TAG t, u",
		"DROP POSTGRES INSTANCE IF EXISTS a",

		"CREATE OPENFLOW DEPLOYMENT IF NOT EXISTS d DEPLOYMENT_TYPE = BYOC VPC_TYPE = 'MANAGED' USE_PRIVATE_LINK = FALSE EVENT_TABLE = NONE",
		"CREATE OPENFLOW DEPLOYMENT d",
		"ALTER OPENFLOW DEPLOYMENT d SET DISPLAY_NAME = 'n' EVENT_TABLE = 'db.s.t'",
		"ALTER OPENFLOW DEPLOYMENT d UNSET DISPLAY_NAME, EVENT_TABLE",
		"ALTER OPENFLOW DEPLOYMENT d RENAME TO e",
		"ALTER OPENFLOW DEPLOYMENT IF EXISTS d UPGRADE",
		"ALTER OPENFLOW DEPLOYMENT d TERMINATE",
		"DROP OPENFLOW DEPLOYMENT IF EXISTS d",

		"CREATE OPENFLOW RUNTIME IF NOT EXISTS db.sch.r IN DEPLOYMENT d NODE_TYPE = SMALL NODE_TYPE_TIER = 'S1' MIN_NODES = 1 MAX_NODES = 2 " +
			"EXECUTE_AS_ROLE = r1 EXTERNAL_ACCESS_INTEGRATIONS = (e1, e2) DISPLAY_NAME = 'n' COMMENT = 'c'",
		"ALTER OPENFLOW RUNTIME r SET MIN_NODES = 1 NODE_TYPE_TIER = 'M4' EXECUTE_AS_ROLE = r2",
		"ALTER OPENFLOW RUNTIME r UNSET EXTERNAL_ACCESS_INTEGRATIONS",
		"ALTER OPENFLOW RUNTIME r ADD EXTERNAL_ACCESS_INTEGRATIONS = (e1, e2)",
		"ALTER OPENFLOW RUNTIME r REMOVE EXTERNAL_ACCESS_INTEGRATIONS = (e1)",
		"ALTER OPENFLOW RUNTIME r RENAME TO s",
		"ALTER OPENFLOW RUNTIME r UPGRADE FORCE",
		"ALTER OPENFLOW RUNTIME r SUSPEND",
		"ALTER OPENFLOW RUNTIME r RESUME RECOVERY",
		"ALTER OPENFLOW RUNTIME r RESTART",
		"ALTER OPENFLOW RUNTIME IF EXISTS r TERMINATE CASCADE",
		"DROP OPENFLOW RUNTIME r CASCADE",

		"ALTER OPENFLOW DATA PLANE INTEGRATION i SET EVENT_TABLE = 'db.s.t'",
	} {
		assertRoundTrip(t, sql)
	}
}
