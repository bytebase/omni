package deparse_test

import "testing"

// Backup, snapshot, storage lifecycle and data movement objects (read by
// their documented shape in snowflake/parser/data_protection.go) round-trip.
func TestDeparse_DataProtectionObjects(t *testing.T) {
	for _, sql := range []string{
		// BACKUP SET
		"CREATE BACKUP SET IF NOT EXISTS s FOR DYNAMIC ICEBERG TABLE db.sc.t WITH TAG (db.sc.tg = 'v') WITH BACKUP POLICY p COMMENT = 'c''s'",
		"CREATE OR REPLACE BACKUP SET s FOR SCHEMA db.sc",
		"CREATE OR ALTER BACKUP SET s FOR DATABASE db WITH BACKUP POLICY p",
		"ALTER BACKUP SET s ADD BACKUP",
		"ALTER BACKUP SET s APPLY BACKUP POLICY p FORCE",
		"ALTER BACKUP SET s SUSPEND BACKUP CREATION POLICY",
		"ALTER BACKUP SET s RESUME BACKUP POLICY",
		"ALTER BACKUP SET s DELETE BACKUP IDENTIFIER 'id'",
		"ALTER BACKUP SET s MODIFY BACKUP IDENTIFIER 'id' ADD LEGAL HOLD",
		"ALTER BACKUP SET s MODIFY BACKUP IDENTIFIER 'id' SET COMMENT = 'c'",
		"ALTER BACKUP SET s MODIFY BACKUP IDENTIFIER 'id' UNSET COMMENT",
		"ALTER BACKUP SET s RENAME TO t",
		"ALTER BACKUP SET s SET TAG a = 's', b = 's'",
		"ALTER BACKUP SET s UNSET TAG a, b",
		"DROP BACKUP SET s",
		// BACKUP POLICY
		"CREATE BACKUP POLICY p WITH TAG (a = 's') WITH RETENTION LOCK SCHEDULE = '60 MINUTE' EXPIRE_AFTER_DAYS = 7 COMMENT = 'c'",
		"CREATE OR ALTER BACKUP POLICY p SCHEDULE = 'USING CRON 0 0 * * * UTC'",
		"ALTER BACKUP POLICY p SET COMMENT = 'c' EXPIRE_AFTER_DAYS = 1",
		"ALTER BACKUP POLICY p UNSET SCHEDULE",
		"DROP BACKUP POLICY p",
		// SNAPSHOT SET and SNAPSHOT POLICY
		"CREATE SNAPSHOT SET s FOR DYNAMIC TABLE t WITH SNAPSHOT POLICY p COMMENT = 'c'",
		"ALTER SNAPSHOT SET s SUSPEND SNAPSHOT EXPIRATION POLICY",
		"ALTER SNAPSHOT SET s MODIFY SNAPSHOT IDENTIFIER 'id' REMOVE LEGAL HOLD",
		"DROP SNAPSHOT SET s",
		"CREATE OR REPLACE SNAPSHOT POLICY p WITH RETENTION LOCK",
		"ALTER SNAPSHOT POLICY p RENAME TO q",
		"DROP SNAPSHOT POLICY p",
		// SNAPSHOT
		"CREATE SNAPSHOT IF NOT EXISTS s FROM SERVICE db.sc.svc VOLUME \"data\" INSTANCE 0 COMMENT = 'c' WITH TAG (a = 's')",
		"ALTER SNAPSHOT IF EXISTS s SET COMMENT = 'c'",
		"DROP SNAPSHOT IF EXISTS s",
		// STORAGE LIFECYCLE POLICY
		"ALTER STORAGE LIFECYCLE POLICY IF EXISTS p SET ARCHIVE_TIER = COOL",
		"ALTER STORAGE LIFECYCLE POLICY p SET ARCHIVE_FOR_DAYS = 30",
		"ALTER STORAGE LIFECYCLE POLICY p UNSET ARCHIVE_FOR_DAYS",
		"DROP STORAGE LIFECYCLE POLICY IF EXISTS p",
		// DATA MOVEMENT POLICY and RULE
		"CREATE DATA MOVEMENT POLICY IF NOT EXISTS p ENFORCE_RULES = (r1, r2) ALERT_RULES = (r3) COMMENT = 'c'",
		"ALTER DATA MOVEMENT POLICY p ADD ENFORCE_RULES = (r1, r2)",
		"ALTER DATA MOVEMENT POLICY p REMOVE ALERT_RULES = (r1)",
		"ALTER DATA MOVEMENT POLICY IF EXISTS p SET ALERT_RULES = (r1)",
		"ALTER DATA MOVEMENT POLICY p UNSET COMMENT",
		"DROP DATA MOVEMENT POLICY p",
		"ALTER DATA MOVEMENT RULE r RENAME TO q",
		"DROP DATA MOVEMENT RULE IF EXISTS r",
	} {
		assertRoundTrip(t, sql)
	}
}
