package deparse_test

import "testing"

// STORAGE LIFECYCLE POLICY's and DATA MOVEMENT RULE's bodies, and PROVISIONED
// THROUGHPUT, round-trip.
func TestDeparse_ObjectBodies(t *testing.T) {
	for _, sql := range []string{
		"CREATE STORAGE LIFECYCLE POLICY IF NOT EXISTS p AS (event_ts TIMESTAMP, id NUMBER) RETURNS BOOLEAN -> event_ts < CURRENT_TIMESTAMP() AND id > 1 ARCHIVE_TIER = COOL ARCHIVE_FOR_DAYS = 180 COMMENT = 'c' WITH TAG (t = 'v')",
		"CREATE OR REPLACE STORAGE LIFECYCLE POLICY db.s.p AS (a INT) RETURNS BOOLEAN -> a = 1",
		"ALTER STORAGE LIFECYCLE POLICY p SET BODY -> a > 1",
		"CREATE OR REPLACE DATA MOVEMENT RULE r TYPE = 'COPY_INTO_EXTERNAL_STAGE' MAX_ROWS AS () RETURNS INTEGER -> (CASE WHEN x = 1 THEN NULL ELSE 0 END) COMMENT = 'c'",
		"CREATE DATA MOVEMENT RULE IF NOT EXISTS r TYPE = 'x' MAX_ROWS AS () RETURNS INTEGER -> (1000)",
		"ALTER DATA MOVEMENT RULE IF EXISTS r SET MAX_ROWS AS () RETURNS INTEGER -> (500)",
		"CREATE OR REPLACE PROVISIONED THROUGHPUT pt CLOUD_PROVIDER = 'aws' MODEL = 'llama3.1-8B' PTUS = 64 TERM_START = '2025-04-15' TERM_END = '2025-05-15'",
	} {
		assertRoundTrip(t, sql)
	}
}
