// Catalog, external access and notification integrations round-trip.
func TestDeparse_Integration(t *testing.T) {
	for _, sql := range []string{
		"CREATE OR REPLACE CATALOG INTEGRATION c CATALOG_SOURCE = ICEBERG_REST TABLE_FORMAT = ICEBERG CATALOG_NAMESPACE = 'ns' " +
			"REST_CONFIG = (CATALOG_URI = 'https://x' CATALOG_API_TYPE = PUBLIC) " +
			"REST_AUTHENTICATION = (TYPE = OAUTH OAUTH_CLIENT_ID = 'id' OAUTH_CLIENT_SECRET = 's' OAUTH_ALLOWED_SCOPES = ('a', 'b')) " +
			"ENABLED = TRUE REFRESH_INTERVAL_SECONDS = 30 COMMENT = 'c''s'",
		"CREATE CATALOG INTEGRATION IF NOT EXISTS \"My Cat\" CATALOG_SOURCE = OBJECT_STORE TABLE_FORMAT = DELTA ENABLED = FALSE",
		"CREATE CATALOG INTEGRATION c CATALOG_SOURCE = POLARIS TABLE_FORMAT = ICEBERG REST_CONFIG = (CATALOG_URI = 'u' CATALOG_NAME = 'n') " +
			"REST_AUTHENTICATION = (TYPE = OAUTH OAUTH_GRANT_TYPE = TOKEN_EXCHANGE OAUTH_ALLOWED_SCOPES = ('s')) " +
			"DEFAULT_STORAGE_CONFIG = (USE_PRIVATELINK_ENDPOINT = TRUE) ENABLED = TRUE",
		"ALTER CATALOG INTEGRATION IF EXISTS c SET REST_AUTHENTICATION = (OAUTH_CLIENT_SECRET = 's') REFRESH_INTERVAL_SECONDS = 60",
		"CREATE OR REPLACE EXTERNAL ACCESS INTEGRATION e ALLOWED_NETWORK_RULES = (r1, db.s.r2, \"Rule\") " +
			"ALLOWED_API_AUTHENTICATION_INTEGRATIONS = none ALLOWED_AUTHENTICATION_SECRETS = (s1) ENABLED = TRUE COMMENT = 'c'",
		"ALTER EXTERNAL ACCESS INTEGRATION e SET ALLOWED_NETWORK_RULES = (r) ENABLED = FALSE TAG t = 's', db.s.u = 's'",
		"ALTER EXTERNAL ACCESS INTEGRATION e SET TAG t = 's'",
		"ALTER EXTERNAL ACCESS INTEGRATION IF EXISTS e UNSET ALLOWED_NETWORK_RULES, COMMENT, TAG t",
		"ALTER EXTERNAL ACCESS INTEGRATION e UNSET TAG t, TAG u",
		"CREATE NOTIFICATION INTEGRATION n ENABLED = TRUE TYPE = MULTI_QUEUE DIRECTION = INBOUND " +
			"QUEUES = ((NAME = 'a' NOTIFICATION_PROVIDER = AWS_SNS AWS_SNS_TOPIC_ARN = 't'), " +
			"(NAME = 'b' NOTIFICATION_PROVIDER = GCP_PUBSUB GCP_PUBSUB_SUBSCRIPTION_NAME = 's')) ACTIVE = 'a'",
		"CREATE NOTIFICATION INTEGRATION n TYPE = WEBHOOK ENABLED = TRUE WEBHOOK_URL = 'u' WEBHOOK_SECRET = db.s.sec " +
			"WEBHOOK_HEADERS = ('Content-Type' = 'application/json', 'X' = 'y')",
		"CREATE NOTIFICATION INTEGRATION n TYPE = WEBHOOK ENABLED = TRUE WEBHOOK_URL = 'u' " +
			"WEBHOOK_HEADERS = ($$Content-Type$$ = 'application/json', 'it''s' = 'y')",
		"CREATE NOTIFICATION INTEGRATION n TYPE = EMAIL ENABLED = TRUE ALLOWED_RECIPIENTS = ('a@b.c', 'd@e.f')",
		"ALTER INTEGRATION i REFRESH",
		"ALTER SECURITY INTEGRATION IF EXISTS i REFRESH OAUTH_CLIENT_SECRET_2",
		"ALTER INTEGRATION i REFRESH SAML2_SNOWFLAKE_PRIVATE_KEY METADATA_URL",
		"DROP CATALOG INTEGRATION IF EXISTS c",
		"DROP EXTERNAL ACCESS INTEGRATION e",
	} {
		assertRoundTrip(t, sql)
	}
}

// The integration kinds and actions whose options stay open-ended are not
// written.
func TestDeparse_IntegrationUnsupported(t *testing.T) {
	for _, sql := range []string{
		"CREATE STORAGE INTEGRATION s TYPE = EXTERNAL_STAGE STORAGE_PROVIDER = 'S3' ENABLED = TRUE STORAGE_ALLOWED_LOCATIONS = ('s3://b/')",
		"ALTER NOTIFICATION INTEGRATION n SET ENABLED = FALSE",
	} {
		f, err := parser.Parse(sql)
		if err != nil {
			t.Fatalf("parse %q: %v", sql, err)
		}
		if out, err := deparse.DeparseFile(f); err == nil {
			t.Errorf("deparse %q = %q, want an error", sql, out)
		}
	}
}
