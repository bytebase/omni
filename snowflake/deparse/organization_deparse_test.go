package deparse_test

import "testing"

// Organization objects round-trip.
func TestDeparse_OrganizationObjects(t *testing.T) {
	for _, sql := range []string{
		"CREATE ORGANIZATION USER IF NOT EXISTS u EMAIL = 'e' LOGIN_NAME = 'l' TYPE = PERSON COMMENT = 'c'",
		"CREATE ORGANIZATION USER u EMAIL = 'a@x.com' EMAIL = 'b@x.com'",
		"ALTER ORGANIZATION USER IF EXISTS u SET DISPLAY_NAME = 'd' TYPE = SERVICE",
		"ALTER ORGANIZATION USER u SET EMAIL = 'a@x.com' EMAIL = 'b@x.com'",
		"ALTER ORGANIZATION USER u UNSET EMAIL, TYPE",
		"DROP ORGANIZATION USER IF EXISTS u",
		"CREATE ORGANIZATION USER GROUP g IS_GRANTABLE = TRUE",
		"ALTER ORGANIZATION USER GROUP IF EXISTS g ADD ORGANIZATION USERS a, b",
		"ALTER ORGANIZATION USER GROUP g REMOVE ORGANIZATION USERS a",
		"ALTER ORGANIZATION USER GROUP g SET VISIBILITY = ALL",
		"ALTER ORGANIZATION USER GROUP g SET VISIBILITY = ACCOUNTS a, b",
		"ALTER ORGANIZATION USER GROUP g SET VISIBILITY = REGION GROUPS 'x', 'y'",
		"ALTER ORGANIZATION USER GROUP g SET IS_GRANTABLE = FALSE",
		"DROP ORGANIZATION USER GROUP g",
		"CREATE ORGANIZATION ACCOUNT a ADMIN_NAME = 'n' ADMIN_PASSWORD = 'p' FIRST_NAME = 'f' EMAIL = 'e' MUST_CHANGE_PASSWORD = TRUE EDITION = ENTERPRISE REGION_GROUP = public REGION = aws_us_west_2 COMMENT = 'c'",
		"ALTER ORGANIZATION ACCOUNT SET RESOURCE_MONITOR = m",
		"ALTER ORGANIZATION ACCOUNT SET TIMEZONE = 'UTC', AUTOCOMMIT = TRUE",
		"CREATE ORGANIZATION ACCOUNT a ADMIN_NAME = admin ADMIN_RSA_PUBLIC_KEY = 'k' EMAIL = 'e' EDITION = ENTERPRISE",
		"ALTER ORGANIZATION ACCOUNT SET PASSWORD POLICY db.s.p",
		"ALTER ORGANIZATION ACCOUNT UNSET SESSION POLICY",
		"ALTER ORGANIZATION ACCOUNT UNSET PASSWORD, TIMEZONE",
		"ALTER ORGANIZATION ACCOUNT SET TAG t = 'v', u = 'w'",
		"ALTER ORGANIZATION ACCOUNT UNSET TAG t, u",
		"CREATE ORGANIZATION PROFILE IF NOT EXISTS p AS 'm' VERSION v PUBLISH = FALSE",
		"CREATE ORGANIZATION PROFILE p FROM @db.s.st/dir VERSION v",
		"ALTER ORGANIZATION PROFILE IF EXISTS p AS 'm'",
		"ALTER ORGANIZATION PROFILE p RENAME TO q",
		"ALTER ORGANIZATION PROFILE p PUBLISH",
		"ALTER ORGANIZATION PROFILE p ADD VERSION FROM @st",
		"ALTER ORGANIZATION PROFILE p ADD VERSION IF NOT EXISTS v FROM @st/a",
		"ALTER ORGANIZATION PROFILE p ADD LIVE VERSION v FROM LAST",
		"CREATE ORGANIZATION PROFILE p FROM @repo/branches/profile-config/ PUBLISH = TRUE",
		"ALTER ORGANIZATION PROFILE p COMMIT",
		"DROP ORGANIZATION PROFILE p",
		"ALTER ORGANIZATION SET DEFAULT_TENANT_TYPE = EXTERNAL",
		"ALTER ORGANIZATION SET DOMAIN_NAMES = ('a.com', 'b.com')",
		"ALTER ORGANIZATION UNSET DOMAIN_NAMES",
		"ALTER ORGANIZATION SET EVENT ROUTING TABLE db.s.t FOR ALL APPLICATION LISTINGS",
		"ALTER ORGANIZATION UNSET EVENT ROUTING TABLE FOR ALL APPLICATION LISTINGS",
	} {
		assertRoundTrip(t, sql)
	}
}
