package deparse_test

import "testing"

// Listings, external consumers, contacts, multi-party approval policies and
// restricted session scopes round-trip.
func TestDeparse_SharingObjects(t *testing.T) {
	for _, sql := range []string{
		"CREATE EXTERNAL LISTING IF NOT EXISTS l SHARE s AS 'm' PUBLISH = FALSE REVIEW = TRUE COMMENT = 'c'",
		"CREATE EXTERNAL LISTING l APPLICATION PACKAGE p FROM '@db.s.st/dir' REVIEW = FALSE",
		"CREATE ORGANIZATION LISTING l SHARE s AS 'm' PUBLISH = TRUE",
		"ALTER LISTING l",
		"ALTER LISTING IF EXISTS l PUBLISH",
		"ALTER LISTING l UNPUBLISH",
		"ALTER LISTING l AS 'm' PUBLISH = TRUE COMMENT = 'c'",
		"ALTER LISTING l ADD VERSION v3 FROM @db.public.st/manifests COMMENT = 'c'",
		"ALTER LISTING l ADD VERSION IF NOT EXISTS v3 FROM @st",
		"ALTER LISTING l ADD VERSION FROM @st",
		"ALTER LISTING l ADD VERSION v FROM @repo/branches/my-branch/ COMMENT = 'c'",
		"ALTER LISTING IF EXISTS l ADD TARGETS 'm'",
		"ALTER LISTING l REMOVE TARGETS 'm'",
		"ALTER LISTING l RENAME TO m",
		"ALTER LISTING l SET COMMENT = 'c'",
		"DROP LISTING l",
		"CREATE OR REPLACE EXTERNAL CONSUMER c REGION = 'r' COMMENT = 'x' EMAIL = 'e'",
		"CREATE EXTERNAL CONSUMER IF NOT EXISTS db.s.c",
		"ALTER EXTERNAL CONSUMER IF EXISTS c SET EMAIL = 'e' COMMENT = 'x'",
		"ALTER EXTERNAL CONSUMER c UNSET COMMENT, EMAIL",
		"ALTER EXTERNAL CONSUMER c RENAME TO d",
		"ALTER EXTERNAL CONSUMER c ADD PAT IF NOT EXISTS t DAYS_TO_EXPIRY = 30 COMMENT = 'x'",
		"ALTER EXTERNAL CONSUMER c ADD PROGRAMMATIC ACCESS TOKEN t",
		"ALTER EXTERNAL CONSUMER c MODIFY PAT IF EXISTS t SET DAYS_TO_EXPIRY = 1 COMMENT = 'x' UNSET COMMENT",
		"ALTER EXTERNAL CONSUMER IF EXISTS c REMOVE PAT IF EXISTS t",
		"ALTER EXTERNAL CONSUMER c ROTATE PROGRAMMATIC ACCESS TOKEN t EXPIRE_ROTATED_TOKEN_AFTER_HOURS = 2",
		"DROP EXTERNAL CONSUMER IF EXISTS c",
		"CREATE OR REPLACE CONTACT c USERS = ('a', 'b') COMMENT = 'x'",
		"CREATE CONTACT IF NOT EXISTS db.s.c URL = 'u'",
		"ALTER CONTACT IF EXISTS c SET EMAIL_DISTRIBUTION_LIST = 'e' COMMENT = 'x'",
		"ALTER CONTACT c RENAME TO d",
		"DROP CONTACT c",
		"CREATE OR REPLACE MULTI PARTY APPROVAL POLICY p AS 'b'",
		"ALTER MULTI PARTY APPROVAL POLICY p RENAME TO q",
		"DROP MULTI PARTY APPROVAL POLICY IF EXISTS p",
		"CREATE RESTRICTED SESSION SCOPE IF NOT EXISTS r COMMENT = 'x' AS 'd'",
		"CREATE OR ALTER RSS r AS 'd'",
		"ALTER RSS IF EXISTS r ADD AS 'd'",
		"ALTER RESTRICTED SESSION SCOPE r REMOVE AS 'd'",
		"ALTER RSS r UNSET COMMENT",
		"DROP RSS IF EXISTS r",
	} {
		assertRoundTrip(t, sql)
	}
}
