package deparse_test

import "testing"

// DBT PROJECT, DCM PROJECT and CODE BUNDLE, and their EXECUTE statements,
// round-trip.
func TestDeparse_Projects(t *testing.T) {
	for _, sql := range []string{
		"CREATE DBT PROJECT IF NOT EXISTS db.sch.p FROM '@db.sch.git/branches/main' DBT_VERSION = '1.9.4' DEFAULT_TARGET = 'prod' DEFAULT_ENVIRONMENT = 'dev' EXTERNAL_ACCESS_INTEGRATIONS = (i1, \"i2\") AUTO_COMPILE = FALSE DEFAULT_WRITEBACK = TRUE COMMENT = 'it''s'",
		"CREATE OR REPLACE DBT PROJECT p FROM 's'",
		"ALTER DBT PROJECT IF EXISTS p RENAME TO db.sch.q",
		"ALTER DBT PROJECT p DEPLOY FROM '@s/p'",
		"ALTER DBT PROJECT p SET DBT_VERSION = '1.9.4' EXTERNAL_ACCESS_INTEGRATIONS = (i)",
		"ALTER DBT PROJECT p UNSET DBT_VERSION, COMMENT",
		"DROP DBT PROJECT IF EXISTS db.sch.p",
		"CREATE OR REPLACE DCM PROJECT p LOG_LEVEL = WARN COMMENT = 'c'",
		"ALTER DCM PROJECT IF EXISTS p SET LOG_LEVEL = TRACE",
		"ALTER DCM PROJECT p UNSET LOG_LEVEL, COMMENT",
		"ALTER DCM PROJECT p DROP DEPLOYMENT DEPLOYMENT$1",
		"DROP DCM PROJECT p",
		"CREATE CODE BUNDLE IF NOT EXISTS db.sch.b FROM '@db.sch.st' COMMENT = 'c'",
		"EXECUTE DBT PROJECT IF EXISTS db.sch.p ARGS = 'run' EXTERNAL_ACCESS_INTEGRATIONS = (i) ENV_VARS = ('K' = 'v', 'L' = 'w') IMPORTS = ('@st/t/' AS 'state', SYSTEM$DBT_GET_LAST_RUN_TARGET('db.sch.p') AS 'prev', '@s/x') WRITEBACK = TRUE",
		"EXECUTE DBT PROJECT",
		"EXECUTE DBT PROJECT IF EXISTS FROM WORKSPACE \"USER$\".PUBLIC.\"ws\" PROJECT_ROOT = 'sub'",
		"EXECUTE DCM PROJECT p PLAN DELTA USING CONFIGURATION PROD (desc => 'x', regions => ['a', 'b']) ENVIRONMENT (:env) FROM '@s/defs' OUTPUT_PATH '@s/out'",
		"EXECUTE DCM PROJECT p PLAN USING (a => 1, b => :v, c => :\"V\") FROM 's'",
		"EXECUTE DCM PROJECT p DEPLOY AS \"my update\" FROM DEPLOYMENT LAST",
		"EXECUTE DCM PROJECT p DEPLOY ENVIRONMENT ($env) FROM 's'",
		"EXECUTE DCM PROJECT p TEST ALL",
		"EXECUTE DCM PROJECT p PREVIEW db.sch.t USING CONFIGURATION c FROM 's' LIMIT 10",
		"EXECUTE DCM PROJECT p PURGE AS \"cleanup\"",
		"EXECUTE CODE BUNDLE db.sch.b ENTRYPOINT = 'main.py' ARGUMENTS = ('--t', :src) WITH SPECIFICATION $$\nbundle:\n  type: custom\n$$",
	} {
		assertRoundTrip(t, sql)
	}
}
