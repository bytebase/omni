package main

import (
	"fmt"
	"go/format"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// A refusal is a message GoogleSQL's grammar writes when one of its actions
// refuses input the rules derive, as a pattern of the message, with the line
// of googlesql.tm the action is on.
type refusal struct {
	line    int
	pattern string
}

// refusalCalls are the calls googlesql.tm's actions make to refuse input.
var refusalCalls = regexp.MustCompile(`\b(MakeSyntaxError|MakeSqlErrorAt|MakeSqlError|SetOverrideError)\s*\(`)

// refusals returns a pattern for each message googlesql.tm's actions write
// when they refuse input, in the order of the file, each pattern once. A
// message is the action's string literals; a part the action computes
// (absl::StrCat of a name, a %s of absl::StrFormat) matches any text. A
// message that starts "Syntax error:" gets no pattern, since that prefix
// marks the parser's error wherever it stands, and neither does an action whose message
// is computed whole, as one that passes on another function's error.
func refusals(tm string) ([]refusal, error) {
	var out []refusal
	seen := map[string]bool{}
	for _, m := range refusalCalls.FindAllStringSubmatchIndex(tm, -1) {
		args, err := callArgs(tm, m[1])
		if err != nil {
			return nil, fmt.Errorf("googlesql.tm:%d: %v", strings.Count(tm[:m[0]], "\n")+1, err)
		}
		pattern, ok := messagePattern(args)
		if !ok || seen[pattern] {
			continue
		}
		seen[pattern] = true
		out = append(out, refusal{line: strings.Count(tm[:m[0]], "\n") + 1, pattern: pattern})
	}
	return out, nil
}

// callArgs returns the text of a call's arguments, from just after its
// opening parenthesis at i to just before the one that closes it.
func callArgs(src string, i int) (string, error) {
	depth := 1
	for j := i; j < len(src); j++ {
		switch {
		case strings.HasPrefix(src[j:], `R"(`):
			end := strings.Index(src[j+3:], `)"`)
			if end < 0 {
				return "", fmt.Errorf("unterminated raw string")
			}
			j += 3 + end + 1
		case src[j] == '"' || src[j] == '\'':
			k := j + 1
			for k < len(src) && src[k] != src[j] {
				if src[k] == '\\' {
					k++
				}
				k++
			}
			j = k
		case src[j] == '(':
			depth++
		case src[j] == ')':
			depth--
			if depth == 0 {
				return src[i:j], nil
			}
		}
	}
	return "", fmt.Errorf("unterminated call")
}

// cppString matches a C++ string literal, raw or not.
var cppString = regexp.MustCompile(`R"\(((?s:.*?))\)"|"((?:\\.|[^"\\])*)"`)

// glue is the text between two parts of a message that adds nothing to it:
// space, the commas of absl::StrCat's arguments, and the call itself.
var glue = regexp.MustCompile(`^(?:\s|,|\(|\)|absl::StrCat|absl::StrFormat|std::string)*$`)

// messagePattern returns the pattern of the message a refusing call writes:
// its literals in order, any text where code computes a part, anchored at
// the start, and ending where the emulator's location or the message ends.
func messagePattern(args string) (string, bool) {
	// The first argument is where the error is, never its text.
	if i := topLevelComma(args); i >= 0 && !strings.HasPrefix(strings.TrimSpace(args), `"`) {
		args = args[i+1:]
	}
	locs := cppString.FindAllStringSubmatchIndex(args, -1)
	if len(locs) == 0 {
		return "", false
	}
	var b strings.Builder
	b.WriteString("^")
	prev := 0
	for _, l := range locs {
		if !glue.MatchString(args[prev:l[0]]) {
			b.WriteString(".*")
		}
		var text string
		if l[2] >= 0 {
			text = args[l[2]:l[3]]
		} else {
			text = unescape(args[l[4]:l[5]])
		}
		for i, part := range strings.Split(text, "%s") {
			if i > 0 {
				b.WriteString(".*")
			}
			b.WriteString(regexp.QuoteMeta(part))
		}
		prev = l[1]
	}
	pattern := b.String()
	if !glue.MatchString(args[prev:]) {
		pattern += ".*"
	} else {
		// The emulator follows the message with its location,
		// " [at 1:8]", and BigQuery with " at [1:8]".
		pattern += `(?:$|\s+\[at |\s+at \[)`
	}
	if strings.Contains(pattern, "Syntax error: ") || strings.Trim(pattern, "^.*") == "" {
		return "", false
	}
	return pattern, true
}

// topLevelComma returns the index of the first comma outside parentheses
// and literals, or -1.
func topLevelComma(s string) int {
	depth := 0
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case '"':
			for i++; i < len(s) && s[i] != '"'; i++ {
				if s[i] == '\\' {
					i++
				}
			}
		case '(':
			depth++
		case ')':
			depth--
		case ',':
			if depth == 0 {
				return i
			}
		}
	}
	return -1
}

// unescape reads the escapes of a C++ string literal the messages use.
func unescape(s string) string {
	return strings.NewReplacer(`\"`, `"`, `\\`, `\`, `\n`, "\n", `\'`, `'`).Replace(s)
}

// refusalsGo writes the refusals as spanner/spanner-oracle's Go source.
func refusalsGo(rs []refusal) string {
	var b strings.Builder
	b.WriteString(`// Code generated by spanner/parser/cmd/tm2g4 from spanner/testdata/googlesql.tm. DO NOT EDIT.

package main

import "regexp"

// grammarRefusals match the messages GoogleSQL's grammar writes when one of
// its actions refuses input the rules derive, as "ROLE is not a supported
// object type" or "QUALIFY is not supported" where the product leaves the
// feature off: the parser's errors that do not start "Syntax error:". Each is
// the action at the line of googlesql.tm beside it.
var grammarRefusals = []*regexp.Regexp{
`)
	sorted := append([]refusal(nil), rs...)
	sort.SliceStable(sorted, func(i, j int) bool { return sorted[i].line < sorted[j].line })
	for _, r := range sorted {
		fmt.Fprintf(&b, "\tregexp.MustCompile(%s), // googlesql.tm:%d\n", strconv.Quote(r.pattern), r.line)
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err) // the source above is Go by construction
	}
	return string(src)
}
