package parser

import (
	"testing"

	"github.com/bytebase/omni/oracle/ast"
)

// TestJSONConstructors checks JSON_OBJECT, JSON_ARRAY, JSON_ARRAYAGG,
// JSON_OBJECTAGG, and JSON_SERIALIZE against Oracle 23ai: every accepted
// form parses there (or fails only on a datatype it checks after parsing,
// ORA-40449 or ORA-00932), and every rejected one fails with the error noted
// beside it. Rows ref_237 to ref_246, ref_253 to ref_256, ref_258 to
// ref_259, and ref_261 to ref_263 run them against the engine.
func TestJSONConstructors(t *testing.T) {
	for _, sql := range []string{
		// JSON_OBJECT entries: KEY, VALUE, IS, ':', a column, a star.
		"SELECT JSON_OBJECT('a' VALUE 1) FROM dual",
		"SELECT JSON_OBJECT(KEY 'a' VALUE 1, KEY 'b' VALUE 'x') FROM dual",
		"SELECT JSON_OBJECT('a' : 1, 'b' : 2) FROM dual",
		"SELECT JSON_OBJECT('a' IS 1) FROM dual",
		"SELECT JSON_OBJECT(KEY 'a' IS 1) FROM dual",
		"SELECT JSON_OBJECT() FROM dual",
		"SELECT JSON_OBJECT(*) FROM dual",
		"SELECT JSON_OBJECT(* RETURNING CLOB) FROM dual",
		"SELECT JSON_OBJECT(* NULL ON NULL STRICT WITH UNIQUE KEYS) FROM dual",
		"SELECT JSON_OBJECT(KEY 'VALUE' VALUE 1) FROM dual",
		"SELECT JSON_OBJECTAGG(KEY 'VALUE' VALUE 1) FROM dual",
		// TRUNCATE is a column name before VALUE (ORA-00932 only on the
		// key's datatype); STRICT is not, below.
		"SELECT JSON_OBJECT(truncate VALUE 1) FROM t",
		"SELECT JSON_OBJECT(truncate) FROM t",
		"SELECT JSON_ARRAY(truncate) FROM t",
		"SELECT JSON_ARRAY(strict) FROM t",
		"SELECT JSON_OBJECT(d.*) FROM dual d",
		"SELECT JSON_OBJECT(dummy) FROM dual",
		"SELECT JSON_OBJECT(d.dummy, d.*) FROM dual d",
		"SELECT JSON_OBJECT(sys.dual.dummy) FROM sys.dual",
		"SELECT JSON_OBJECT('a' VALUE 1, dummy) FROM dual",
		"SELECT JSON_OBJECT(dummy FORMAT JSON) FROM dual",
		"SELECT JSON_OBJECT(key VALUE 1) FROM (SELECT 'k' key FROM dual)",
		"SELECT JSON_OBJECT(KEY key VALUE 1) FROM (SELECT 'k' key FROM dual)",
		"SELECT JSON_OBJECT('a' VALUE '{}' FORMAT JSON) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE SUM(1)) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE CASE WHEN 1 = 1 THEN 'x' END) FROM dual",
		// JSON_OBJECT clauses, in order.
		"SELECT JSON_OBJECT('a' VALUE 1 NULL ON NULL) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 ABSENT ON NULL RETURNING CLOB) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 RETURNING VARCHAR2(100 BYTE) STRICT WITH UNIQUE KEYS) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 RETURNING VARCHAR2(100) STRICT) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 RETURNING VARCHAR2(10) TRUNCATE) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 RETURNING BLOB) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 RETURNING JSON) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 RETURNING RAW(100)) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 NULL ON NULL TRUNCATE) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 TRUNCATE STRICT) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 STRICT) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 WITH UNIQUE KEYS) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 WITHOUT UNIQUE KEYS) FROM dual",
		// JSON_ARRAY elements and clauses, or a subquery.
		"SELECT JSON_ARRAY(1, 2, 'x') FROM dual",
		"SELECT JSON_ARRAY() FROM dual",
		"SELECT JSON_ARRAY('[]' FORMAT JSON, 2 NULL ON NULL RETURNING CLOB STRICT) FROM dual",
		"SELECT JSON_ARRAY(1 ABSENT ON NULL) FROM dual",
		"SELECT JSON_ARRAY(1 STRICT) FROM dual",
		"SELECT JSON_ARRAY(1 TRUNCATE) FROM dual",
		"SELECT JSON_ARRAY(1 NULL ON NULL TRUNCATE STRICT) FROM dual",
		"SELECT JSON_ARRAY(1 RETURNING VARCHAR2(100) TRUNCATE STRICT) FROM dual",
		"SELECT JSON_ARRAY((SELECT 1 FROM dual)) FROM dual",
		"SELECT JSON_ARRAY(SELECT 1 FROM dual) FROM dual",
		"SELECT JSON_ARRAY(SELECT 1 FROM dual NULL ON NULL) FROM dual",
		"SELECT JSON_ARRAY(SELECT 1 FROM dual STRICT) FROM dual",
		"SELECT JSON_ARRAY(SELECT 1 FROM dual ORDER BY 1) FROM dual",
		// JSON_ARRAYAGG.
		"SELECT JSON_ARRAYAGG(dummy) FROM dual",
		"SELECT JSON_ARRAYAGG(ALL dummy) FROM dual",
		"SELECT JSON_ARRAYAGG(dummy ORDER BY dummy DESC RETURNING CLOB) FROM dual",
		"SELECT JSON_ARRAYAGG(dummy FORMAT JSON ORDER BY 1 NULL ON NULL RETURNING VARCHAR2(4000) STRICT) FROM dual",
		"SELECT JSON_ARRAYAGG(dummy ORDER BY dummy, 1 DESC NULLS LAST) FROM dual",
		"SELECT JSON_ARRAYAGG(dummy ABSENT ON NULL RETURNING CLOB) FROM dual",
		"SELECT JSON_ARRAYAGG(dummy RETURNING VARCHAR2(10) TRUNCATE STRICT) FROM dual",
		"SELECT JSON_ARRAYAGG(dummy TRUNCATE) FROM dual",
		"SELECT JSON_ARRAYAGG(JSON_OBJECT(KEY 'a' VALUE SUM(1), KEY 'b' VALUE dummy) RETURNING CLOB) FROM dual",
		// JSON_OBJECTAGG.
		"SELECT JSON_OBJECTAGG(KEY dummy VALUE 1) FROM dual",
		"SELECT JSON_OBJECTAGG(dummy IS 1) FROM dual",
		"SELECT JSON_OBJECTAGG(KEY dummy IS 1) FROM dual",
		"SELECT JSON_OBJECTAGG(dummy VALUE '1' FORMAT JSON) FROM dual",
		"SELECT JSON_OBJECTAGG(dummy VALUE 1 ABSENT ON NULL RETURNING CLOB STRICT WITH UNIQUE KEYS) FROM dual",
		"SELECT JSON_OBJECTAGG(dummy VALUE 1 TRUNCATE) FROM dual",
		// JSON_SERIALIZE.
		"SELECT JSON_SERIALIZE('{}') FROM dual",
		"SELECT JSON_SERIALIZE('{}' RETURNING CLOB PRETTY) FROM dual",
		"SELECT JSON_SERIALIZE('{}' RETURNING VARCHAR2(100) PRETTY ASCII TRUNCATE ERROR ON ERROR) FROM dual",
		"SELECT JSON_SERIALIZE('{}' FORMAT JSON RETURNING CLOB PRETTY) FROM dual",
		"SELECT JSON_SERIALIZE('{}' TRUNCATE ASCII PRETTY) FROM dual",
		"SELECT JSON_SERIALIZE('{}' ASCII TRUNCATE PRETTY ORDERED EXTENDED NULL ON ERROR) FROM dual",
		"SELECT JSON_SERIALIZE('{}' PRETTY ORDERED) FROM dual",
		"SELECT JSON_SERIALIZE('{}' EXTENDED ERROR ON ERROR) FROM dual",
		"SELECT JSON_SERIALIZE('{}' EMPTY ON ERROR) FROM dual",
		"SELECT JSON_SERIALIZE('{}' EMPTY ARRAY ON ERROR) FROM dual",
		"SELECT JSON_SERIALIZE('{}' EMPTY OBJECT ON ERROR) FROM dual",
		"SELECT JSON_SERIALIZE('{}' RETURNING VARCHAR2) FROM dual",
		// A quoted "*" names a column, so it is a scalar key.
		`SELECT JSON_OBJECTAGG("*" VALUE 1) FROM (SELECT 'k' "*" FROM dual)`,
		`SELECT JSON_OBJECTAGG(d."*" VALUE 1) FROM (SELECT 'k' "*" FROM dual) d`,
		// A colon right before the value, which the lexer reads as a bind.
		"SELECT JSON_OBJECT('a':1) FROM dual",
		"SELECT JSON_OBJECT('a':dummy, 'b':-1) FROM dual",
		`SELECT JSON_OBJECT('a':'x', 'b':"DUMMY") FROM dual`,
		// WITH TYPENAME, JSON_OBJECT's alone, before or after UNIQUE KEYS.
		"SELECT JSON_OBJECT(x WITH TYPENAME) FROM t",
		"SELECT JSON_OBJECT(WITH TYPENAME) FROM dual",
		"SELECT JSON_OBJECT(x RETURNING CLOB WITH TYPENAME) FROM t",
		"SELECT JSON_OBJECT('a' VALUE 1 TRUNCATE WITH TYPENAME) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 STRICT WITH TYPENAME WITH UNIQUE KEYS) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 WITHOUT TYPENAME WITH UNIQUE KEYS) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 RETURNING VARCHAR2(10) TRUNCATE STRICT WITH UNIQUE KEYS WITH TYPENAME) FROM dual",
		"SELECT JSON_OBJECT(x WITHOUT UNIQUE KEYS WITH TYPENAME) FROM t",
		// An object instance alone, from a call, CAST, or TREAT.
		"SELECT JSON_OBJECT(t(1) WITH TYPENAME) FROM dual",
		"SELECT JSON_OBJECT(CAST(NULL AS t)) FROM dual",
		"SELECT JSON_OBJECT(TREAT(x AS t)) FROM s",
		// Whether a call returns an object is the engine's to resolve:
		// Oracle 23ai rejects this one on UPPER's type (ORA-02000).
		"SELECT JSON_OBJECT(UPPER(dummy)) FROM dual",
		// STRICT after table.*, *, or FORMAT JSON.
		"SELECT JSON_OBJECT(dummy FORMAT JSON STRICT) FROM dual",
		"SELECT JSON_OBJECT(d.* STRICT) FROM dual d",
	} {
		ParseAndCheck(t, sql)
	}

	for _, sql := range []string{
		// An entry has a value unless it is a column or a star (ORA-02000),
		// none is empty (ORA-00936), and KEY's key takes VALUE or IS.
		"SELECT JSON_OBJECT('a' 1) FROM dual",
		"SELECT JSON_OBJECT(1) FROM dual",
		"SELECT JSON_OBJECT('a') FROM dual",
		"SELECT JSON_OBJECT('name', dummy) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1,) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE) FROM dual",
		"SELECT JSON_OBJECT(*, 'a' VALUE 1) FROM dual",
		"SELECT JSON_OBJECT(KEY dummy) FROM dual",
		"SELECT JSON_OBJECT(key) FROM (SELECT 'k' key FROM dual)",
		"SELECT JSON_OBJECT(KEY 'a' : 1) FROM dual",
		"SELECT JSON_OBJECT('a' FORMAT JSON VALUE 1) FROM dual",
		"SELECT JSON_OBJECT(strict VALUE 1) FROM t",
		// The clauses come in their order (ORA-02000).
		"SELECT JSON_OBJECT('a' VALUE 1 STRICT RETURNING CLOB) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 RETURNING CLOB NULL ON NULL) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 WITH UNIQUE KEYS STRICT) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 WITH UNIQUE KEYS RETURNING CLOB) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 TRUNCATE RETURNING CLOB) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 STRICT TRUNCATE) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 NULL ON EMPTY) FROM dual",
		"SELECT JSON_ARRAY(1,) FROM dual",
		"SELECT JSON_ARRAY(1 RETURNING CLOB NULL ON NULL) FROM dual",
		"SELECT JSON_ARRAY(1 WITH UNIQUE KEYS) FROM dual",
		"SELECT JSON_ARRAY(SELECT 1 FROM dual RETURNING CLOB) FROM dual",
		"SELECT JSON_ARRAY(SELECT 1 FROM dual ABSENT ON NULL) FROM dual",
		// The aggregates: one argument, no DISTINCT (ORA-30482), clauses in
		// order, no OVER or KEEP (ORA-30483, ORA-00923, ORA-00939).
		"SELECT JSON_ARRAYAGG() FROM dual",
		"SELECT JSON_ARRAYAGG(DISTINCT dummy) FROM dual",
		"SELECT JSON_ARRAYAGG(dummy, dummy) FROM dual",
		"SELECT JSON_ARRAYAGG(dummy RETURNING CLOB ORDER BY dummy) FROM dual",
		"SELECT JSON_ARRAYAGG(dummy NULL ON NULL ORDER BY dummy) FROM dual",
		"SELECT JSON_ARRAYAGG(dummy STRICT TRUNCATE) FROM dual",
		"SELECT JSON_ARRAYAGG(dummy WITH UNIQUE KEYS) FROM dual",
		"SELECT JSON_ARRAYAGG(dummy ORDER BY 1 ORDER BY 1) FROM dual",
		"SELECT JSON_ARRAYAGG(dummy ORDER BY dummy,) FROM dual",
		"SELECT JSON_ARRAYAGG(dummy) OVER () FROM dual",
		"SELECT JSON_ARRAYAGG(dummy) KEEP (DENSE_RANK FIRST ORDER BY 1) FROM dual",
		"SELECT JSON_OBJECTAGG(dummy : 1) FROM dual",
		"SELECT JSON_OBJECTAGG(dummy) FROM dual",
		"SELECT JSON_OBJECTAGG(DISTINCT dummy VALUE 1) FROM dual",
		"SELECT JSON_OBJECTAGG(dummy VALUE 1, 'b' VALUE 2) FROM dual",
		"SELECT JSON_OBJECTAGG(dummy VALUE 1 STRICT RETURNING CLOB) FROM dual",
		"SELECT JSON_OBJECTAGG(dummy VALUE 1) OVER () FROM dual",
		"SELECT JSON_OBJECTAGG(* VALUE 1) FROM dual",
		"SELECT JSON_OBJECTAGG(d.* VALUE 1) FROM dual d",
		// An unqualified quoted name is the built-in too (ORA-06552 for a
		// user function's arguments); only a qualified one is generic.
		"SELECT \"JSON_SERIALIZE\"(1, 2) FROM dual",
		// JSON_SERIALIZE: one argument, each flag once and in its place, one
		// ON ERROR clause without DEFAULT (ORA-00907, ORA-00939, ORA-40450).
		"SELECT JSON_SERIALIZE() FROM dual",
		"SELECT JSON_SERIALIZE('{}', 1) FROM dual",
		"SELECT JSON_SERIALIZE(DISTINCT '{}') FROM dual",
		"SELECT JSON_SERIALIZE('{}' PRETTY RETURNING CLOB) FROM dual",
		"SELECT JSON_SERIALIZE('{}' RETURNING CLOB FORMAT JSON) FROM dual",
		"SELECT JSON_SERIALIZE('{}' PRETTY PRETTY) FROM dual",
		"SELECT JSON_SERIALIZE('{}' ASCII ASCII) FROM dual",
		"SELECT JSON_SERIALIZE('{}' ORDERED PRETTY) FROM dual",
		"SELECT JSON_SERIALIZE('{}' ORDERED ORDERED) FROM dual",
		"SELECT JSON_SERIALIZE('{}' EXTENDED ORDERED) FROM dual",
		"SELECT JSON_SERIALIZE('{}' EXTENDED PRETTY) FROM dual",
		"SELECT JSON_SERIALIZE('{}' ERROR ON ERROR PRETTY) FROM dual",
		"SELECT JSON_SERIALIZE('{}' EMPTY ARRAY ON ERROR ORDERED) FROM dual",
		"SELECT JSON_SERIALIZE('{}' ASCII ORDERED PRETTY) FROM dual",
		"SELECT JSON_SERIALIZE('{}' NULL ON ERROR ERROR ON ERROR) FROM dual",
		"SELECT JSON_SERIALIZE('{}' DEFAULT 'x' ON ERROR) FROM dual",
		// A RETURNING datatype has its size or precision (ORA-00910,
		// ORA-40449).
		"SELECT JSON_SERIALIZE('{}' RETURNING VARCHAR2()) FROM dual",
		"SELECT JSON_ARRAYAGG(1 RETURNING RAW()) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 RETURNING NUMBER(,)) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 RETURNING NUMBER(5,)) FROM dual",
		// A KEY takes VALUE, and an entry one value (ORA-02000).
		"SELECT JSON_OBJECT(KEY 'a':1) FROM dual",
		"SELECT JSON_OBJECT('a':1:2) FROM dual",
		// One TYPENAME clause, in its place, on JSON_OBJECT alone (ORA-02000,
		// ORA-48503).
		"SELECT JSON_OBJECT(x WITH TYPENAME RETURNING CLOB) FROM t",
		"SELECT JSON_OBJECT('a' VALUE 1 WITH TYPENAME STRICT) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 WITH TYPENAME ABSENT ON NULL) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 WITH TYPENAME WITHOUT UNIQUE KEYS) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 WITH UNIQUE KEYS WITHOUT TYPENAME) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1 WITH TYPENAME WITH UNIQUE KEYS WITH TYPENAME) FROM dual",
		"SELECT JSON_ARRAY(1 WITH TYPENAME) FROM dual",
		"SELECT JSON_ARRAYAGG(1 WITH TYPENAME) FROM dual",
		"SELECT JSON_OBJECTAGG('k' VALUE 1 WITH TYPENAME) FROM dual",
		"SELECT JSON_OBJECT(1 WITH TYPENAME) FROM dual",
		// STRICT or TRUNCATE right after a column entry (ORA-02000).
		"SELECT JSON_OBJECT(dummy STRICT) FROM dual",
		"SELECT JSON_OBJECT(dummy TRUNCATE) FROM dual",
		"SELECT JSON_OBJECT('a' VALUE 1, dummy STRICT) FROM dual",
		// An object instance stands alone (ORA-02000).
		"SELECT JSON_OBJECT(t(1), t(2)) FROM dual",
	} {
		ParseShouldFail(t, sql)
	}

	agg := parseOne[*ast.SelectStmt](t, "SELECT JSON_ARRAYAGG(a ORDER BY b DESC RETURNING CLOB) FROM t").TargetList.Items[0].(*ast.ResTarget).Expr.(*ast.FuncCallExpr)
	if agg.FuncName.Name != "JSON_ARRAYAGG" || agg.Args.Len() != 1 || agg.OrderBy.Len() != 1 {
		t.Errorf("JSON_ARRAYAGG = %s, %d args, order %v", agg.FuncName.Name, agg.Args.Len(), agg.OrderBy)
	}
	obj := parseOne[*ast.SelectStmt](t, "SELECT JSON_OBJECT(KEY 'a' VALUE 1, b) FROM t").TargetList.Items[0].(*ast.ResTarget).Expr.(*ast.FuncCallExpr)
	if obj.Args.Len() != 3 {
		t.Errorf("JSON_OBJECT args = %d, want key, value, and column", obj.Args.Len())
	}
}
