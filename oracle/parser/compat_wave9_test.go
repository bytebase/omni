package parser

import (
	"errors"
	"testing"
)

// TestWave9CompatReadings pins the Wave 9 grammar and byte-offset families
// exposed by judge rev 4 (MAX_STRING_SIZE=EXTENDED, TYPE/DIMENSION fixtures,
// and offset-preserving stand-ins), together with valid Oracle 23ai controls
// beside each refusal.
func TestWave9CompatReadings(t *testing.T) {
	refusedAt := []struct {
		sql  string
		want int
	}{
		// ALTER TABLE ADD/MODIFY COLLATE near-misses report exact token offsets.
		{`ALTER TABLE a ADD(a COLLATE AS(1))`, 28},
		{`ALTER TABLE a ADD(a COLLATE`, 27},
		{`ALTER TABLE a ADD(a COLLATE a zzz AS(1))`, 30},
		{`ALTER TABLE a MODIFY(a COLLATE)`, 30},
		{`ALTER TABLE a MODIFY(a COLLATE`, 30},
		{`ALTER TABLE a MODIFY(a COLLATE a zzz)`, 33},
		{`ALTER TABLE a MODIFY(a COLLATE AS(1))`, 31},
		{`ALTER TABLE a MODIFY(a COLLATE a zzz AS(1))`, 33},

		// CREATE TABLE/VIEW/MATERIALIZED VIEW DEFAULT COLLATION requires a name
		// (and CREATE TABLE still requires a column list or AS subquery).
		{`CREATE VIEW a DEFAULT COLLATION`, 31},
		{`CREATE MATERIALIZED VIEW a DEFAULT COLLATION`, 44},
		{`CREATE TABLE a DEFAULT COLLATION`, 32},
		{`CREATE TABLE a DEFAULT COLLATION a`, 15},

		// CREATE SYNONYM SHARING = METADATA trailing token reports after METADATA.
		{`CREATE SYNONYM a SHARING = METADATA zzz FOR a`, 36},

		// CREATE PFILE requires '=' before filename.
		{`CREATE PFILE 's' FROM SPFILE`, 13},
		{`CREATE PFILE = 's' FROM SPFILE 's'`, 31},

		// Traditional AUDIT validates options (rejecting broken unified-audit near-misses).
		{`AUDIT a`, 6},
		{`AUDIT PORT a`, 6},
		{`AUDIT NAMESPACE a ATTRIBUTES a`, 6},
		{`AUDIT CONTINUE NAMESPACE a ATTRIBUTES a`, 6},

		// CREATE FUNCTION places SHARING before parameters and RETURN.
		{`CREATE FUNCTION a RETURN NUMBER SHARING = METADATA IS BEGIN RETURN 1; END;`, 32},
		{`CREATE FUNCTION a RETURN NUMBER SHARING = NONE IS BEGIN RETURN 1; END;`, 32},

		// ALTER TYPE rejects MODIFY [NOT] INSTANTIABLE|FINAL, bare CASCADE FORCE,
		// and CASCADE NOT SUBSTITUTABLE (PLS-00103).
		{`ALTER TYPE a MODIFY INSTANTIABLE`, 20},
		{`ALTER TYPE a MODIFY NOT INSTANTIABLE`, 20},
		{`ALTER TYPE a MODIFY FINAL`, 20},
		{`ALTER TYPE a MODIFY NOT FINAL`, 20},
		{`ALTER TYPE a ADD MAP MEMBER FUNCTION a RETURN NUMBER CASCADE FORCE`, 66},
		{`ALTER TYPE a ADD MAP MEMBER FUNCTION a RETURN NUMBER CASCADE NOT SUBSTITUTABLE`, 61},

		// ALTER TABLE NO DELETE UNTIL requires plural DAYS (ORA-02000).
		{`ALTER TABLE a NO DELETE UNTIL 1 DAY AFTER INSERT`, 32},
		{`ALTER TABLE a NO DELETE UNTIL 1 DAY INSERT`, 32},
		{`ALTER TABLE a NO DELETE UNTIL 1 DAY AFTER`, 32},

		// ALTER MATERIALIZED VIEW REFRESH USING ROLLBACK requires MASTER or LOCAL (ORA-12061 at byte 45).
		{`ALTER MATERIALIZED VIEW a REFRESH FAST USING ROLLBACK SEGMENT a`, 45},
		{`ALTER MATERIALIZED VIEW a REFRESH FAST USING ROLLBACK a`, 45},
		{`ALTER MATERIALIZED VIEW a REFRESH FAST USING ROLLBACK SEGMENT`, 45},
		{`ALTER MATERIALIZED VIEW a REFRESH FAST USING SEGMENT a`, 45},

		// CREATE MATERIALIZED VIEW refuses column-level INMEMORY clauses at query end (ORA-00922).
		{`CREATE MATERIALIZED VIEW a INMEMORY(a) INMEMORY AS SELECT 1 FROM dual`, 65},
		{`CREATE MATERIALIZED VIEW a INMEMORY(a) NO INMEMORY AS SELECT 1 FROM dual`, 68},
		{`CREATE MATERIALIZED VIEW a INMEMORY(a) INMEMORY NO MEMCOMPRESS AS SELECT 1 FROM dual`, 80},

		// CREATE PLUGGABLE DATABASE places AS CLONE before USING.
		{`CREATE PLUGGABLE DATABASE a USING 's' AS CLONE`, 38},

		// ALTER PLUGGABLE DATABASE RECOVER refuses STANDBY/UNTIL/USING (ORA-00905).
		{`ALTER PLUGGABLE DATABASE RECOVER STANDBY`, 33},
		{`ALTER PLUGGABLE DATABASE RECOVER UNTIL CANCEL`, 33},
		{`ALTER PLUGGABLE DATABASE RECOVER UNTIL`, 33},
		{`ALTER PLUGGABLE DATABASE RECOVER UNTIL TIME`, 33},
		{`ALTER PLUGGABLE DATABASE RECOVER UNTIL CHANGE 1`, 33},
		{`ALTER PLUGGABLE DATABASE RECOVER USING BACKUP CONTROLFILE`, 33},

		// ASSOCIATE STATISTICS USING NULL is allowed only with COLUMNS or INDEXES (ORA-29936).
		{`ASSOCIATE STATISTICS WITH FUNCTIONS a USING NULL`, 44},
		{`ASSOCIATE STATISTICS WITH PACKAGES a USING NULL`, 43},
	}

	for _, tc := range refusedAt {
		_, err := Parse(tc.sql)
		if err == nil {
			t.Errorf("Parse(%q) accepted; want rejection at byte %d", tc.sql, tc.want)
			continue
		}
		var pe *ParseError
		if !errors.As(err, &pe) || pe.Position != tc.want {
			t.Errorf("Parse(%q) failed with %v; want ParseError at byte %d", tc.sql, err, tc.want)
		}
	}

	// Valid Oracle 23ai controls beside each Wave 9 change.
	accepted := []string{
		`ALTER TABLE a ADD(a COLLATE a AS(1))`,
		`ALTER TABLE a MODIFY(a COLLATE a)`,
		`ALTER TABLE a MODIFY(a COLLATE a AS(1))`,
		`CREATE TABLE a (c VARCHAR2(10)) DEFAULT COLLATION USING_NLS_COMP`,
		`CREATE VIEW a DEFAULT COLLATION USING_NLS_COMP AS SELECT 1 FROM dual`,
		`CREATE MATERIALIZED VIEW a DEFAULT COLLATION USING_NLS_COMP AS SELECT 1 FROM dual`,
		`CREATE SYNONYM a SHARING = METADATA FOR b`,
		`CREATE SYNONYM a SHARING = NONE FOR b`,
		`CREATE PFILE = '/tmp/init.ora' FROM SPFILE = '/tmp/spfile.ora'`,
		`CREATE PFILE FROM SPFILE`,
		`AUDIT SELECT ON t BY ACCESS WHENEVER NOT SUCCESSFUL`,
		`AUDIT ALL STATEMENTS BY ACCESS`,
		`AUDIT POLICY my_pol BY scott`,
		`CREATE FUNCTION f1 SHARING = METADATA RETURN NUMBER IS BEGIN RETURN 1; END;`,
		`CREATE FUNCTION f2 SHARING = NONE (x NUMBER) RETURN NUMBER IS BEGIN RETURN x; END;`,
		`ALTER TYPE y INSTANTIABLE`,
		`ALTER TYPE y NOT FINAL CASCADE`,
		`ALTER TYPE y ADD ATTRIBUTE (x NUMBER) CASCADE FORCE EXCEPTIONS INTO err_tab`,
		`ALTER TYPE y NOT FINAL CASCADE CONVERT TO SUBSTITUTABLE`,
		`ALTER TABLE t NO DELETE UNTIL 16 DAYS AFTER INSERT`,
		`ALTER MATERIALIZED VIEW v REFRESH FAST USING MASTER ROLLBACK SEGMENT rbs1`,
		`ALTER MATERIALIZED VIEW v REFRESH FAST USING LOCAL ROLLBACK SEGMENT rbs1`,
		`ALTER MATERIALIZED VIEW v REFRESH FAST USING DEFAULT MASTER ROLLBACK SEGMENT`,
		`CREATE MATERIALIZED VIEW mv INMEMORY AS SELECT 1 FROM dual`,
		`CREATE PLUGGABLE DATABASE pdb1 AS CLONE USING '/tmp/pdb1.xml'`,
		`ALTER PLUGGABLE DATABASE pdb1 RECOVER`,
		`ALTER PLUGGABLE DATABASE RECOVER CANCEL`,
		`ALTER PLUGGABLE DATABASE RECOVER CONTINUE DEFAULT`,
		`ASSOCIATE STATISTICS WITH COLUMNS t.c USING NULL`,
		`ASSOCIATE STATISTICS WITH INDEXES idx USING NULL`,
	}

	for _, sql := range accepted {
		if _, err := Parse(sql); err != nil {
			t.Errorf("Parse(%q) failed: %v; want accept", sql, err)
		}
	}
}
