package parser

import (
	"errors"
	"testing"

	"github.com/bytebase/omni/oracle/ast"
)

// TestWave4CompatReadings pins the Wave 4 grammar families moved to Oracle
// 23.26.3's exact byte offsets, together with valid Oracle SQL controls beside
// each refusal.
func TestWave4CompatReadings(t *testing.T) {
	refusedAt := []struct {
		sql  string
		want int
	}{
		// Inline external table access driver TYPE enum (ORA-00922).
		{`SELECT * FROM EXTERNAL((a NUMBER) TYPE a DEFAULT DIRECTORY a LOCATION('s'))`, 39},
		{`DELETE a FROM EXTERNAL((a NUMBER) TYPE a DEFAULT DIRECTORY a LOCATION('s'))`, 39},
		{`SELECT * FROM EXTERNAL((a NUMBER NOT NULL) TYPE a DEFAULT DIRECTORY a LOCATION('s'))`, 48},
		{`SELECT * FROM EXTERNAL((a NUMBER) TYPE a DEFAULT DIRECTORY a REJECT LIMIT 1)`, 39},

		// ALTER TABLE MODIFY PARTITION BY & CREATE INDEX GLOBAL PARTITION BY expr lists.
		{`ALTER TABLE a MODIFY PARTITION BY RANGE(a(PARTITION VALUES LESS THAN(1))`, 52},
		{`ALTER TABLE a MODIFY PARTITION BY LIST(a(PARTITION VALUES(1))`, 51},
		{`ALTER TABLE a MODIFY PARTITION BY RANGE(a) SUBPARTITION BY HASH(a(PARTITION VALUES LESS THAN(1))`, 76},
		{`ALTER TABLE a MODIFY PARTITION BY LIST(a) SUBPARTITION BY RANGE(a(PARTITION VALUES(1))`, 76},
		{`CREATE INDEX a ON a(a) GLOBAL PARTITION BY RANGE(a(PARTITION VALUES LESS THAN(a))`, 61},

		// CREATE MATERIALIZED VIEW XMLTYPE XMLSCHEMA & ALLOW/DISALLOW refusal.
		{`CREATE MATERIALIZED VIEW a XMLTYPE a XMLSCHEMA 's' ELEMENT a AS SELECT 1 FROM dual`, 47},
		{`CREATE MATERIALIZED VIEW a XMLTYPE a XMLSCHEMA ELEMENT a AS SELECT 1 FROM dual`, 55},
		{`CREATE MATERIALIZED VIEW a XMLTYPE a ELEMENT a ALLOW NONSCHEMA AS SELECT 1 FROM dual`, 47},
		{`CREATE MATERIALIZED VIEW a XMLTYPE a ELEMENT a DISALLOW NONSCHEMA AS SELECT 1 FROM dual`, 47},
		{`CREATE MATERIALIZED VIEW a XMLTYPE a ELEMENT a ALLOW ANYSCHEMA AS SELECT 1 FROM dual`, 47},

		// ALTER TABLE UPGRADE INCLUDING DATA VARRAY ... STORE AS LOB partition storage.
		{`ALTER TABLE a UPGRADE INCLUDING DATA VARRAY a STORE AS LOB a(LOGGING)`, 61},
		{`ALTER TABLE a UPGRADE INCLUDING DATA VARRAY a STORE AS LOB a(PARTITIONING a VARRAY a STORE AS LOB a)`, 61},
		{`ALTER TABLE a UPGRADE INCLUDING DATA VARRAY a STORE AS LOB a(a VARRAY a STORE AS LOB a)`, 61},
		{`ALTER TABLE a UPGRADE INCLUDING DATA VARRAY a STORE AS LOB a(PARTITION a LOB a) STORE AS(LOGGING))`, 77},
		{`ALTER TABLE a UPGRADE INCLUDING DATA VARRAY a STORE AS LOB a(PARTITION a(a) STORE AS(LOGGING))`, 73},

		// ALTER TABLE MODIFY virtual column near-misses report exact inner error tokens.
		{`ALTER TABLE a MODIFY(a AS(1), a AS 1))`, 35},
		{`ALTER TABLE a MODIFY(a AS(1), a AS())`, 35},
		{`ALTER TABLE a MODIFY(a AS(1), a AS(1`, 36},
		{`ALTER TABLE a MODIFY(a AS(1), a ASC(1))`, 32},
		{`ALTER TABLE a MODIFY(a AS(1), a(1))`, 31},

		// CREATE TABLE / CREATE MATERIALIZED VIEW NESTED TABLE LOCAL refusal.
		{`CREATE TABLE a NESTED TABLE a LOCAL STORE AS a`, 30},
		{`CREATE TABLE a NESTED TABLE a LOCAL zzz STORE AS a`, 30},
		{`CREATE MATERIALIZED VIEW a NESTED TABLE a LOCAL STORE AS a AS SELECT 1 FROM dual`, 42},
		{`CREATE MATERIALIZED VIEW a NESTED TABLE a LOCAL zzz STORE AS a AS SELECT 1 FROM dual`, 42},

		// Empty SUBPARTITION TEMPLATE() on CREATE TABLE without columns blames PARTITION.
		{`CREATE TABLE a PARTITION BY HASH(a) SUBPARTITION BY RANGE(a) SUBPARTITION TEMPLATE() PARTITIONS 1`, 15},

		// CREATE/ALTER INDEXTYPE WITH ARRAY DML list & WITHOUT SYSTEM.
		{`ALTER INDEXTYPE a ADD a(NUMBER) USING a WITH ARRAY DML(a, a), a, a)`, 62},
		{`CREATE INDEXTYPE a FOR a(NUMBER) USING a WITH ARRAY DML(a, a), a, a)`, 63},
		{`CREATE INDEXTYPE a FOR a(NUMBER) USING a WITHOUT SYSTEM MANAGED STORAGE TABLES`, 49},

		// SELECT / DELETE / UPDATE table aliases: PERIOD, WINDOW (in DELETE), LEFT before PARTITION BY, LATERAL.
		{`SELECT * FROM a PERIOD FOR a BETWEEN 1 AND 1`, 27},
		{`DELETE a FROM a PERIOD FOR a BETWEEN 1 AND 1`, 23},
		{`DELETE a WINDOW 1 = 1`, 16},
		{`DELETE a FROM LATERAL zzz SELECT 1 FROM dual`, 26},
		{`SELECT * FROM a LEFT PARTITION BY 1 a ON 1 = 1`, 34},
		{`DELETE a FROM a LEFT PARTITION BY 1 a ON 1 = 1`, 34},
		{`UPDATE a SET a = 1 FROM a LEFT PARTITION BY 1 a ON 1 = 1`, 44},

		// ALTER TABLE top-level NESTED TABLE / VARRAY column_properties & ADD UDT(...).
		{`ALTER TABLE a NESTED TABLE a RETURN AS LOCATOR`, 29},
		{`ALTER TABLE a VARRAY a(RETENTION)`, 22},
		{`ALTER TABLE a ADD LOG DATA(ALL) COLUMNS`, 22},

		// Other Wave 4 grammar readings.
		{`CREATE TABLE a(a ANNOTATIONS(ADD a, a))`, 38},
		{`CREATE SNAPSHOT TABLESPACE a`, 27},
		{`CREATE "SNAPSHOT" mv AS SELECT 1 FROM dual`, 7},
		{`CREATE MATERIALIZED VIEW a AS SELECT 1 FROM dual(ADD a)`, 49},
		{`ALTER MATERIALIZED VIEW a MERGE SUBPARTITIONS a, a INVALIDATE SUBPARTITION`, 62},
		{`ALTER MATERIALIZED VIEW LOG ON a SPLIT PARTITION a AT(1) INTO PARTITION, PARTITION)`, 62},
		{`ADMINISTER KEY MANAGEMENT MOVE KEYS TO NEW KEYSTORE 's' IDENTIFIED BY a FROM KEYSTORE IDENTIFIED BY a WITH IDENTIFIER IN a)`, 121},
	}

	for _, tc := range refusedAt {
		_, err := Parse(tc.sql)
		if err == nil {
			t.Errorf("Parse(%q) accepted; want rejection at byte %d", tc.sql, tc.want)
			continue
		}
		var pe *ParseError
		if !errors.As(err, &pe) || pe.Position != tc.want {
			t.Errorf("Parse(%q) failed with %v; want ParseError at byte %d", tc.sql, err, tc.want)
		}
	}

	// Valid Oracle SQL controls beside the Wave 4 refusals.
	accepted := []string{
		`SELECT * FROM EXTERNAL ((a NUMBER) TYPE ORACLE_LOADER DEFAULT DIRECTORY ext_dir LOCATION ('f.csv'))`,
		`SELECT * FROM EXTERNAL ((a NUMBER) TYPE ORACLE_DATAPUMP DEFAULT DIRECTORY ext_dir LOCATION ('f.dmp'))`,
		`SELECT * FROM EXTERNAL ((a NUMBER) TYPE ORACLE_HDFS DEFAULT DIRECTORY ext_dir LOCATION ('f.dat'))`,
		`SELECT * FROM EXTERNAL ((a NUMBER) TYPE ORACLE_HIVE DEFAULT DIRECTORY ext_dir LOCATION ('f.dat'))`,
		`SELECT * FROM EXTERNAL ((a NUMBER) TYPE ORACLE_BIGDATA DEFAULT DIRECTORY ext_dir LOCATION ('f.dat'))`,
		`CREATE TABLE t (a NUMBER) PARTITION BY HASH (a) SUBPARTITION BY RANGE (a) SUBPARTITION TEMPLATE () PARTITIONS 2`,
		`CREATE MATERIALIZED VIEW mv PARTITION BY HASH (a) SUBPARTITION BY RANGE (a) SUBPARTITION TEMPLATE () PARTITIONS 1 AS SELECT 1 FROM dual`,
		`CREATE MATERIALIZED VIEW LOG ON t PARTITION BY HASH (a) SUBPARTITION BY RANGE (a) SUBPARTITION TEMPLATE () PARTITIONS 1`,
		`CREATE TABLE t (a NUMBER) NESTED TABLE nt GLOBAL STORE AS nt_store`,
		`CREATE MATERIALIZED VIEW mv NESTED TABLE nt GLOBAL STORE AS nt_store AS SELECT 1 FROM dual`,
		`CREATE MATERIALIZED VIEW mv XMLTYPE x XMLSCHEMA s1 ELEMENT e1 AS SELECT 1 FROM dual`,
		`CREATE SNAPSHOT mv AS SELECT 1 FROM dual`,
		`CREATE SNAPSHOT LOG ON t`,
		`CREATE INDEXTYPE it FOR op(NUMBER) USING impl WITH ARRAY DML (t1, vt1), (t2, vt2) WITH SYSTEM MANAGED STORAGE TABLES`,
		`SELECT * FROM t period WHERE period.id = 1`,
		`SELECT * FROM lateral l WHERE l.id = 1`,
		`DELETE t window WHERE window.id = 1`,
		`SELECT * FROM a LEFT JOIN b ON a.id = b.id`,
		`SELECT * FROM a PARTITION BY (a.k) LEFT JOIN b ON a.id = b.id`,
		`ALTER TABLE t MODIFY PARTITION BY RANGE (a) SUBPARTITION BY HASH (b) (PARTITION p1 VALUES LESS THAN (10))`,
		`ALTER TABLE t MODIFY PARTITION BY RANGE (json_value) (PARTITION p1 VALUES LESS THAN (10))`,
		`CREATE INDEX idx ON t (a) GLOBAL PARTITION BY RANGE (a) (PARTITION p1 VALUES LESS THAN (10), PARTITION pmax VALUES LESS THAN (MAXVALUE))`,
		`CREATE INDEX idx ON t (json_value) GLOBAL PARTITION BY RANGE (json_value) (PARTITION p1 VALUES LESS THAN (10))`,
		`ALTER TABLE t UPGRADE INCLUDING DATA VARRAY v STORE AS LOB v_lob (PARTITION p1 VARRAY v STORE AS LOB p1_lob)`,
		`ALTER TABLE t MODIFY (a AS (1), b AS (2))`,
		`ALTER TABLE t ADD (c NUMBER)`,
		`CREATE TABLE t (a NUMBER ANNOTATIONS (ADD ann1, ann2))`,
		`ALTER MATERIALIZED VIEW LOG ON t SPLIT PARTITION p1 AT (10) INTO (PARTITION p1a, PARTITION p1b)`,
		`ADMINISTER KEY MANAGEMENT MOVE KEYS TO NEW KEYSTORE '/k' IDENTIFIED BY p1 FROM KEYSTORE IDENTIFIED BY p2 WITH IDENTIFIER IN 'k1'`,
	}

	for _, sql := range accepted {
		list, err := Parse(sql)
		if err != nil {
			t.Errorf("Parse(%q) failed: %v", sql, err)
			continue
		}
		if list == nil || len(list.Items) != 1 {
			t.Errorf("Parse(%q) returned %d statements; want 1", sql, len(list.Items))
			continue
		}
		raw, ok := list.Items[0].(*ast.RawStmt)
		if !ok || raw.Stmt == nil {
			t.Errorf("Parse(%q) item is %T; want non-nil *ast.RawStmt", sql, list.Items[0])
		}
	}
}
