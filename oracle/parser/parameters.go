// isOracleParameter reports whether name is one of the server's parameters.
func isOracleParameter(name string) bool {
	return oracleParameters[strings.ToUpper(name)]
}

// isAlterSessionSetting reports whether name is a setting of its own in
// alter_session_set_clause rather than an initialization parameter: the page
// names these, and Oracle reads their values by the setting's own grammar.
