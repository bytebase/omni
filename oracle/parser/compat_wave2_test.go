// TestWave2CompatReadings pins the unclosed-'(' delimiter deferral, its
// prerequisite grammar readings, and the Wave 2 grammar families moved to
// Oracle 23.26.3's exact byte offsets, together with valid Oracle SQL controls
// beside each refusal.
func TestWave2CompatReadings(t *testing.T) {
	refusedAt := []struct {
		sql  string
		want int
	}{
		// Unclosed-'(' deferral: report the statement parser's earlier error
		// inside an unterminated parenthesis group instead of EOF.
		{`INSERT INTO t (a VALUES (1)`, 17},
		{`SELECT * WINDOW a AS(ROWS UNBOUNDED`, 21},
		{`CREATE TABLESPACE SET a USING TEMPLATE(DEFAULT DEFAULT TABLE`, 47},
		{`CREATE MATERIALIZED VIEW a(PARTITION ILM ADD POLICY ROW STORE`, 37},
		{`ALTER TABLE a MODIFY PARTITION BY RANGE(a SUBPARTITION BY RANGE(a)(PARTITION VALUES LESS THAN(1))`, 42},
		{`DELETE a FROM EXTERNAL((a NUMBER DEFAULT`, 33},
		{`SELECT * FROM EXTERNAL((a NUMBER GENERATED ALWAYS AS`, 33},

		// Prerequisite readings that unblocked unclosed-'(' deferral.
		{`ADMINISTER KEY MANAGEMENT MOVE KEYS TO NEW KEYSTORE 's' IDENTIFIED BY a FROM KEYSTORE IDENTIFIED BY a WITH IDENTIFIER IN(a)`, 123},
		{`ADMINISTER KEY MANAGEMENT MOVE KEYS TO NEW KEYSTORE 's' IDENTIFIED BY a FROM KEYSTORE IDENTIFIED BY a WITH IDENTIFIER IN(a,`, 123},
		{`ADMINISTER KEY MANAGEMENT MOVE KEYS TO NEW KEYSTORE 's' IDENTIFIED BY a FROM KEYSTORE IDENTIFIED BY a WITH IDENTIFIER IN()`, 122},
		{`ALTER MATERIALIZED VIEW a MODIFY LOB(a, a)()`, 40},
		{`ALTER MATERIALIZED VIEW a MODIFY LOB(a,)()`, 39},
		{`ALTER MATERIALIZED VIEW a MODIFY LOB(a,`, 39},
		{`ALTER TABLE a UPGRADE INCLUDING DATA VARRAY a STORE AS LOB a(PARTITION a VARRAY a STORE AS LOB a VARRAY a STORE AS LOB a)`, 120},
		{`ALTER TABLE a UPGRADE INCLUDING DATA VARRAY a STORE AS LOB a(PARTITION a VARRAY a STORE AS LOB a VARRAY a AS LOB a)`, 106},
		{`ALTER TABLE a UPGRADE INCLUDING DATA VARRAY a STORE AS LOB a(PARTITION a VARRAY a STORE AS LOB a VARRAY a STORE AS LOB`, 118},
		{`CREATE INDEX a ON a(a) INDEXTYPE IS a LOCAL(PARTITION PARAMETERS('s')`, 69},
		{`CREATE INDEX a ON a(a) INDEXTYPE IS XDB.XMLINDEX LOCAL(PARTITION PARAMETERS('s')`, 80},
		{`CREATE TABLE a(DOMAIN a(a))`, 26},
		{`CREATE TABLE a(DOMAIN a(a)`, 26},
		{`CREATE TABLE a(DOMAIN a(a, a))`, 29},
		{`CREATE TABLE a(DOMAIN a())`, 24},
		{`CREATE TABLE a(SUPPLEMENTAL LOG GROUP a(a NO))`, 44},
		{`CREATE TABLE a(SUPPLEMENTAL LOG GROUP a(a NO`, 44},
		{`CREATE TABLE a PARTITION BY HASH(a)(PARTITION ILM`, 49},
		{`CREATE TABLE a(PARTITION READ`, 29},
		{`CREATE TABLE a(PARTITION READ ONLY)`, 30},

		// CREATE TABLE / CREATE MATERIALIZED VIEW VARRAY STORE AS LOB seg (PARTITION ...).
		{`CREATE TABLE a VARRAY a STORE AS LOB a(PARTITION a VARRAY a STORE AS LOB a)`, 38},
		{`CREATE TABLE a VARRAY a STORE AS LOB a(a VARRAY a STORE AS LOB a)`, 39},
		{`CREATE MATERIALIZED VIEW a VARRAY a STORE AS LOB a(PARTITION a VARRAY a STORE AS LOB a) AS SELECT 1 FROM dual`, 50},
		{`CREATE MATERIALIZED VIEW a VARRAY a STORE AS LOB a(PARTITIONING a VARRAY a STORE AS LOB a) AS SELECT 1 FROM dual`, 51},

		// ALTER MATERIALIZED VIEW ADD PARTITION blame & UPDATE INDEXES.
		{`ALTER MATERIALIZED VIEW a ADD PARTITION UPDATE INDEXES(a PARTITION))`, 40},
		{`ALTER MATERIALIZED VIEW a ADD PARTITION UPDATE`, 40},
		{`ALTER MATERIALIZED VIEW a ADD PARTITION LESS THAN(1)`, 40},
		{`ALTER MATERIALIZED VIEW a ADD PARTITION READS ONLY`, 40},
		{`ALTER MATERIALIZED VIEW a ADD PARTITION a zzz`, 40},
		{`ALTER MATERIALIZED VIEW a ADD PARTITION VALUES THAN(1)`, 47},

		// INMEMORY DISTRIBUTE BY target blame.
		{`ALTER MATERIALIZED VIEW a INMEMORY DISTRIBUTE BY ROWID`, 46},
		{`ALTER MATERIALIZED VIEW a INMEMORY DISTRIBUTE BY`, 46},
		{`ALTER TABLE a INMEMORY DISTRIBUTE BY RANGE`, 34},
		{`ALTER TABLE a INMEMORY DISTRIBUTE BY`, 34},
		{`CREATE TABLE a INMEMORY DISTRIBUTE BY RANGE`, 35},
		{`CREATE MATERIALIZED VIEW a INMEMORY DISTRIBUTE BY RANGE AS SELECT 1 FROM dual`, 47},

		// CREATE MATERIALIZED VIEW PARTITION BY REFERENCE at constraint name.
		{`CREATE MATERIALIZED VIEW a PARTITION BY REFERENCE(a) AS SELECT 1 FROM dual`, 50},
		{`CREATE MATERIALIZED VIEW a PARTITION BY REFERENCE(a)(PARTITION) AS SELECT 1 FROM dual`, 50},
		{`CREATE MATERIALIZED VIEW a PARTITION BY REFERENCE(a AS SELECT 1 FROM dual`, 52},

		// CREATE TABLE / CREATE MATERIALIZED VIEW attribute_clustering_clause.
		{`CREATE TABLE a CLUSTERING a JOIN a ON(a = a) BY(a)`, 47},
		{`CREATE TABLE a CLUSTERING a.a JOIN a ON(a = a) BY(a)`, 49},
		{`CREATE TABLE a CLUSTERING a`, 27},
		{`CREATE TABLE a CLUSTERING JOIN a`, 32},
		{`CREATE TABLE a CLUSTERING JOIN a(a = a) BY(a)`, 32},
		{`CREATE TABLE a CLUSTERING.a JOIN a ON(a = a) BY(a)`, 25},
		{`CREATE MATERIALIZED VIEW a CLUSTERING a(a) AS SELECT 1 FROM dual`, 39},

		// ALTER TABLE MODIFY user-defined type with '(' (ORA-03060).
		{`ALTER TABLE a MODIFY(a LOB(a) STORE AS(LOGGING))`, 23},
		{`ALTER TABLE a MODIFY(a LOBS(a) STORE AS(LOGGING))`, 23},
		{`ALTER TABLE a MODIFY(a LOB a) STORE AS(LOGGING))`, 27},
		{`ALTER TABLE a MODIFY(a CHECKPOINT(1 = 1))`, 23},

		// ALTER VIEW ADD constraints.
		{`ALTER VIEW a ADD CHECK(1 = 1)`, 17},
		{`ALTER VIEW a ADD CONSTRAINT c CHECK(1 = 1)`, 30},
		{`ALTER VIEW a ADD(a)`, 17},
		{`ALTER VIEW a ADD CONSTRAINT UNIQUE(a)`, 28},
		{`ALTER VIEW a ADD PRIMARY(a)`, 24},
		{`ALTER VIEW a ADD FOREIGN(a) REFERENCES a`, 24},

		// ALTER TABLE NO prefix & ALTER MATERIALIZED VIEW TRUNCATE.
		{`ALTER TABLE a NO`, 14},
		{`ALTER TABLE a NO FOR READ`, 14},
		{`ALTER TABLE a NO REFRESH`, 14},
		{`ALTER MATERIALIZED VIEW a TRUNCATE a`, 26},
		{`ALTER MATERIALIZED VIEW a TRUNCATE`, 26},

		// ALTER DISKGROUP MOVE / REPLACE / MODIFY QUOTAGROUP.
		{`ALTER DISKGROUP a MOVE FILE TO FILEGROUP a`, 31},
		{`ALTER DISKGROUP a MOVE FILE FILEGROUP a`, 38},
		{`ALTER DISKGROUP a MOVE FILEGROUP TO QUOTAGROUP a`, 36},
		{`ALTER DISKGROUP a REPLACE DISK WITH 's'`, 36},
		{`ALTER DISKGROUP a MODIFY QUOTAGROUP SET QUOTA = 1`, 40},

		// INMEMORY / NOMAPPING / IMMEDIATE / MEMOPTIMIZE / ON / USING readings.
		{`ALTER CLUSTER a INMEMORY 1`, 25},
		{`CREATE CLUSTER a(a NUMBER) INMEMORY 1`, 36},
		{`ALTER INDEX a INMEMORY 1`, 23},
		{`CREATE INDEX a ON CLUSTER a INMEMORY 1`, 37},
		{`CREATE INDEX a ON CLUSTER a NOMAPPING`, 37},
		{`ALTER MATERIALIZED VIEW LOG ON a INMEMORY 1`, 42},
		{`ALTER MATERIALIZED VIEW LOG ON a NOMAPPING`, 42},
		{`ALTER MATERIALIZED VIEW LOG ON a IMMEDIATE SYNCHRONOUS`, 43},
		{`CREATE MATERIALIZED VIEW LOG ON a INMEMORY 1`, 43},
		{`CREATE MATERIALIZED VIEW LOG ON a NOMAPPING`, 43},
		{`CREATE MATERIALIZED VIEW LOG ON a IMMEDIATE SYNCHRONOUS`, 44},
		{`CREATE MATERIALIZED VIEW LOG ON a PARTITION BY HASH(a)(PARTITION INMEMORY zzz)`, 74},
		{`CREATE MATERIALIZED VIEW a NOMAPPING AS SELECT 1 FROM dual`, 37},
		{`CREATE MATERIALIZED VIEW a IMMEDIATE AS SELECT 1 FROM dual`, 37},
		{`CREATE MATERIALIZED VIEW a ON TABLE AS SELECT 1 FROM dual`, 30},
		{`CREATE MATERIALIZED VIEW a USING CURRENT EDITION AS SELECT 1 FROM dual`, 33},
		{`CREATE MATERIALIZED VIEW a INMEMORY MEMOPTIMIZE FOR DML AS SELECT 1 FROM dual`, 52},
		{`ALTER MATERIALIZED VIEW a INMEMORY MEMOPTIMIZE FOR QUERY`, 51},
		{`ALTER MATERIALIZED VIEW a INMEMORY FOR QUERY`, 39},
		{`ALTER MATERIALIZED VIEW a FOR OLTP`, 30},
		{`ALTER MATERIALIZED VIEW a USING EDITION a`, 32},

		// Supplemental log duplicates, annotations duplicates, MODIFY PARTITION ADD VALUES LESS THAN,
		// hash TABLESPACE SET, ENCRYPT NO zzz SALT, CONTAINER_MAP UPDATE, VERSIONS FOR.
		{`ALTER TABLE a ADD SUPPLEMENTAL LOG DATA(ALL, ALL) COLUMNS`, 48},
		{`ALTER TABLE a ADD SUPPLEMENTAL LOG DATA(ALL, ALL zzz) COLUMNS`, 49},
		{`CREATE TABLE a(SUPPLEMENTAL LOG DATA(ALL, ALL) COLUMNS)`, 45},
		{`CREATE TABLE a(a ANNOTATIONS(ADD a, a zzz))`, 38},
		{`ALTER TABLE a MODIFY PARTITION a ADD VALUES LESS THAN(1)`, 44},
		{`ALTER MATERIALIZED VIEW a MODIFY PARTITION a ADD VALUES LESS THAN(1)`, 56},
		{`CREATE TABLE a PARTITION BY HASH(a) TABLESPACE SET a`, 47},
		{`CREATE MATERIALIZED VIEW a(a ENCRYPT NO zzz SALT) AS SELECT 1 FROM dual`, 40},
		{`CREATE PLUGGABLE DATABASE a CONTAINER_MAP UPDATE(ADD a VALUES LESS THAN(1))`, 55},
		{`CREATE PLUGGABLE DATABASE a CONTAINER_MAP UPDATE(SPLIT PARTITION a AT(1) INTO(PARTITION, PARTITION a))`, 102},
		{`SELECT * FROM a VERSIONS FOR a BETWEEN 1 AND 1`, 29},
	}
	for _, tc := range refusedAt {
		_, err := Parse(tc.sql)
		var pe *ParseError
		if !errors.As(err, &pe) {
			t.Errorf("Parse(%q): error = %v, want a ParseError", tc.sql, err)
			continue
		}
		if pe.Position != tc.want {
			t.Errorf("Parse(%q): refused at %d, want %d", tc.sql, pe.Position, tc.want)
		}
	}

	// Valid Oracle SQL controls beside the refusals above.
	controls := []string{
		`CREATE TABLE t (c1 NUMBER, c2 NUMBER, DOMAIN my_dom (c1, c2))`,
		`CREATE TABLE t (c1 NUMBER, c2 NUMBER, DOMAIN hr.my_dom (c1, c2))`,
		`CREATE TABLE t (domain VARCHAR2(10))`,
		`CREATE TABLE t (a NUMBER) CLUSTERING BY LINEAR ORDER (a)`,
		`CREATE TABLE t (a NUMBER) CLUSTERING t JOIN d ON (t.a = d.a) BY INTERLEAVED ORDER ((t.a, d.b)) YES ON LOAD YES ON DATA MOVEMENT WITH MATERIALIZED ZONEMAP`,
		`CREATE MATERIALIZED VIEW mv CLUSTERING BY LINEAR ORDER (a) AS SELECT 1 a FROM dual`,
		`ADMINISTER KEY MANAGEMENT MOVE KEYS TO NEW KEYSTORE 's' IDENTIFIED BY a FROM KEYSTORE IDENTIFIED BY a WITH IDENTIFIER IN (SELECT 'k' FROM dual) WITH BACKUP USING 'b'`,
		`ALTER MATERIALIZED VIEW a ADD PARTITION UPDATE INDEXES(a(PARTITION))`,
		`ALTER MATERIALIZED VIEW a INMEMORY DISTRIBUTE BY PARTITION`,
		`ALTER TABLE a INMEMORY DISTRIBUTE BY ROWID RANGE`,
		`CREATE TABLE t (c CLOB) VARRAY c STORE AS LOB c_lob (RETENTION)`,
		`ALTER TABLE t MODIFY (c VARCHAR2(10))`,
		`ALTER TABLE t MODIFY (c NUMBER(10, 2))`,
		`ALTER TABLE t MODIFY (r RAW(100))`,
		`ALTER VIEW v ADD CONSTRAINT pk_v PRIMARY KEY (a) DISABLE NOVALIDATE`,
		`ALTER VIEW v ADD UNIQUE (a) DISABLE`,
		`ALTER DISKGROUP dg MOVE FILE '+DG/file' TO FILEGROUP fg1`,
		`ALTER DISKGROUP dg REPLACE DISK d1 WITH '/dev/disk1'`,
		`ALTER TABLE t ADD SUPPLEMENTAL LOG DATA (ALL, PRIMARY KEY) COLUMNS`,
		`CREATE TABLE t (a NUMBER ANNOTATIONS (ADD k1 'v1', ADD k2 'v2'))`,
		`CREATE MATERIALIZED VIEW mv (a ENCRYPT NO SALT) AS SELECT 1 a FROM dual`,
		`CREATE TABLE t (a NUMBER) INMEMORY MEMOPTIMIZE FOR READ`,
		`SELECT * FROM a VERSIONS PERIOD FOR valid_time BETWEEN 1 AND 2`,
	}
	for _, sql := range controls {
		if _, err := Parse(sql); err != nil {
			t.Errorf("Parse(%q): %v, want accepted", sql, err)
		}
	}

	// Verify AST fidelity for table-level DOMAIN and attribute_clustering_clause.
	domList, err := Parse(`CREATE TABLE t (c1 NUMBER, c2 NUMBER, DOMAIN hr.my_dom (c1, c2))`)
	if err != nil {
		t.Fatalf("Parse table-level DOMAIN: %v", err)
	}
	ct := domList.Items[0].(*ast.RawStmt).Stmt.(*ast.CreateTableStmt)
	if ct.Columns.Len() != 2 {
		t.Fatalf("expected 2 columns, got %d", ct.Columns.Len())
	}
	if ct.Options == nil || ct.Options.Len() != 1 {
		t.Fatalf("expected 1 DDLOption for DOMAIN, got %v", ct.Options)
	}
	opt := ct.Options.Items[0].(*ast.DDLOption)
	if opt.Key != "DOMAIN" {
		t.Fatalf("expected DDLOption key DOMAIN, got %q", opt.Key)
	}
}
