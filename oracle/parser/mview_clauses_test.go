package parser

import "testing"

// TestMaterializedViewGrammar holds CREATE and ALTER MATERIALIZED VIEW to
// the pinned Oracle's answers, probed on a server with a materialized view
// a in place.
func TestMaterializedViewGrammar(t *testing.T) {
	accepted := []string{
		"CREATE MATERIALIZED VIEW a(a ENCRYPT, SCOPE FOR(REF(b)) IS t) AS SELECT 1 a, b FROM t",
		"CREATE MATERIALIZED VIEW a OF ty AS SELECT 1 a FROM dual",
		"CREATE MATERIALIZED VIEW a SEGMENT CREATION IMMEDIATE ORGANIZATION HEAP PCTFREE 1 AS SELECT 1 FROM dual",
		"CREATE MATERIALIZED VIEW a PARTITION BY HASH(a) PARTITIONS 2 NOLOGGING CACHE PARALLEL 2 BUILD IMMEDIATE AS SELECT 1 a FROM dual",
		"CREATE MATERIALIZED VIEW a NESTED TABLE a STORE AS s CACHE AS SELECT 1 a FROM dual",
		"CREATE MATERIALIZED VIEW a XMLTYPE a STORE AS CLOB(CACHE) AS SELECT 1 a FROM dual",
		"CREATE MATERIALIZED VIEW a JSON(a, b) STORE AS s AS SELECT 1 a FROM dual",
		"CREATE MATERIALIZED VIEW a BUILD IMMEDIATE USING INDEX TABLESPACE u INITRANS 2 REFRESH FAST AS SELECT 1 FROM dual",
		"CREATE MATERIALIZED VIEW a REFRESH ON DEMAND WITH PRIMARY KEY USING DEFAULT ROLLBACK SEGMENT USING TRUSTED CONSTRAINTS START WITH SYSDATE NEXT SYSDATE + 1 FORCE AS SELECT 1 FROM dual",
		"CREATE MATERIALIZED VIEW a NEVER REFRESH FOR UPDATE AS SELECT 1 FROM dual",
		"CREATE MATERIALIZED VIEW a ENABLE ON QUERY COMPUTATION DISABLE QUERY REWRITE AS SELECT 1 FROM dual",
		"CREATE MATERIALIZED VIEW a ENABLE QUERY REWRITE UNUSABLE BEFORE EDITION e UNUSABLE BEGINNING WITH CURRENT EDITION AS SELECT 1 FROM dual",
		"CREATE MATERIALIZED VIEW a ON PREBUILT TABLE ANNOTATIONS(ADD a, DROP b, c 'x') AS SELECT 1 FROM dual",
		"ALTER MATERIALIZED VIEW a PCTFREE 5 NOLOGGING",
		"ALTER MATERIALIZED VIEW a REFRESH COMPLETE ENABLE QUERY REWRITE",
		"ALTER MATERIALIZED VIEW a CACHE COMPILE",
		"ALTER MATERIALIZED VIEW a COMPRESS 1",
		"ALTER MATERIALIZED VIEW a ENABLE CONCURRENT REFRESH",
		"ALTER MATERIALIZED VIEW a SPLIT PARTITION a AT(5)",
		"ALTER MATERIALIZED VIEW a MERGE SUBPARTITIONS a, b INTO SUBPARTITION c PARALLEL",
	}
	for _, sql := range accepted {
		t.Run(sql, func(t *testing.T) {
			ParseAndCheck(t, sql)
		})
	}
	refused := []string{
		// ORA-00922 at MATERIALIZED.
		"CREATE OR REPLACE MATERIALIZED VIEW a AS SELECT 1 FROM dual",
		// ORA-02000: properties end at BUILD, and USING INDEX comes before REFRESH.
		"CREATE MATERIALIZED VIEW a BUILD IMMEDIATE PARALLEL 2 AS SELECT 1 FROM dual",
		"CREATE MATERIALIZED VIEW a REFRESH FAST USING INDEX AS SELECT 1 FROM dual",
		// ORA-00905: REFRESH takes at least one part.
		"CREATE MATERIALIZED VIEW a REFRESH AS SELECT 1 FROM dual",
		// ORA-03048: a materialized view's query takes no WITH READ ONLY.
		"CREATE MATERIALIZED VIEW a AS SELECT 1 FROM dual WITH READ ONLY",
		// ORA-03048 at COLUMN: no object_type_col_properties.
		"CREATE MATERIALIZED VIEW a COLUMN a NOT SUBSTITUTABLE AT ALL LEVELS AS SELECT 1 a FROM dual",
		// ORA-02000 at EDITIONS: the 26 page's UNUSABLE EDITIONS.
		"CREATE MATERIALIZED VIEW a ENABLE QUERY REWRITE UNUSABLE EDITIONS AS SELECT 1 FROM dual",
		// ORA-02000 at the end: the 26 page's QUERY REWRITE ENABLE.
		"ALTER MATERIALIZED VIEW a QUERY REWRITE ENABLE",
		// ORA-00905: REFRESH takes a part before ON QUERY COMPUTATION.
		"ALTER MATERIALIZED VIEW a REFRESH ENABLE ON QUERY COMPUTATION",
		// ORA-03049: nothing follows COMPILE.
		"ALTER MATERIALIZED VIEW a COMPILE REFRESH FAST",
		// ORA-32339: no DROP, TRUNCATE or EXCHANGE of a partition.
		"ALTER MATERIALIZED VIEW a DROP PARTITION a",
		"ALTER MATERIALIZED VIEW a TRUNCATE PARTITION a",
		// ORA-14051 at LOB: no LOB_storage_clause.
		"ALTER MATERIALIZED VIEW a LOB(a) STORE AS(CACHE)",
	}
	for _, sql := range refused {
		t.Run(sql, func(t *testing.T) {
			ParseShouldFail(t, sql)
		})
	}
}
