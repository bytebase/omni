package parser

import (
	"errors"
	"testing"
)

// TestWave10CompatReadings pins every grammar family fixed in Wave 10 to reach
// 46,862 / 46,862 (100.00%) agreement on Oracle 23ai compat.tsv at judge rev 5,
// together with valid Oracle 23ai controls beside each refusal.
func TestWave10CompatReadings(t *testing.T) {
	refused := []string{
		// CREATE LIBRARY strict Oracle 23ai grammar (SHARING before IS|AS, quoted AGENT, no trailing skip).
		`CREATE LIBRARY a`,
		`CREATE LIBRARY a 's'`,
		`CREATE LIBRARY a IS`,
		`CREATE LIBRARY a IS 's' zzz`,
		`CREATE LIBRARY a IS 's' AGENT a`,
		`CREATE LIBRARY a IS 's' AGENT`,
		`CREATE LIBRARY a IS 's' CREDENTIAL`,
		`CREATE LIBRARY a IS 's' SHARING = NONE`,
		`CREATE LIBRARY a IS 's' SHARING = METADATA`,
		`CREATE LIBRARY a.zzz a IS 's'`,

		// GRANT / REVOKE program units: no REVOKE REVOKE, no schema.KIND name.
		`GRANT a TO a.FUNCTION a`,
		`REVOKE REVOKE a FROM PROCEDURE FUNCTION a`,
		`REVOKE REVOKE ALL FROM PROCEDURE FUNCTION a`,
		`REVOKE REVOKE a FROM PROCEDURE a`,

		// ALTER MATERIALIZED VIEW SET SUBPARTITION TEMPLATE SUBPARTITIONS (ORA-14156).
		`ALTER MATERIALIZED VIEW a SET SUBPARTITION TEMPLATE SUBPARTITIONS 1`,
		`ALTER MATERIALIZED VIEW a SET SUBPARTITION TEMPLATE SUBPARTITIONS 1 STORE IN(a)`,
		`ALTER MATERIALIZED VIEW a SET SUBPARTITION TEMPLATE SUBPARTITIONS`,
		`ALTER MATERIALIZED VIEW a SET SUBPARTITION TEMPLATE SUBPARTITION)`,
		`ALTER MATERIALIZED VIEW a SET SUBPARTITION TEMPLATE SUBSET 1`,

		// ALTER MATERIALIZED VIEW / ALTER TABLE INMEMORY column near-misses (ORA-64350).
		`ALTER MATERIALIZED VIEW a INMEMORY INMEMORY FOR QUERY(a)`,
		`ALTER MATERIALIZED VIEW a INMEMORY INMEMORY MEMCOMPRESS FOR QUERY a)`,
		`ALTER MATERIALIZED VIEW a INMEMORY INMEMORY MEMCOMPRESS FOR QUERY zzz(a)`,
		`ALTER MATERIALIZED VIEW a INMEMORY INMEMORY MEMCOMPRESS FOR QUERY(a, a zzz)`,
		`ALTER TABLE a INMEMORY INMEMORY NO`,

		// Bare CREATE AUDIT POLICY with no option (ORA-46373) & bare ALTER PDB SNAPSHOT.
		`CREATE AUDIT POLICY a`,
		`ALTER PLUGGABLE DATABASE SNAPSHOT`,

		// Range partition bound arity, inline multi-column REFERENCES, cluster OBJECT datatype, duplicate PARTITION column.
		`ALTER TABLE a MODIFY PARTITION BY RANGE(a, a)(PARTITION VALUES LESS THAN(1))`,
		`CREATE MATERIALIZED VIEW a PARTITION BY RANGE(a, a)(PARTITION VALUES LESS THAN(1)) AS SELECT 1 FROM dual`,
		`CREATE MATERIALIZED VIEW LOG ON a PARTITION BY RANGE(a, a)(PARTITION VALUES LESS THAN(1))`,
		`CREATE TABLE a(a REFERENCES a(a, a))`,
		`ALTER TABLE a ADD(a NUMBER REFERENCES a(a, a))`,
		`CREATE CLUSTER a(a NUMBER, a OBJECT)`,
		`CREATE TABLE a(PARTITION, PARTITION)`,
		`ALTER TABLE a MODIFY(PARTITION, PARTITION)`,
		`CREATE MATERIALIZED VIEW a(PARTITION, PARTITION) AS SELECT 1 FROM dual`,
	}

	for _, sql := range refused {
		_, err := Parse(sql)
		var pe *ParseError
		if !errors.As(err, &pe) {
			t.Errorf("Parse(%q) = %v; want *ParseError", sql, err)
		}
	}

	accepted := []string{
		// Valid CREATE LIBRARY forms (SHARING before IS|AS, quoted AGENT, optional CREDENTIAL).
		`CREATE LIBRARY a IS 's'`,
		`CREATE LIBRARY a SHARING = NONE IS 's'`,
		`CREATE LIBRARY a SHARING = METADATA AS '/tmp/lib.so' AGENT 'dblink1' CREDENTIAL hr.cred1`,
		`CREATE LIBRARY a IS 's' CREDENTIAL a`,

		// Valid GRANT / REVOKE program-unit forms.
		`GRANT r TO FUNCTION hr.f, PROCEDURE hr.p, PACKAGE hr.pkg`,
		`REVOKE r FROM FUNCTION hr.f, PROCEDURE hr.p`,

		// ALTER TABLE UPGRADE INCLUDING DATA JSON [STORE] AS and VARRAY STORE AS.
		`ALTER TABLE a UPGRADE INCLUDING DATA JSON(a) STORE AS`,
		`ALTER TABLE a UPGRADE INCLUDING DATA JSON(a) AS`,
		`ALTER TABLE a UPGRADE INCLUDING DATA VARRAY a STORE AS`,

		// CREATE INMEMORY JOIN GROUP comma-optional member list.
		`CREATE INMEMORY JOIN GROUP a(a(a) a(a))`,
		`CREATE INMEMORY JOIN GROUP a(s1.t1(a) s2.t2(b))`,
		`CREATE INMEMORY JOIN GROUP a(t1(c1), t2(c2))`,

		// MERGE INTO optional USING when ON directly follows target [alias].
		`MERGE INTO USING s ON (t.id = s.id) WHEN MATCHED THEN UPDATE SET t.x = s.x`,
		`MERGE INTO t ON (t.id = 1) WHEN MATCHED THEN UPDATE SET t.x = 2`,

		// Unnamed PARTITION in SPLIT PARTITION ... NESTED TABLE ... INTO (...).
		`ALTER TABLE a SPLIT PARTITION a AT(1) NESTED TABLE a INTO(PARTITION, PARTITION a)`,
		`ALTER TABLE a SPLIT PARTITION a AT(1) NESTED TABLE a INTO(PARTITION a, PARTITION)`,
		`ALTER MATERIALIZED VIEW a SPLIT PARTITION a AT(1) NESTED TABLE a INTO(PARTITION, PARTITION a)`,
		`ALTER MATERIALIZED VIEW a SPLIT PARTITION a AT(1) NESTED TABLE a INTO(PARTITION a, PARTITION)`,

		// ALTER MATERIALIZED VIEW LOG SPLIT [SUB]PARTITION DEPENDENT TABLES / ALLOW CLUSTERING.
		`ALTER MATERIALIZED VIEW LOG ON a SPLIT PARTITION a AT(1) DEPENDENT TABLES(a(PARTITION))`,
		`ALTER MATERIALIZED VIEW LOG ON a SPLIT PARTITION a AT(1) ALLOW CLUSTERING`,
		`ALTER MATERIALIZED VIEW LOG ON a SPLIT SUBPARTITION a AT(1) DEPENDENT TABLES(a(PARTITION))`,
		`ALTER MATERIALIZED VIEW LOG ON a SPLIT SUBPARTITION a AT(1) ALLOW CLUSTERING`,

		// ALTER MATERIALIZED VIEW MODIFY column with datatype.
		`ALTER MATERIALIZED VIEW a MODIFY(a, a zzz)`,

		// Valid ALTER PLUGGABLE DATABASE SNAPSHOT modes and CREATE AUDIT POLICY with clauses.
		`ALTER PLUGGABLE DATABASE SNAPSHOT EVERY 1 HOURS`,
		`ALTER PLUGGABLE DATABASE SNAPSHOT MANUAL`,
		`CREATE AUDIT POLICY a ACTIONS ALL`,
		`CREATE AUDIT POLICY a ONLY TOPLEVEL`,

		// Valid 2-column RANGE partition with 2-value bound & table-level multi-column FOREIGN KEY.
		`ALTER TABLE a MODIFY PARTITION BY RANGE(a, b)(PARTITION VALUES LESS THAN(1, 2))`,
		`CREATE TABLE a(x NUMBER, y NUMBER, FOREIGN KEY(x, y) REFERENCES b(c1, c2))`,
	}

	for _, sql := range accepted {
		ParseAndCheck(t, sql)
	}
}
