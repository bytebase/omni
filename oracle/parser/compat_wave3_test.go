package parser

import (
	"errors"
	"testing"

	"github.com/bytebase/omni/oracle/ast"
)

// TestWave3CompatReadings pins the Wave 3 grammar families moved to Oracle
// 23.26.3's exact byte offsets, together with valid Oracle SQL controls beside
// each refusal.
func TestWave3CompatReadings(t *testing.T) {
	refusedAt := []struct {
		sql  string
		want int
	}{
		// NESTED TABLE ... STORE AS storage ( ... unclosed '(' blames nested item.
		{`CREATE TABLE a NESTED TABLE a STORE AS a(`, 28},
		{`CREATE TABLE a NESTED TABLE a STORE AS a((a)`, 28},
		{`CREATE MATERIALIZED VIEW a NESTED TABLE a STORE AS a((a)`, 40},
		{`CREATE MATERIALIZED VIEW a NESTED TABLE a STORE AS a((SUPPLEMENTAL LOG GROUP a(a)`, 40},

		// Partition / subpartition clauses: ADD/MODIFY/MERGE/SPLIT/bounds/OVERFLOW/template.
		{`CREATE TABLE a PARTITION BY HASH(a)(PARTITION a zzz)`, 46},
		{`CREATE TABLE a PARTITION BY HASH(a)(PARTITION READS ONLY)`, 46},
		{`CREATE TABLE a PARTITION BY HASH(a)(PARTITION COMPRESS zzz)`, 46},
		{`CREATE TABLE a PARTITION BY HASH(a)(PARTITION NOCOMPRESS zzz)`, 46},
		{`CREATE MATERIALIZED VIEW a PARTITION BY HASH(a)(PARTITION a zzz) AS SELECT 1 FROM dual`, 58},
		{`CREATE MATERIALIZED VIEW a PARTITION BY HASH(a)(PARTITION COMPRESS zzz) AS SELECT 1 FROM dual`, 58},
		{`CREATE MATERIALIZED VIEW LOG ON a PARTITION BY HASH(a)(PARTITION a zzz)`, 65},
		{`CREATE TABLE a PARTITION BY RANGE(a)(PARTITION VALUES LESS THAN(MAX_AUDIT_SIZE))`, 78},
		{`CREATE TABLE a PARTITION BY LIST(a)(PARTITION VALUES(DEFAULT_COLLATION))`, 70},
		{`CREATE TABLE a PARTITION BY LIST(a)(PARTITION VALUES(NULLS))`, 58},
		{`CREATE MATERIALIZED VIEW a PARTITION BY HASH(a) SUBPARTITION BY RANGE(a) SUBPARTITION TEMPLATE(SUBPARTITION VALUES LESS THAN(1) INDEXING ON) PARTITIONS 1 AS SELECT 1 FROM dual`, 128},
		{`CREATE MATERIALIZED VIEW a PARTITION BY HASH(a) SUBPARTITION BY RANGE(a) SUBPARTITION TEMPLATE(SUBPARTITION VALUES LESS THAN(1) INDEXING) PARTITIONS 1 AS SELECT 1 FROM dual`, 128},
		{`ALTER TABLE a ADD PARTITION a zzz`, 28},
		{`ALTER TABLE a ADD PARTITION UPDATE`, 28},
		{`ALTER TABLE a MODIFY PARTITION a ADD SUBPARTITION UPDATE`, 50},
		{`ALTER MATERIALIZED VIEW LOG ON a MODIFY PARTITION a ADD SUBPARTITION UPDATE INDEXES`, 69},
		{`ALTER TABLE a SPLIT PARTITION a INTO PARTITION, PARTITION)`, 37},
		{`ALTER TABLE a SPLIT PARTITION a AT(1) INTO PARTITION, PARTITION)`, 43},
		{`ALTER TABLE a SPLIT SUBPARTITION a INTO SUBPARTITION, SUBPARTITION)`, 52},
		{`ALTER TABLE a SPLIT PARTITION a AT(1) NESTED TABLE a(PARTITION a, PARTITION a)`, 51},
		{`ALTER MATERIALIZED VIEW a SPLIT PARTITION a AT(1) NESTED TABLE a(PARTITION a, PARTITION a)`, 63},
		{`ALTER TABLE a ADD PARTITION VALUES LESS THAN(MAX_AUDIT_SIZE)`, 59},
		{`ALTER TABLE a ADD PARTITION VALUES(DEFAULT_COLLATION)`, 52},

		// CREATE/ALTER TABLE & VIEW column datatypes, constraints, and table properties.
		{`CREATE TABLE a(PARTITION VARRAY a STORE AS LOB a)`, 32},
		{`CREATE TABLE a(PARTITION NESTED TABLE a STORE AS a)`, 32},
		{`CREATE TABLE a(a GLOBAL ALWAYS AS(1))`, 24},
		{`ALTER TABLE a ADD(a GLOBAL ALWAYS AS(1))`, 27},
		{`ALTER TABLE a MODIFY(a GLOBAL ALWAYS AS IDENTITY)`, 30},
		{`CREATE TABLE a(a REFRESH a)`, 25},
		{`ALTER TABLE a MODIFY(a REFRESH a)`, 31},
		{`CREATE TABLE a(a FOREIGN KEY(a) REFERENCES a)`, 25},
		{`CREATE TABLE a(a CHECKPOINT(1 = 1))`, 17},
		{`CREATE TABLE a(DOUBLE a(a))`, 22},
		{`CREATE TABLE a(a GENERATED AS(1))`, 27},
		{`ALTER TABLE a ADD(a GENERATED AS(1))`, 30},
		{`ALTER TABLE a MODIFY(a GENERATED AS(1))`, 33},
		{`CREATE TABLE a(a DEFAULT ON NULL INSERT ONLY 1)`, 33},
		{`ALTER TABLE a MODIFY(a GENERATED ALWAYS AS IDENTITY(NOMAXVALUE NOMAXVALUE))`, 63},
		{`ALTER TABLE a MODIFY(a GENERATED ALWAYS AS IDENTITY(NOMAXVALUE NOMAXVALUE zzz))`, 63},
		{`CREATE TABLE a(SUPPLEMENTAL LOG GROUP(a))`, 15},
		{`ALTER TABLE a ADD SUPPLEMENTAL LOG GROUP(a)`, 18},
		{`ALTER TABLE a RENAME LOB(a) TO a`, 28},
		{`ALTER TABLE a RENAME LOB(a) a`, 29},
		{`ALTER TABLE a DROP(PERIOD FOR a`, 26},
		{`ALTER TABLE a ENABLE LOGICAL REPLICATION ALL`, 41},
		{`ALTER TABLE a ENABLE LOGICAL REPLICATION ALLOW NOVALIDATE`, 47},
		{`ALTER TABLE a MODIFY CLUSTERING COALESCE BY(a)`, 32},
		{`ALTER TABLE a INMEMORY NO INMEMORY zzz(a)`, 23},
		{`ALTER TABLE a INMEMORY INMEMORY NO MEMCOMPRESS zzz(a)`, 32},
		{`CREATE TABLE a ILM ENABLE zzz POLICY a`, 15},
		{`CREATE TABLE a ILM DISABLE zzz POLICY a`, 15},
		{`CREATE VIEW a(a CONSTRAINT a zzz UNIQUE) AS SELECT 1 FROM dual`, 16},
		{`CREATE GLOBAL TABLE a(a NUMBER)`, 7},
		{`CREATE PRIVATE TABLE a(a NUMBER)`, 7},

		// Reserved object / schema / user / dblink names and CREATE IF EXISTS / IF NOT.
		{`DROP TABLE EXISTS a`, 11},
		{`CREATE DIRECTORY AS 's'`, 17},
		{`CREATE PACKAGE IS END;`, 15},
		{`CREATE TYPE BODY IS END;`, 17},
		{`CREATE USER IDENTIFIED BY "Temp#12345"`, 12},
		{`CREATE TABLE IF EXISTS a(a NUMBER)`, 13},
		{`CREATE FUNCTION IF NOT`, 16},
		{`ALTER MATERIALIZED VIEW ON a`, 24},

		// GRANT checks.
		{`GRANT ALL`, 6},
		{`GRANT ALL PROCEDURE ON a TO a`, 6},

		// OPAQUE / XMLTYPE / XMLSCHEMA / MVIEW REFRESH.
		{`ALTER TABLE a MODIFY OPAQUE a STORE AS LOB(LOGGING)`, 28},
		{`CREATE MATERIALIZED VIEW a XMLTYPE AS SELECT 1 FROM dual`, 35},
		{`CREATE MATERIALIZED VIEW a XMLTYPE a ELEMENT a STORE VARRAYS AS LOBS AS SELECT 1 FROM dual`, 47},
		{`CREATE MATERIALIZED VIEW a REFRESH START WITH AS SELECT 1 FROM dual`, 46},
		{`CREATE MATERIALIZED VIEW a REFRESH NEXT AS SELECT 1 FROM dual`, 40},

		// Query, DML, and utility statements.
		{`UPDATE SET a = 1`, 7},
		{`UPDATE a SET a =(SELECT 1 FROM dual`, 17},
		{`UPDATE a SET(a) =(SELECT 1 FROM dual`, 18},
		{`UPDATE a SET VALUE(a) =(SELECT 1 FROM dual`, 24},
		{`DELETE FROM t RETURNING INTO :x`, 24},
		{`ANALYZE TABLE VALIDATE STRUCTURE`, 14},
		{`MERGE a USING b ON(1 = 1) WHEN MATCHED THEN UPDATE SET a = 1`, 6},
		{`SELECT * FROM a AS SCN 1`, 16},
		{`SELECT * FROM a START WITH 1 = 1`, 16},
		{`SELECT * FROM a SAMPLE BLOCK zzz(1)`, 23},
		{`LOCK TABLE a PARTITION(a IN EXCLUSIVE MODE`, 13},
		{`FLASHBACK TABLE a TO BEFORE`, 21},

		// Other DDL clauses.
		{`ADMINISTER KEY MANAGEMENT SET KEY IDENTIFIED BY a FORCE`, 50},
		{`ADMINISTER KEY MANAGEMENT EXPORT KEYS WITH SECRET a TO 's' IDENTIFIED BY a WITH IDENTIFIER IN a)`, 94},
		{`ALTER PLUGGABLE DATABASE CREATE SNAPSHOT a`, 25},
		{`ALTER PLUGGABLE DATABASE SET NOLOGGING FOR LOAD PERFORMANCE`, 25},
		{`CREATE PLUGGABLE DATABASE a AS SEED`, 31},
		{`CREATE PLUGGABLE DATABASE a CONTAINER_MAP UPDATE(ADD PARTITION a LESS THAN(1))`, 63},
		{`CREATE PLUGGABLE DATABASE a CONTAINER_MAP UPDATE(SPLIT PARTITION a AT(1) INTO(PARTITION a PARTITION a))`, 88},
		{`CREATE MLE MODULE a LANGUAGE JAVASCRIPT USING CLOB SELECT 1 FROM dual)`, 46},
		{`CREATE INMEMORY JOIN GROUP a(a(a) a(a))`, 29},
		{`CREATE PROPERTY GRAPH a VERTEX TABLES(a PROPERTIES(AS a))`, 51},
		{`CREATE INDEX a ON a(a) INDEXTYPE IS a LOCAL(PARTITION PARAMETERS('s'`, 65},
		{`CREATE OPERATOR a BINDING(RETURN NUMBER USING a`, 26},
		{`CREATE DOMAIN a AS ANY(a)`, 19},
		{`ALTER USECASE zzz DOMAIN a DROP DISPLAY`, 6},
		{`CREATE RESTORE POINT a AS OF TIMESTAMP zzz 1`, 39},
		{`CREATE RESTORE POINT a AS OF SCN zzz 1`, 33},
		{`AUDIT POLICY a BY WITH ROLE a`, 18},
	}

	for _, tc := range refusedAt {
		_, err := Parse(tc.sql)
		if err == nil {
			t.Errorf("Parse(%q) accepted; want rejection at byte %d", tc.sql, tc.want)
			continue
		}
		var pe *ParseError
		if !errors.As(err, &pe) || pe.Position != tc.want {
			t.Errorf("Parse(%q) failed with %v; want ParseError at byte %d", tc.sql, err, tc.want)
		}
	}

	// Valid Oracle SQL controls beside the Wave 3 refusals.
	accepted := []string{
		`CREATE TABLE t (id NUMBER) NESTED TABLE nt STORE AS nt_tab ((PRIMARY KEY (NESTED_TABLE_ID)))`,
		`CREATE TABLE t (a NUMBER) PARTITION BY HASH (a) (PARTITION p1 TABLESPACE ts1, PARTITION p2 COMPRESS)`,
		`CREATE TABLE t (a NUMBER) PARTITION BY RANGE (a) (PARTITION p1 VALUES LESS THAN (10), PARTITION pmax VALUES LESS THAN (MAXVALUE))`,
		`CREATE TABLE t (a NUMBER) PARTITION BY LIST (a) (PARTITION p1 VALUES (1, 2), PARTITION pdef VALUES (DEFAULT))`,
		`ALTER TABLE t SPLIT PARTITION p1 AT (10) INTO (PARTITION p1a, PARTITION p1b)`,
		`ALTER TABLE t SPLIT PARTITION p1 AT (10) NESTED TABLE nt INTO (PARTITION nt1, PARTITION nt2)`,
		`ALTER TABLE t RENAME LOB (c1) old_lob_seg TO new_lob_seg`,
		`ALTER TABLE t DROP (PERIOD FOR valid_time)`,
		`ALTER TABLE t ENABLE LOGICAL REPLICATION ALL KEYS`,
		`ALTER TABLE t ENABLE LOGICAL REPLICATION ALLOW NOVALIDATE KEYS`,
		`ALTER TABLE t MODIFY CLUSTERING YES ON LOAD`,
		`ALTER TABLE t INMEMORY NO INMEMORY (c1)`,
		`ALTER TABLE t MODIFY (c1 GENERATED ALWAYS AS IDENTITY (NOMAXVALUE NOCYCLE))`,
		`CREATE TABLE t (partition partition, c2 only, c3 nocopy, c4 inner)`,
		`ALTER TABLE t MODIFY (partition partition)`,
		`CREATE TABLE t (c1 NUMBER DEFAULT ON NULL FOR INSERT ONLY 1)`,
		`CREATE TABLE t (c1 NUMBER GENERATED ALWAYS AS (1 + 1))`,
		`CREATE TABLE t (c1 NUMBER, SUPPLEMENTAL LOG GROUP grp1 (c1))`,
		`CREATE TABLE t (c1 NUMBER) ILM ENABLE POLICY p1`,
		`CREATE VIEW v (c1 CONSTRAINT c1_uq UNIQUE DISABLE) AS SELECT 1 FROM dual`,
		`CREATE TABLE IF NOT EXISTS t (a NUMBER)`,
		`DROP TABLE IF EXISTS t`,
		`GRANT ALL PRIVILEGES ON s.t TO u`,
		`CREATE MATERIALIZED VIEW mv REFRESH START WITH SYSDATE NEXT SYSDATE + 1 AS SELECT 1 FROM dual`,
		`CREATE RESTORE POINT rp AS OF TIMESTAMP SYSTIMESTAMP`,
		`CREATE RESTORE POINT rp AS OF SCN 12345`,
		`AUDIT POLICY p BY USERS WITH GRANTED ROLES dba`,
		`ALTER USECASE DOMAIN d DROP DISPLAY`,
		`CREATE DOMAIN d AS NUMBER NOT NULL`,
		`CREATE INDEX idx ON t (c1) INDEXTYPE IS ctxsys.context LOCAL (PARTITION p1 PARAMETERS ('s'))`,
		`CREATE PLUGGABLE DATABASE pdb1 FROM src CONTAINER_MAP UPDATE (SPLIT PARTITION p1 AT (10) INTO (PARTITION p1a, PARTITION p1b))`,
		`LOCK TABLE t PARTITION (p1) IN EXCLUSIVE MODE`,
		`MERGE INTO t USING s ON (t.id = s.id) WHEN MATCHED THEN UPDATE SET t.v = s.v`,
		`UPDATE t SET a = 1 WHERE b = 2 RETURNING a INTO :x`,
		`UPDATE t SET a = (SELECT 1 FROM dual) + 1`,
		`UPDATE t SET VALUE(a) = (SELECT 1 FROM dual) + 1`,
		`UPDATE t SET "UID" = 1`,
		`DROP TABLE "UID"`,
		`DROP TABLE "RESOURCE"`,
		`DROP TABLE "MLSLABEL"`,
		`CREATE USER "UID" IDENTIFIED BY secret`,
		`FLASHBACK TABLE t TO BEFORE DROP`,
	}

	for _, sql := range accepted {
		list, err := Parse(sql)
		if err != nil {
			t.Errorf("Parse(%q) failed: %v", sql, err)
			continue
		}
		if list == nil || len(list.Items) != 1 {
			t.Errorf("Parse(%q) returned %d statements; want 1", sql, len(list.Items))
			continue
		}
		raw, ok := list.Items[0].(*ast.RawStmt)
		if !ok || raw.Stmt == nil {
			t.Errorf("Parse(%q) item is %T; want non-nil *ast.RawStmt", sql, list.Items[0])
		}
	}
}
