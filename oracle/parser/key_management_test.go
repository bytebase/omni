package parser

import (
	"errors"
	"testing"
)

// TestAdministerKeyManagementGrammar holds forms Oracle Free 23.26.3
// answered: accepted ones (refused only for the privilege, ORA-01031, after
// the parse), and refused ones with the byte omni reports.
func TestAdministerKeyManagementGrammar(t *testing.T) {
	const akm = "ADMINISTER KEY MANAGEMENT "
	accepts := []string{
		"SET KEY USING ALGORITHM 'AES256' IDENTIFIED BY a",
		"CREATE ENCRYPTION KEY 'mk' USING TAG 't' USING ALGORITHM 'ARIA256' IDENTIFIED BY a",
		"SET KEY 'mkid:mk' IDENTIFIED BY a",
		"SET KEY IDENTIFIED BY \"Pw\"",
		"SET KEY IDENTIFIED BY KEY",
		"SET KEY IDENTIFIED BY \"UID\"",
		"SET KEY IDENTIFIED BY \"EXTERNAL STORE\" REVERSE MIGRATE USING b",
		"SET ENCRYPTION KEY USING TAG 't' FORCE KEYSTORE IDENTIFIED BY EXTERNAL STORE WITH BACKUP USING 'b' CONTAINER = CURRENT",
		"SET KEY USING TAG 't' IDENTIFIED BY a FORCE KEYSTORE MIGRATE USING b",
		"SET KEY IDENTIFIED BY a REVERSE MIGRATE USING b WITH BACKUP",
		"USE KEY 'k' USING TAG 't' FORCE KEYSTORE IDENTIFIED BY a WITH BACKUP USING 'b'",
		"USE ENCRYPTION KEY 'k' IDENTIFIED BY a MIGRATE USING b",
		"SET TAG 't' FOR 'k' IDENTIFIED BY EXTERNAL STORE",
		"SET KEYSTORE OPEN FORCE KEYSTORE IDENTIFIED BY EXTERNAL STORE CONTAINER = ALL",
		"SET KEYSTORE CLOSE CONTAINER = ALL",
		"BACKUP KEYSTORE USING \"b\" FORCE KEYSTORE IDENTIFIED BY a TO 'x'",
		"ALTER KEYSTORE PASSWORD FORCE KEYSTORE IDENTIFIED BY a SET b",
		"SET KEY IDENTIFIED BY a WITH BACKUP USING N'b'",
		"MERGE KEYSTORE 's' IDENTIFIED BY a AND KEYSTORE 's' IDENTIFIED BY b INTO NEW KEYSTORE 's' IDENTIFIED BY c",
		"MERGE KEYSTORE 's' INTO EXISTING KEYSTORE 's' IDENTIFIED BY a WITH BACKUP USING 'b'",
		"FORCE ISOLATE KEYSTORE IDENTIFIED BY a FROM ROOT KEYSTORE IDENTIFIED BY a",
		"UNITE KEYSTORE IDENTIFIED BY a WITH ROOT KEYSTORE FORCE KEYSTORE IDENTIFIED BY a WITH BACKUP USING 'b'",
		"EXPORT KEYS WITH SECRET \"q\" TO 'f' IDENTIFIED BY a WITH IDENTIFIER IN 'k', 'j'",
		"EXPORT KEYS WITH SECRET a TO 's' IDENTIFIED BY a WITH IDENTIFIER IN (SELECT 'k' FROM dual)",
		"EXPORT KEYS WITH SECRET a TO 's' IDENTIFIED BY a WITH IDENTIFIER IN(a zzz)",
		"EXPORT KEYS WITH SECRET a TO 's' IDENTIFIED BY a WITH IDENTIFIER IN(a) zzz",
		"IMPORT KEYS WITH SECRET a FROM 's' IDENTIFIED BY EXTERNAL STORE",
		"MOVE ENCRYPTION KEYS TO NEW KEYSTORE 's' IDENTIFIED BY a FROM KEYSTORE IDENTIFIED BY a WITH IDENTIFIER IN 'k', 'j'",
		"MOVE KEYS TO NEW KEYSTORE 's' IDENTIFIED BY a FROM KEYSTORE IDENTIFIED BY a WITH IDENTIFIER IN (SELECT 'k' FROM dual) WITH BACKUP USING 'b'",
		"UPDATE SECRET 's' FOR CLIENT 'c' USING TAG 't' FORCE KEYSTORE IDENTIFIED BY a WITH BACKUP USING 'b'",
		"DELETE SECRET FOR CLIENT 'c' IDENTIFIED BY EXTERNAL STORE",
		"SWITCHOVER TO LIBRARY 's' FOR ALL CONTAINERS",
	}
	for _, sql := range accepts {
		if _, err := Parse(akm + sql); err != nil {
			t.Errorf("Parse(%q): %v", akm+sql, err)
		}
	}
	rejects := []struct {
		sql string
		pos int
	}{
		{"SET KEY USING ALGORITHM AES256 IDENTIFIED BY a", 50},                   // ORA-46679
		{"ADD SECRET a FOR CLIENT 'c' IDENTIFIED BY a", 37},                      // ORA-46607
		{"EXPORT KEYS WITH SECRET 's' TO 'f' IDENTIFIED BY a", 50},               // ORA-46609
		{"SET KEY IDENTIFIED BY 'pw'", 48},                                       // ORA-00988
		{"SET KEY IDENTIFIED BY USER", 48},                                       // ORA-00988
		{"SET KEY FORCE KEYSTORE USING TAG 't' IDENTIFIED BY a", 49},             // ORA-02000
		{"SET KEY IDENTIFIED BY a CONTAINER = ALL WITH BACKUP", 66},              // ORA-03048
		{"SET KEY IDENTIFIED BY EXTERNAL STORE MIGRATE USING b", 63},             // ORA-02000 at 57
		{"SET KEYSTORE IDENTIFIED BY a", 26},                                     // ORA-46602
		{"CREATE KEYSTORE 's' IDENTIFIED BY EXTERNAL STORE", 69},                 // ORA-03049
		{"ALTER KEYSTORE PASSWORD IDENTIFIED BY a SET a FORCE KEYSTORE", 72},     // ORA-03049
		{"MERGE KEYSTORE 's' AND 's' INTO NEW KEYSTORE 's' IDENTIFIED BY a", 49}, // ORA-02000
		{"BACKUP KEYSTORE USING a IDENTIFIED BY a", 48},                          // ORA-00931
		{"SWITCHOVER TO LIBRARY 's' FOR CONTAINERS", 56},                         // ORA-02000
	}
	for _, tt := range rejects {
		_, err := Parse(akm + tt.sql)
		var pe *ParseError
		if !errors.As(err, &pe) {
			t.Errorf("Parse(%q) = %v, want a ParseError", akm+tt.sql, err)
			continue
		}
		if pe.Position != tt.pos {
			t.Errorf("Parse(%q) failed at %d, want %d", akm+tt.sql, pe.Position, tt.pos)
		}
	}
}
