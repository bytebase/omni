// SET's names and scopes as MariaDB reads them, every verdict measured with PREPARE on
// mariadb:11.8.8 on 2026-11-05: a 1064 is the parser's refusal, and any other answer is a
// statement that parsed.
//
// The rules are option_value and option_type, sql_yacc.yy:17128 and 17137, and
// option_value_following_option_type and option_value_no_option_type, sql_yacc.yy:17206 and
// 17250. Every assignment may write a scope, and it names the system variable after it, so
// `SET SESSION @a = 1` is a 1064. GLOBAL, SESSION and LOCAL are also names, and PERSIST and
// PERSIST_ONLY only names, so `SET PERSIST a = 1` is a 1064 where MySQL parses it. The most
// recent scope reaches an assignment that writes none. The lexer reads a word directly before
// a dot as an identifier, reserved or not.
//
// A 1193 or 4081 is the parser's action refusing an unknown variable, and it stops there:
// `SET a = 1 2` answers 1193 where a declared local variable answers 1064. So a row holds one
// only where no text follows the assignment that raised it, and the stored program rows check
// the same forms against a real verdict.
//
// What is not in this table is in set_list_forms_test.go, with SET STATEMENT, which needs a
// statement node of its own.

// TestSetNamesScopesForms holds omni to the recorded verdicts without a server, so a run with
// no Docker still reports a widened or narrowed grammar.
func TestSetNamesScopesForms(t *testing.T) {
	for _, c := range setNamesScopesCases {
		t.Run(c.sql, func(t *testing.T) {
			got, err := parsesAsOneStatement(c.sql)
			if got != c.accept {
				t.Errorf("omni accepts=%v, want %v for %q: %v", got, c.accept, c.sql, err)
			}
		})
	}
}

