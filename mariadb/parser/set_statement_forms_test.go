// SET STATEMENT as MariaDB reads it, every verdict measured with PREPARE on mariadb:11.8.8 on
// 2026-11-05 against a database with a table t: a 1064 is the parser's refusal, and any other
// answer here is a statement that parsed (1295 is PREPARE refusing to carry one it read, 1415 a
// result set a routine may not return, and 1229, 1231 and 1232 a value the variable refuses).
//
// The rules are set_param, sql_yacc.yy:17011, set_stmt_option, 17161, and
// directly_executable_statement, 2089. An option is a name and a value, with no scope, variable
// reference, NAMES or charset form. The statement is any statement, BEGIN or a compound
// statement, but no label, and none of the forms only a stored program has. MySQL and OceanBase
// answer 1064 to all of it.
//
// Not in this table. A 1193, 4081 or 1272 is the parser's action refusing an unknown variable,
// which stops there, as `SET STATEMENT nope = 1 FOR` shows, so no row holds one. Forms omni reads
// nowhere, with SET STATEMENT or without: BEGIN NOT ATOMIC, a top-level IF, WHILE or LOOP, a FOR
// loop, and EXECUTE IMMEDIATE. `SET STATEMENT a = 1 FOR WITH c AS (SELECT 1) UPDATE t SET a = 1`,
// a 1064 omni accepts without the wrapper too.

// TestSetStatementForms holds omni to the recorded verdicts without a server.
func TestSetStatementForms(t *testing.T) {
	for _, c := range setStatementCases {
		t.Run(c.sql, func(t *testing.T) {
			got, err := parsesAsOneStatement(c.sql)
			if got != c.accept {
				t.Errorf("omni accepts=%v, want %v for %q: %v", got, c.accept, c.sql, err)
			}
		})
	}
}

