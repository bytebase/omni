// TestCastTypeForms holds the parser to the recorded verdicts without the server.
func TestCastTypeForms(t *testing.T) {
	for _, c := range castTypeFormCases {
		t.Run(c.sql, func(t *testing.T) {
			_, err := Parse(c.sql)
			if omniAccepts := err == nil; omniAccepts != c.accept {
				t.Errorf("omni accepts=%v, the record says %v for %q: %v", omniAccepts, c.accept, c.sql, err)
			}
		})
	}
}

func TestCastTypeFormsOracle(t *testing.T) {
	o := startMariaDB(t)
	for _, c := range castTypeFormCases {
		t.Run(c.sql, func(t *testing.T) {
			if got := o.prepareParses(t, c.sql); got != c.accept {
				t.Errorf("MariaDB 11.8.8 accepts=%v, the record says %v for %q", got, c.accept, c.sql)
			}
		})
	}
}

// castUnknownTypeCases name no type, which the grammar reads and its action refuses with
// 4161. They can never run, so the parser refuses them, as it does on a column.
