// SET's quoted user variables and a bare DEFAULT in an expression as MariaDB reads them, with the
// forms set_list_forms_test.go does not hold, every verdict measured with PREPARE on
// mariadb:11.8.8 on 2026-11-05: a 1064 is the parser's refusal, and any other answer is a
// statement that parsed.
//
// `'@' ident_or_text` makes a string a user variable's name when it follows the @ directly.
// 'user'@'host' keeps its own rule, and `SELECT @'a'` and `SELECT 1 INTO @'a'` read the same
// name as SET. An empty name is a 1064, where MySQL parses it.
//
// set_expr_or_default, sql_yacc.yy:17558, has DEFAULT beside expr and not inside it, so `SET a =
// (DEFAULT)` and `SET a = 1 + DEFAULT` are 1064s.
//
// Not in this table, because omni still disagrees and each is its own change. A bare @: `SELECT
// @` and `SELECT @ a` parse.

// TestSetValueForms holds omni to the recorded verdicts without a server, so a run with no
// Docker still reports a widened or narrowed grammar.
func TestSetValueForms(t *testing.T) {
	for _, c := range setValueFormCases {
		t.Run(c.sql, func(t *testing.T) {
			got, err := parsesAsOneStatement(c.sql)
			if got != c.accept {
				t.Errorf("omni accepts=%v, want %v for %q: %v", got, c.accept, c.sql, err)
			}
		})
	}
}

