package parser

import "testing"

// MariaDB has no AS OF TIMESTAMP on a table reference: its stale read is FOR SYSTEM_TIME
// AS OF. Every verdict was measured with PREPARE on mariadb:11.8.8 on 2026-11-05: a 1064
// is the parser's refusal, and any other answer means the text parsed. Every form of the
// clause is a 1064. The verdict on `/*T! AS OF TIMESTAMP NOW() */` is a comment's.
//
// Not in this table:
//   - OF is not reserved here, so `FROM t AS of`, `SELECT of FROM t` and `CREATE TABLE of
//     (a INT)` parse, and omni refuses every one. That does not depend on this clause.
//   - `DELETE t FROM t AS OF TIMESTAMP NOW()` and `DELETE FROM t USING t a AS OF TIMESTAMP
//     NOW()` answer 1109 for the target before the server reaches the syntax error, and
//     `DELETE t FROM t x garbage garbage garbage` answers the same, so 1109 there is no
//     verdict. With a target that resolves, as in `DELETE t FROM t t AS OF TIMESTAMP
//     NOW()`, the answer is 1064, and those are in the table.
//   - `FROM t FOR SYSTEM_TIME AS OF TIMESTAMP NOW()` parses and omni refuses it, though it
//     reads the form without the word TIMESTAMP.
//   - `LOCK TABLES t USE INDEX (i) READ` is a 1064 and omni accepts it.

// asOfCase is a statement and whether the engine's parser accepts it.
type asOfCase struct {
	sql    string
	accept bool
}

// TestAsOfForms holds omni to the recorded verdicts without a server.
func TestAsOfForms(t *testing.T) {
	for _, c := range asOfCases {
		t.Run(c.sql, func(t *testing.T) {
			got, err := parsesAsOneStatement(c.sql)
			if got != c.accept {
				t.Errorf("omni accepts=%v, want %v for %q: %v", got, c.accept, c.sql, err)
			}
		})
	}
}

