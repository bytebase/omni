// refuseNativeArgCount holds a call to the count its name takes.
func refuseNativeArgCount(name string, args, pos int) error {
	spec, ok := nativeFunctions[name]
	if !ok {
		return nil
	}
	if args >= spec.min && (spec.max < 0 || args <= spec.max) && (args-spec.min)%spec.step == 0 {
		return nil
	}
	return &ParseError{Message: "Incorrect parameter count in the call to native function '" + name + "'", Position: pos}
}
