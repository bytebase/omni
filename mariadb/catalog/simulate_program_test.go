// TestProgramSimulation holds the catalog to testdata/programs/simulate.tsv:
// stored procedures, stored functions, triggers and events written as an
// application writes them, run across the object fixtures, with what MariaDB
// did and what Exec does. The compat.tsv statements on these objects are in
// TestSimulation already; these rows carry mysql/catalog's programs corpus to
// MariaDB with real names, values and bodies, and add MariaDB's own forms: OR
// REPLACE, IF NOT EXISTS on routines and triggers, parameter modes and
// defaults on functions, ROW and TYPE OF parameters, FOR loops, and stored
// aggregate functions. Packages are left out: the catalog models none.
//
// MariaDB's side is on the test's tape (testdata/tapes/TestProgramSimulation.tape),
// so the test starts no server. OMNI_RECORD=1 runs every row on the pinned
// MariaDB again; -update-compat commits the rows a catalog fix brought to
// MariaDB's outcome; and -simulate-show=<text> prints both schemas of the rows
// that hold the text.
func TestProgramSimulation(t *testing.T) {
	simulate.Check(t, simulate.Suite{
		Path:     filepath.Join("testdata", "programs", "simulate.tsv"),
		Pins:     testcontainer.Pins,
		Fixtures: filepath.Join("testdata", "fixtures"),
		Rows:     programSimulationRows(),
		Omni:     simulationOmni,
		Engine:   simulationEngine,
	})
}

