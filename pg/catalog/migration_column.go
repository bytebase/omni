package catalog

import (
	"fmt"
	"sort"
	"strings"
	"unicode"
)

// generateColumnDDL produces ALTER TABLE … ADD/DROP/ALTER COLUMN operations
// for every column change within modified relations.
func generateColumnDDL(from, to *Catalog, diff *SchemaDiff) []MigrationOp {
	var ops []MigrationOp
	var nnTracker *nnMigrationNameTracker
	if to != nil && to.Version() >= PG18 {
		nnTracker = newNNMigrationNameTracker(from, diff)
	}

	// Process modified relations in the exact deterministic (SchemaName, Name)
	// order that PhaseMain executes them so nnTracker reflects earlier column
	// ADD / SET NOT NULL / DROP NOT NULL / RENAME CONSTRAINT mutations.
	var modRels []RelationDiffEntry
	for _, rel := range diff.Relations {
		if rel.Action != DiffModify || len(rel.Columns) == 0 {
			continue
		}
		// Skip views and materialized views — column changes are handled by
		// view DDL (CREATE OR REPLACE VIEW / DROP+CREATE MATERIALIZED VIEW).
		if rel.To != nil && (rel.To.RelKind == 'v' || rel.To.RelKind == 'm') {
			continue
		}
		modRels = append(modRels, rel)
	}
	sort.SliceStable(modRels, func(i, j int) bool {
		if modRels[i].SchemaName != modRels[j].SchemaName {
			return modRels[i].SchemaName < modRels[j].SchemaName
		}
		return modRels[i].Name < modRels[j].Name
	})

	for _, rel := range modRels {
		tableName := fmt.Sprintf("%s.%s", quoteIdentifier(rel.SchemaName), quoteIdentifier(rel.Name))
		if (rel.To != nil && rel.To.Persistence == 't') || isTempSchemaName(rel.SchemaName) {
			tableName = quoteIdentifier(rel.Name)
		}

		// Resolve the owning relation OID for column metadata.
		var relOID uint32
		if rel.To != nil {
			relOID = rel.To.OID
		}

		for _, col := range rel.Columns {
			switch col.Action {
			case DiffAdd:
				colOps := columnAddOps(to, tableName, rel.SchemaName, rel.Name, col)
				if nnTracker != nil && col.To != nil && col.To.NotNull && rel.From != nil && rel.From.Schema != nil {
					addedNN := ""
					if rel.To != nil {
						addedNN = to.notNullConstraintName(rel.To, col.To.AttNum)
					}
					if addedNN == "" || addedNN == makePGObjectName(rel.Name, col.Name, "not_null") {
						addedNN = nnTracker.chooseName(rel.From, rel.Name, col.Name)
					}
					nnTracker.add(rel.From.Schema.OID, addedNN)
				}
				for i := range colOps {
					colOps[i].Phase = PhaseMain
					colOps[i].ObjType = 'r'
					colOps[i].ObjOID = relOID
					colOps[i].Priority = PriorityColumn
				}
				ops = append(ops, colOps...)
			case DiffDrop:
				dropRelOID := relOID
				if rel.From != nil {
					dropRelOID = rel.From.OID
				}
				ops = append(ops, MigrationOp{
					Type:          OpDropColumn,
					SchemaName:    rel.SchemaName,
					ObjectName:    rel.Name,
					SQL:           fmt.Sprintf("ALTER TABLE %s DROP COLUMN %s", tableName, quoteIdentifier(col.Name)),
					Transactional: true,
					Phase:         PhasePre,
					ObjType:       'r',
					ObjOID:        dropRelOID,
					Priority:      PriorityColumn,
				})
			case DiffModify:
				modOps := columnModifyOpsForStmtWithDiff(from, to, diff, nnTracker, "ALTER TABLE", tableName, rel.SchemaName, rel.Name, col, nil)
				for i := range modOps {
					modOps[i].Phase = PhaseMain
					modOps[i].ObjType = 'r'
					modOps[i].ObjOID = relOID
					modOps[i].Priority = PriorityColumn
				}
				ops = append(ops, modOps...)
			}
		}
	}

	// Determinism is ensured by iterating relations (sorted above) and
	// columns (sorted by name in diff). Within a single column's modifications,
	// the insertion order matters (e.g., DROP DEFAULT → ALTER TYPE → SET DEFAULT),
	// so we use stable sort by schema+table only.
	sort.SliceStable(ops, func(i, j int) bool {
		if ops[i].SchemaName != ops[j].SchemaName {
			return ops[i].SchemaName < ops[j].SchemaName
		}
		return ops[i].ObjectName < ops[j].ObjectName
	})

	return ops
}

// columnAddOps generates an ALTER TABLE … ADD COLUMN statement.
func columnAddOps(to *Catalog, tableName, schemaName, relName string, col ColumnDiffEntry) []MigrationOp {
	c := col.To
	typeName := to.FormatType(c.TypeOID, c.TypeMod)

	ddl := fmt.Sprintf("ALTER TABLE %s ADD COLUMN %s %s%s", tableName, quoteIdentifier(c.Name), typeName, formatColumnCollate(to, c))
	if stor := columnExplicitStorage(to, c); stor != "" {
		ddl += " STORAGE " + stor
	}
	if comp := columnExplicitCompression(c); comp != "" {
		ddl += " COMPRESSION " + comp
	}

	if c.NotNull {
		var toRel *Relation
		if to != nil {
			toRel = to.GetRelation(schemaName, relName)
		}
		ddl += " " + formatColumnNotNullClause(to, toRel, c)
	}
	if c.Generated == 's' {
		// Generated stored column — use GENERATED ALWAYS AS syntax, not DEFAULT.
		expr := c.GenerationExpr
		if expr == "" {
			expr = c.Default // catalog sometimes stores it in Default
		}
		if expr != "" {
			ddl += " GENERATED ALWAYS AS (" + expr + ") STORED"
		}
	} else if c.Identity != 0 {
		switch c.Identity {
		case 'a':
			ddl += " GENERATED ALWAYS AS IDENTITY"
		case 'd':
			ddl += " GENERATED BY DEFAULT AS IDENTITY"
		}
	} else if c.HasDefault && c.Default != "" {
		ddl += " DEFAULT " + c.Default
	}

	return []MigrationOp{{
		Type:          OpAddColumn,
		SchemaName:    schemaName,
		ObjectName:    relName,
		SQL:           ddl,
		Transactional: true,
	}}
}

// columnModifyOps generates ALTER TABLE … ALTER COLUMN statements for a
// modified column. Multiple property changes on the same column produce
// multiple ALTER statements; when a type change is combined with an existing
// default, the sequence is DROP DEFAULT → ALTER TYPE → SET DEFAULT.
func columnModifyOps(from, to *Catalog, tableName, schemaName, relName string, col ColumnDiffEntry) []MigrationOp {
	return columnModifyOpsForStmtWithDiff(from, to, nil, nil, "ALTER TABLE", tableName, schemaName, relName, col, nil)
}

func columnModifyOpsForStmt(from, to *Catalog, alterStmt, tableName, schemaName, relName string, col ColumnDiffEntry, skipCheckNames map[string]bool) []MigrationOp {
	return columnModifyOpsForStmtWithDiff(from, to, nil, nil, alterStmt, tableName, schemaName, relName, col, skipCheckNames)
}

func columnModifyOpsForStmtWithDiff(from, to *Catalog, diff *SchemaDiff, nnTracker *nnMigrationNameTracker, alterStmt, tableName, schemaName, relName string, col ColumnDiffEntry, skipCheckNames map[string]bool) []MigrationOp {
	oldCol := col.From
	newCol := col.To
	var ops []MigrationOp

	colRef := fmt.Sprintf("%s %s ALTER COLUMN %s", alterStmt, tableName, quoteIdentifier(newCol.Name))

	addingIdentity := oldCol.Identity == 0 && newCol.Identity != 0
	droppingIdentity := oldCol.Identity != 0 && newCol.Identity == 0

	typeChanged := from.FormatType(oldCol.TypeOID, oldCol.TypeMod) != to.FormatType(newCol.TypeOID, newCol.TypeMod)

	// When type changes and the old column has a default, we must drop the
	// default first, then change the type, then re-set the new default.
	needDefaultSandwich := typeChanged && oldCol.HasDefault && oldCol.Default != ""

	// When type changes, find CHECK constraints on the table that reference
	// the column. PG requires dropping CHECK constraints before ALTER TYPE.
	var checkConstraints []*Constraint
	if typeChanged {
		fromRel := from.GetRelation(schemaName, relName)
		if fromRel != nil {
			for _, con := range from.ConstraintsOf(fromRel.OID) {
				if con.Type != ConstraintCheck || skipCheckNames[con.Name] {
					continue
				}
				// Check if the constraint expression references this column name.
				// A simple heuristic: the CHECK expression text contains the column name.
				// This covers cases like "val > 0" for column "val".
				if containsColumnRef(con.CheckExpr, oldCol.Name) {
					checkConstraints = append(checkConstraints, con)
				}
			}
		}
	}

	// --- DROP CHECK constraints before type change ---
	for _, con := range checkConstraints {
		ops = append(ops, MigrationOp{
			Type:          OpDropConstraint,
			SchemaName:    schemaName,
			ObjectName:    relName,
			SQL:           fmt.Sprintf("%s %s DROP CONSTRAINT %s", alterStmt, tableName, quoteIdentifier(con.Name)),
			Transactional: true,
		})
	}

	// --- DROP DEFAULT before type change (if sandwich) ---
	if needDefaultSandwich {
		ops = append(ops, MigrationOp{
			Type:          OpAlterColumn,
			SchemaName:    schemaName,
			ObjectName:    relName,
			SQL:           fmt.Sprintf("%s DROP DEFAULT", colRef),
			Transactional: true,
		})
	}

	// --- Type or collation change ---
	alterTypeEmitted := typeChanged || columnCollationKey(from, oldCol) != columnCollationKey(to, newCol)
	if alterTypeEmitted {
		newType := to.FormatType(newCol.TypeOID, newCol.TypeMod)
		alterType := fmt.Sprintf("%s TYPE %s%s", colRef, newType, formatColumnCollate(to, newCol))

		// Check if an implicit (assignment) cast exists.
		pathway, _ := from.FindCoercionPathway(oldCol.TypeOID, newCol.TypeOID, 'a')
		if pathway == CoercionNone {
			// Need explicit USING clause.
			alterType += fmt.Sprintf(" USING %s::%s", quoteIdentifier(newCol.Name), newType)
		}

		ops = append(ops, MigrationOp{
			Type:          OpAlterColumn,
			SchemaName:    schemaName,
			ObjectName:    relName,
			SQL:           alterType,
			Transactional: true,
		})
	}

	// --- SET DEFAULT after type change (if sandwich) ---
	if needDefaultSandwich && newCol.HasDefault && newCol.Default != "" {
		ops = append(ops, MigrationOp{
			Type:          OpAlterColumn,
			SchemaName:    schemaName,
			ObjectName:    relName,
			SQL:           fmt.Sprintf("%s SET DEFAULT %s", colRef, newCol.Default),
			Transactional: true,
		})
	}

	// --- Re-add CHECK constraints after type change ---
	// Use the target catalog's constraint expressions (which may reference the new type).
	for _, oldCon := range checkConstraints {
		checkExpr := oldCon.CheckExpr
		validated := oldCon.Validated
		noInherit := oldCon.ConNoInherit
		// Look up the constraint in the target catalog for the updated expression.
		toRel := to.GetRelation(schemaName, relName)
		if toRel != nil {
			for _, newCon := range to.ConstraintsOf(toRel.OID) {
				if newCon.Type == ConstraintCheck && newCon.Name == oldCon.Name {
					checkExpr = newCon.CheckExpr
					validated = newCon.Validated
					noInherit = newCon.ConNoInherit
					break
				}
			}
		}
		sql := fmt.Sprintf("%s %s ADD CONSTRAINT %s CHECK (%s)", alterStmt, tableName, quoteIdentifier(oldCon.Name), checkExpr)
		if noInherit {
			sql += " NO INHERIT"
		}
		if !validated {
			sql += " NOT VALID"
		}
		ops = append(ops, MigrationOp{
			Type:          OpAddConstraint,
			SchemaName:    schemaName,
			ObjectName:    relName,
			SQL:           sql,
			Transactional: true,
		})
	}

	// --- Default change (without type change) ---
	// Skip default changes when identity is being added or dropped, because
	// identity manages its own sequence-based default automatically.
	if !needDefaultSandwich && !typeChanged && !addingIdentity && !droppingIdentity {
		if oldCol.HasDefault && !newCol.HasDefault {
			ops = append(ops, MigrationOp{
				Type:          OpAlterColumn,
				SchemaName:    schemaName,
				ObjectName:    relName,
				SQL:           fmt.Sprintf("%s DROP DEFAULT", colRef),
				Transactional: true,
			})
		} else if newCol.HasDefault && newCol.Default != "" && (oldCol.Default != newCol.Default || !oldCol.HasDefault) {
			ops = append(ops, MigrationOp{
				Type:          OpAlterColumn,
				SchemaName:    schemaName,
				ObjectName:    relName,
				SQL:           fmt.Sprintf("%s SET DEFAULT %s", colRef, newCol.Default),
				Transactional: true,
			})
		}
	}

	// --- DROP IDENTITY (must come before DROP NOT NULL) ---
	if droppingIdentity {
		ops = append(ops, MigrationOp{
			Type:          OpAlterColumn,
			SchemaName:    schemaName,
			ObjectName:    relName,
			SQL:           fmt.Sprintf("%s DROP IDENTITY", colRef),
			Transactional: true,
		})
	}

	// --- NOT NULL change (between DROP IDENTITY and ADD IDENTITY) ---
	// SET NOT NULL must come before ADD IDENTITY (PG requires NOT NULL for identity).
	// DROP NOT NULL must come after DROP IDENTITY.
	if oldCol.NotNull != newCol.NotNull {
		if newCol.NotNull {
			ops = append(ops, MigrationOp{
				Type:          OpAlterColumn,
				SchemaName:    schemaName,
				ObjectName:    relName,
				SQL:           fmt.Sprintf("%s SET NOT NULL", colRef),
				Transactional: true,
			})
			if alterStmt == "ALTER TABLE" && to != nil && to.Version() >= PG18 {
				toRel := to.GetRelation(schemaName, relName)
				var fromRel *Relation
				if from != nil {
					fromRel = from.GetRelation(schemaName, relName)
				}
				if toRel != nil && !ancestorSettingNotNull(from, diff, fromRel, newCol.Name) {
					var toNNCon *Constraint
					for _, con := range to.consByRel[toRel.OID] {
						if con.Type == ConstraintNotNull && len(con.Columns) == 1 && con.Columns[0] == newCol.AttNum {
							toNNCon = con
							break
						}
					}
					var defaultNN string
					if nnTracker != nil {
						defaultNN = nnTracker.chooseName(fromRel, relName, newCol.Name)
					} else {
						defaultNN = predictedSetNotNullName(from, diff, fromRel, relName, newCol.Name)
					}
					finalNN := defaultNN
					if toNNCon != nil && toNNCon.ConIsLocal && toNNCon.Name != "" && toNNCon.Name != defaultNN {
						ops = append(ops, MigrationOp{
							Type:          OpAlterColumn,
							SchemaName:    schemaName,
							ObjectName:    relName,
							SQL:           fmt.Sprintf("%s %s RENAME CONSTRAINT %s TO %s", alterStmt, tableName, quoteIdentifier(defaultNN), quoteIdentifier(toNNCon.Name)),
							Transactional: true,
						})
						finalNN = toNNCon.Name
					}
					if nnTracker != nil && fromRel != nil && fromRel.Schema != nil {
						nnTracker.add(fromRel.Schema.OID, finalNN)
					}
				}
			}
		} else {
			ops = append(ops, MigrationOp{
				Type:          OpAlterColumn,
				SchemaName:    schemaName,
				ObjectName:    relName,
				SQL:           fmt.Sprintf("%s DROP NOT NULL", colRef),
				Transactional: true,
			})
			if nnTracker != nil && from != nil && from.Version() >= PG18 {
				if fromRel := from.GetRelation(schemaName, relName); fromRel != nil && fromRel.Schema != nil {
					if oldNN := from.notNullConstraintName(fromRel, oldCol.AttNum); oldNN != "" {
						nnTracker.remove(fromRel.Schema.OID, oldNN)
					}
				}
			}
		}
	}

	// --- ADD IDENTITY (must come after SET NOT NULL) ---
	if addingIdentity {
		if newCol.Identity == 'a' {
			ops = append(ops, MigrationOp{
				Type:          OpAlterColumn,
				SchemaName:    schemaName,
				ObjectName:    relName,
				SQL:           fmt.Sprintf("%s ADD GENERATED ALWAYS AS IDENTITY", colRef),
				Transactional: true,
			})
		} else if newCol.Identity == 'd' {
			ops = append(ops, MigrationOp{
				Type:          OpAlterColumn,
				SchemaName:    schemaName,
				ObjectName:    relName,
				SQL:           fmt.Sprintf("%s ADD GENERATED BY DEFAULT AS IDENTITY", colRef),
				Transactional: true,
			})
		}
	}

	oldStor := columnExplicitStorage(from, oldCol)
	newStor := columnExplicitStorage(to, newCol)
	if oldStor != newStor || (alterTypeEmitted && newStor != "") {
		mode := newStor
		if mode == "" {
			mode = "DEFAULT"
		}
		ops = append(ops, MigrationOp{
			Type:          OpAlterColumn,
			SchemaName:    schemaName,
			ObjectName:    relName,
			SQL:           fmt.Sprintf("%s SET STORAGE %s", colRef, mode),
			Transactional: true,
		})
	}

	if oldCol.Compression != newCol.Compression || (alterTypeEmitted && newCol.Compression != 0) {
		comp := columnExplicitCompression(newCol)
		if comp == "" {
			comp = "DEFAULT"
		}
		ops = append(ops, MigrationOp{
			Type:          OpAlterColumn,
			SchemaName:    schemaName,
			ObjectName:    relName,
			SQL:           fmt.Sprintf("%s SET COMPRESSION %s", colRef, comp),
			Transactional: true,
		})
	}

	return ops
}

// ancestorSettingNotNull reports whether any ancestor of fromRel is also
// transitioning colName from nullable to NOT NULL in diff (in which case
// recursive SET NOT NULL from the parent already creates the child's constraint).
func ancestorSettingNotNull(from *Catalog, diff *SchemaDiff, fromRel *Relation, colName string) bool {
	if from == nil || diff == nil || fromRel == nil {
		return false
	}
	setting := make(map[string]bool)
	for _, rel := range diff.Relations {
		if rel.Action != DiffModify {
			continue
		}
		for _, c := range rel.Columns {
			if c.Action == DiffModify && c.Name == colName && c.From != nil && c.To != nil && !c.From.NotNull && c.To.NotNull {
				setting[rel.SchemaName+"\x00"+rel.Name] = true
				break
			}
		}
	}
	if len(setting) == 0 {
		return false
	}
	visited := make(map[uint32]bool)
	var walk func(r *Relation) bool
	walk = func(r *Relation) bool {
		if r == nil || visited[r.OID] {
			return false
		}
		visited[r.OID] = true
		var parents []uint32
		if r.PartitionOf != 0 {
			parents = append(parents, r.PartitionOf)
		}
		parents = append(parents, r.InhParents...)
		for _, poid := range parents {
			p := from.relationByOID[poid]
			if p == nil || p.Schema == nil {
				continue
			}
			if setting[p.Schema.Name+"\x00"+p.Name] || walk(p) {
				return true
			}
		}
		return false
	}
	return walk(fromRel)
}

// nnMigrationNameTracker tracks live constraint-name counts per schema across
// PhaseMain column operations (starting from from's namespace after PhasePre
// drops) so generated SET NOT NULL default names account for earlier ADD COLUMN,
// SET NOT NULL, DROP NOT NULL, and RENAME CONSTRAINT statements.
type nnMigrationNameTracker struct {
	from   *Catalog
	counts map[uint32]map[string]int
}

func newNNMigrationNameTracker(from *Catalog, diff *SchemaDiff) *nnMigrationNameTracker {
	t := &nnMigrationNameTracker{
		from:   from,
		counts: make(map[uint32]map[string]int),
	}
	if from == nil {
		return t
	}
	droppedCons := make(map[uint32]bool)
	droppedDomainCons := make(map[uint32]map[string]bool)
	if diff != nil {
		markRelCons := func(r *Relation) {
			if r == nil {
				return
			}
			for _, con := range from.consByRel[r.OID] {
				droppedCons[con.OID] = true
			}
		}
		markRelEntry := func(entry RelationDiffEntry) {
			if entry.From == nil {
				return
			}
			if entry.Action == DiffDrop {
				markRelCons(entry.From)
				return
			}
			if entry.Action != DiffModify {
				return
			}
			dropNames := make(map[string]bool)
			for _, ce := range entry.Constraints {
				if ce.Action == DiffDrop || ce.Action == DiffModify {
					dropNames[ce.Name] = true
				}
			}
			dropCols := make(map[int16]bool)
			for _, col := range entry.Columns {
				if col.Action == DiffDrop && col.From != nil {
					dropCols[col.From.AttNum] = true
				}
			}
			for _, con := range from.consByRel[entry.From.OID] {
				if dropNames[con.Name] {
					droppedCons[con.OID] = true
					continue
				}
				for _, att := range con.Columns {
					if dropCols[att] {
						droppedCons[con.OID] = true
						break
					}
				}
			}
		}
		for _, re := range diff.Relations {
			markRelEntry(re)
		}
		for _, fe := range diff.ForeignTables {
			markRelEntry(fe)
		}
		for _, de := range diff.Domains {
			if de.From == nil {
				continue
			}
			bt := from.typeByOID[de.From.TypeOID]
			if bt == nil {
				continue
			}
			if droppedDomainCons[bt.Namespace] == nil {
				droppedDomainCons[bt.Namespace] = make(map[string]bool)
			}
			if de.Action == DiffDrop {
				for _, dc := range de.From.Constraints {
					droppedDomainCons[bt.Namespace][dc.Name] = true
				}
				continue
			}
			if de.Action == DiffModify && de.To != nil {
				kept := make(map[string]bool, len(de.To.Constraints))
				for _, dc := range de.To.Constraints {
					kept[dc.Name] = true
				}
				for _, dc := range de.From.Constraints {
					if !kept[dc.Name] {
						droppedDomainCons[bt.Namespace][dc.Name] = true
					}
				}
			}
		}
	}

	for _, con := range from.constraints {
		if droppedCons[con.OID] {
			continue
		}
		conNS := con.Namespace
		if conNS == 0 {
			if rel := from.relationByOID[con.RelOID]; rel != nil && rel.Schema != nil {
				conNS = rel.Schema.OID
			}
		}
		if conNS != 0 {
			t.add(conNS, con.Name)
		}
	}
	for typeOID, dt := range from.domainTypes {
		bt := from.typeByOID[typeOID]
		if bt == nil {
			continue
		}
		for _, dc := range dt.Constraints {
			if droppedDomainCons[bt.Namespace][dc.Name] {
				continue
			}
			t.add(bt.Namespace, dc.Name)
		}
	}
	return t
}

func (t *nnMigrationNameTracker) add(nsOID uint32, name string) {
	if t == nil || nsOID == 0 || name == "" {
		return
	}
	if t.counts[nsOID] == nil {
		t.counts[nsOID] = make(map[string]int)
	}
	t.counts[nsOID][name]++
}

func (t *nnMigrationNameTracker) remove(nsOID uint32, name string) {
	if t == nil || nsOID == 0 || name == "" {
		return
	}
	if m := t.counts[nsOID]; m != nil && m[name] > 0 {
		m[name]--
	}
}

func (t *nnMigrationNameTracker) chooseName(fromRel *Relation, relName, colName string) string {
	if t == nil || fromRel == nil || fromRel.Schema == nil {
		return makePGObjectName(relName, colName, "not_null")
	}
	// Check fromRel's schema and any descendant schemas whose column will also
	// receive the recursive NOT NULL constraint.
	nsSet := map[uint32]bool{fromRel.Schema.OID: true}
	if t.from != nil {
		visited := make(map[uint32]bool)
		var collect func(r *Relation, isRoot bool)
		collect = func(r *Relation, isRoot bool) {
			if r == nil || visited[r.OID] {
				return
			}
			visited[r.OID] = true
			if !isRoot {
				if ci, ok := r.colByName[colName]; ok && r.Columns[ci].NotNull {
					return
				}
				if r.Schema != nil {
					nsSet[r.Schema.OID] = true
				}
			}
			for _, childOID := range t.from.findChildRelations(r.OID) {
				collect(t.from.relationByOID[childOID], false)
			}
		}
		collect(fromRel, true)
	}
	nameTaken := func(name string) bool {
		for nsOID := range nsSet {
			if t.counts[nsOID][name] > 0 {
				return true
			}
		}
		return false
	}
	name := makePGObjectName(fromRel.Name, colName, "not_null")
	for i := 1; ; i++ {
		if !nameTaken(name) {
			return name
		}
		name = makePGObjectName(fromRel.Name, colName, fmt.Sprintf("not_null%d", i))
	}
}

// predictedSetNotNullName predicts the PG 18 default NOT NULL constraint name
// that ALTER TABLE ... ALTER COLUMN ... SET NOT NULL will choose during
// PhaseMain after PhasePre drops (DROP TABLE/COLUMN/CONSTRAINT/DOMAIN) have run.
func predictedSetNotNullName(from *Catalog, diff *SchemaDiff, fromRel *Relation, relName, colName string) string {
	return newNNMigrationNameTracker(from, diff).chooseName(fromRel, relName, colName)
}

// containsColumnRef checks whether a CHECK expression text references the
// given column name as a word boundary (not as a substring of another identifier).
func containsColumnRef(expr, colName string) bool {
	lower := strings.ToLower(expr)
	target := strings.ToLower(colName)
	idx := 0
	for {
		pos := strings.Index(lower[idx:], target)
		if pos < 0 {
			return false
		}
		pos += idx
		// Check word boundaries: character before and after must not be alphanumeric/underscore.
		before := pos - 1
		after := pos + len(target)
		leftOK := before < 0 || !isIdentChar(rune(lower[before]))
		rightOK := after >= len(lower) || !isIdentChar(rune(lower[after]))
		if leftOK && rightOK {
			return true
		}
		idx = pos + 1
	}
}

// isIdentChar returns true if the rune can be part of an SQL identifier.
func isIdentChar(r rune) bool {
	return unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_'
}
