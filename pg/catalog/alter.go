func (c *Catalog) atAddColumn(schema *Schema, rel *Relation, relName string, colDef ColumnDef, recursing bool) error {
	// pg: src/backend/commands/tablecmds.c — ATExecAddColumn (MaxHeapAttributeNumber check)
	if len(rel.Columns) >= MaxHeapAttributeNumber {
		return &Error{Code: CodeTooManyColumns, Message: fmt.Sprintf("tables can have at most %d columns", MaxHeapAttributeNumber)}
	}

	// pg: src/backend/commands/tablecmds.c — check_for_column_name_collision
	if _, exists := rel.colByName[colDef.Name]; exists {
		return errColumnAlreadyExists(colDef.Name, rel.Name)
	}

	typeOID, typmod, err := c.ResolveType(colDef.Type)
	if err != nil {
		return err
	}
	typ := c.typeByOID[typeOID]
	var userCollOID uint32
	collSchema := colDef.CollationSchema
	if colDef.CollClause != nil {
		var cerr error
		_, userCollOID, cerr = c.resolveColumnCollation(colDef.CollClause.Collname, typeOID)
		if cerr != nil {
			return cerr
		}
		collSchema = c.resolvedCollationSchema(colDef.CollClause.Collname, colDef.CollationName, userCollOID)
	}
	stor, err := c.resolveColumnStorage(typ, colDef.StorageName)
	if err != nil {
		return err
	}
	comp, err := c.resolveColumnCompression(typ, colDef.Compression)
	if err != nil {
		return err
	}
	if err := c.checkCompositeSelfReference(rel.RowTypeOID, typeOID, rel.Name); err != nil {
		return err
	}

	var identitySeq *Sequence
	var identityDefault string
	if colDef.Identity == 'a' || colDef.Identity == 'd' {
		if !recursing {
			seq, seqRV, explicitName, err := c.createIdentitySequence(schema, relName, colDef.Name, rel.OwnerName, typeOID, colDef.IdentityOptions)
			if err != nil {
				return err
			}
			colDef.IdentitySequence = seqRV
			identitySeq = seq
			identityDefault = identitySequenceDefault(schema, seq.Schema, seq.Name, explicitName)
		}
		colDef.NotNull = true
	}

	col := &Column{
		AttNum:           int16(len(rel.Columns) + 1),
		Name:             colDef.Name,
		TypeOID:          typeOID,
		TypeMod:          typmod,
		NotNull:          colDef.NotNull,
		Len:              typ.Len,
		ByVal:            typ.ByVal,
		Align:            typ.Align,
		Storage:          stor,
		Compression:      comp,
		Collation:        c.effectiveColumnCollation(typeOID, colDef.CollationName, userCollOID),
		CollationSchema:  collSchema,
		CollationName:    colDef.CollationName,
		UserCollationOID: userCollOID,
	}
	if colDef.Default != "" || colDef.RawDefault != nil {
		col.HasDefault = true
		col.Default = colDef.Default
	}
	if colDef.Generated == 's' {
		col.Generated = 's'
		col.HasDefault = true
		col.Default = colDef.GenerationExpr
	}
	if colDef.Identity == 'a' || colDef.Identity == 'd' {
		col.Identity = colDef.Identity
		if !recursing {
			col.HasDefault = true
			col.Default = identityDefault
		}
	}

	rel.Columns = append(rel.Columns, col)
	rel.colByName[col.Name] = len(rel.Columns) - 1
	if userCollOID != 0 {
		c.recordDependency('r', rel.OID, int32(col.AttNum), 'L', userCollOID, 0, DepNormal)
	}
	if identitySeq != nil {
		identitySeq.OwnerRelOID = rel.OID
		identitySeq.OwnerAttNum = col.AttNum
		c.recordDependency('s', identitySeq.OID, 0, 'r', rel.OID, int32(col.AttNum), DepAuto)
	}
	return nil
}

// atDropColumn drops a column from a relation. recursing is set when the
// drop reaches an inheritance child or partition from its parent.
//
// pg: src/backend/commands/tablecmds.c — ATExecDropColumn
func (c *Catalog) atDropColumn(schema *Schema, rel *Relation, colName string, cascade, ifExists, recursing bool) error {
	idx, exists := rel.colByName[colName]
	if !exists {
		if ifExists {
			return nil
		}
		return errUndefinedColumn(colName)
	}

	// Don't drop inherited columns, unless recursing. A child column that
	// another parent or a local definition also provides survives the
	// parent's drop with one fewer parent.
	col := rel.Columns[idx]
	if recursing && (col.InhCount > 1 || col.InhCount == 1 && col.IsLocal) {
		col.InhCount--
		return nil
	}
	if !recursing && col.InhCount > 0 {
		return &Error{
			Code:    CodeInvalidTableDefinition,
			Message: fmt.Sprintf("cannot drop inherited column %q", colName),
		}
	}

	// Cannot drop a column named in partition key.
	// pg: src/backend/commands/tablecmds.c — ATExecDropColumn (partition key check)
	if err := checkNotPartitionKey(rel, col); err != nil {
		return err
	}

	// Drop the objects that depend on this column. Those linked only by
	// NORMAL entries (views, generated columns, foreign keys referencing the
	// column, triggers naming it) need CASCADE; those with an AUTO entry
	// (its indexes, constraints and owned sequences) go with it regardless.
	//
	// pg: src/backend/commands/tablecmds.c — ATExecDropColumn (performDeletion
	// of the column); src/backend/catalog/dependency.c — reportDependentObjects
	deps := c.relationDependents(rel.OID, col.AttNum)
	if hasNormalDependent(deps) && !cascade {
		return errDependentObjects("column", colName)
	}
	var depCols []string
	for _, d := range deps {
		if d.ObjType == 'r' && d.ObjOID == rel.OID {
			// A generated column of this table reads the column.
			if d.ObjSubID >= 1 && int(d.ObjSubID) <= len(rel.Columns) {
				depCols = append(depCols, rel.Columns[d.ObjSubID-1].Name)
			}
			continue
		}
		if d.ObjType == 'r' && d.ObjSubID != 0 {
			continue
		}
		c.dropDependentObject(d.ObjType, d.ObjOID)
	}
	// Drop dependent columns by name: each drop renumbers the columns after it.
	for _, name := range depCols {
		if err := c.atDropColumn(schema, rel, name, true, true, recursing); err != nil {
			return err
		}
	}
	idx = rel.colByName[colName]
	col = rel.Columns[idx]

	// Drop indexes and constraints that reference this column. Their
	// dependency entries normally cover them; this also catches those that
	// record none on the column (constraints cloned to a partition).
	//
	// pg: src/backend/catalog/dependency.c — reportDependentObjects
	// Indexes and constraints have DEPENDENCY_AUTO on the column.
	// AUTO dependencies are auto-cascaded even under DROP_RESTRICT
	// (only DEPENDENCY_NORMAL blocks RESTRICT). So we drop them
	// unconditionally, matching PG behavior.
	attNum := col.AttNum
	var indexesToDrop []*Index
	for _, ix := range c.indexesByRel[rel.OID] {
		for _, a := range ix.Columns {
			if a == attNum {
				indexesToDrop = append(indexesToDrop, ix)
				break
			}
		}
	}
	for _, ix := range indexesToDrop {
		// If the index backs a constraint, drop the constraint too.
		if ix.ConstraintOID != 0 {
			if con := c.constraints[ix.ConstraintOID]; con != nil {
				c.removeConstraint(schema, con)
			}
		}
		c.removeIndex(schema, ix.Name, ix)
	}

	// Drop non-index-backed constraints (e.g. CHECK) that reference this column.
	// These also have DEPENDENCY_AUTO on the column in pg.
	var consToDrop []*Constraint
	for _, con := range c.consByRel[rel.OID] {
		if con.IndexOID != 0 {
			continue // already handled above
		}
		for _, a := range con.Columns {
			if a == attNum {
				consToDrop = append(consToDrop, con)
				break
			}
		}
	}
	for _, con := range consToDrop {
		c.removeConstraint(schema, con)
	}

	// Remove the column.
	rel.Columns = append(rel.Columns[:idx], rel.Columns[idx+1:]...)
	c.renumberColumns(rel)
	c.shiftAttnumsAfterDrop(rel, attNum)

	// AlterTableStmt hands the drop to rel's children; a child passes it on
	// to its own, one level at a time as PostgreSQL does.
	// pg: src/backend/commands/tablecmds.c — ATExecDropColumn (children loop)
	if recursing {
		for _, childOID := range c.findChildRelations(rel.OID) {
			if child := c.relationByOID[childOID]; child != nil {
				if err := c.atDropColumn(child.Schema, child, colName, cascade, true, true); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

// atDropConstraint drops a constraint from a relation.
//
// pg: src/backend/commands/tablecmds.c — ATExecDropConstraint
// PG calls performDeletion(&conobj, behavior, 0), which checks
// DEPENDENCY_NORMAL entries against the constraint. The backing index
// has DEPENDENCY_INTERNAL and is always auto-cascaded, so the objects
// that depend on the index are the constraint's dependents too: a
// foreign key referencing a primary key or unique constraint depends on
// its index.
func (c *Catalog) atDropConstraint(schema *Schema, rel *Relation, conName string, cascade, ifExists bool) error {
	for _, con := range c.consByRel[rel.OID] {
		if con.Name == conName {
			// Check for NORMAL dependents (e.g. views) — require CASCADE.
			if deps := c.findNormalDependents('c', con.OID); len(deps) > 0 {
				if !cascade {
					return errDependentObjects("constraint", conName)
				}
				c.dropDependents('c', con.OID)
			}
			if con.IndexOID != 0 {
				if deps := c.findNormalDependents('r', con.IndexOID); len(deps) > 0 {
					if !cascade {
						return errDependentObjects("constraint", conName)
					}
					c.dropDependents('r', con.IndexOID)
				}
			}
			c.removeConstraint(schema, con)
			return nil
		}
	}
	if ifExists {
		return nil
	}
	return &Error{
		Code:    CodeUndefinedObject,
		Message: fmt.Sprintf("constraint %q of relation %q does not exist", conName, rel.Name),
	}
}

func (c *Catalog) atRenameColumn(rel *Relation, oldName, newName string) error {
	idx, exists := rel.colByName[oldName]
	if !exists {
		return errUndefinedColumn(oldName)
	}
	// pg: src/backend/commands/tablecmds.c — renameatt_internal → check_for_column_name_collision
	if _, dup := rel.colByName[newName]; dup {
		return errColumnAlreadyExists(newName, rel.Name)
	}

	rel.Columns[idx].Name = newName
	delete(rel.colByName, oldName)
	rel.colByName[newName] = idx
	return nil
}

func (c *Catalog) atRenameIndexColumn(idx *Index, oldName, newName string) error {
	colNames := c.indexColumnNames(idx)
	pos := slices.Index(colNames, oldName)
	if pos < 0 {
		return errUndefinedColumn(oldName)
	}
	if slices.Contains(colNames, newName) {
		return errColumnAlreadyExists(newName, idx.Name)
	}
	idx.ColumnNames[pos] = newName
	return nil
}

