// atExecAttachPartition attaches a partition to a partitioned table.
//
// pg: src/backend/commands/tablecmds.c — ATExecAttachPartition
func (c *Catalog) atExecAttachPartition(schema *Schema, parent *Relation, pc *nodes.PartitionCmd) error {
	if parent.PartitionInfo == nil {
		return errInvalidObjectDefinition(fmt.Sprintf("table %q is not partitioned", parent.Name))
	}
	if pc.Name == nil {
		return errInvalidParameterValue("ATTACH PARTITION requires a partition name")
	}

	_, part, err := c.findRelation(pc.Name.Schemaname, pc.Name.Relname)
	if err != nil {
		return err
	}

	// Preflight trigger-name collisions before mutating partition links.
	for _, trig := range c.triggersByRel[parent.OID] {
		if !trig.ForEachRow || trig.IsConstraint {
			continue
		}
		for _, existing := range c.triggersByRel[part.OID] {
			if existing.Name == trig.Name {
				return errDuplicateObject("trigger", trig.Name)
			}
		}
		if part.RelKind == 'p' {
			if err := c.checkPartitionTriggerName(part, trig.Name, false); err != nil {
				return err
			}
		}
	}

	// Store partition bound.
	if pc.Bound != nil {
		part.PartitionBound = &PartitionBound{
			Strategy:   pc.Bound.Strategy,
			IsDefault:  pc.Bound.IsDefault,
			ListValues: deparseDatumList(pc.Bound.Listdatums),
			LowerBound: deparseDatumList(pc.Bound.Lowerdatums),
			UpperBound: deparseDatumList(pc.Bound.Upperdatums),
			Modulus:    pc.Bound.Modulus,
			Remainder:  pc.Bound.Remainder,
		}
	}
	part.PartitionOf = parent.OID
	part.InhParents = []uint32{parent.OID}
	part.InhCount = 1

	// Record inheritance entry.
	c.inhEntries = append(c.inhEntries, InhEntry{
		InhRelID:  part.OID,
		InhParent: parent.OID,
		InhSeqNo:  1,
	})

	// Record auto-dependency (partition auto-dropped with parent).
	c.recordDependency('r', part.OID, 0, 'r', parent.OID, 0, DepAuto)

	// Clone parent's indexes, triggers, and FK constraints to the attached partition.
	// pg: src/backend/commands/tablecmds.c — ATExecAttachPartition
	c.cloneIndexesToPartition(schema, parent, part)
	c.cloneRowTriggersToPartition(parent, part)
	c.cloneForeignKeyConstraints(schema, parent, part)

	return nil
}

// atExecDetachPartition detaches a partition from a partitioned table.
//
// pg: src/backend/commands/tablecmds.c — ATExecDetachPartition
func (c *Catalog) atExecDetachPartition(parent *Relation, pc *nodes.PartitionCmd) error {
	if parent.PartitionInfo == nil {
		return errInvalidObjectDefinition(fmt.Sprintf("table %q is not partitioned", parent.Name))
	}
	if pc.Name == nil {
		return errInvalidParameterValue("DETACH PARTITION requires a partition name")
	}

	_, part, err := c.findRelation(pc.Name.Schemaname, pc.Name.Relname)
	if err != nil {
		return err
	}

	if part.PartitionOf != parent.OID {
		return errInvalidObjectDefinition(fmt.Sprintf("relation %q is not a partition of %q", part.Name, parent.Name))
	}

	// Clear partition info and parent links on cloned indexes, constraints, and triggers.
	part.PartitionBound = nil
	part.PartitionOf = 0
	part.InhParents = nil
	part.InhCount = 0
	for _, idx := range c.indexesByRel[part.OID] {
		if parentIdx := c.indexes[idx.ParentIndexOID]; parentIdx != nil && parentIdx.RelOID == parent.OID {
			idx.ParentIndexOID = 0
		}
	}
	for _, con := range c.consByRel[part.OID] {
		if parentCon := c.constraints[con.ConParentID]; parentCon != nil && parentCon.RelOID == parent.OID {
			con.ConParentID = 0
		}
	}
	// Remove row triggers cloned from the detached parent.
	// pg: src/backend/commands/tablecmds.c — DetachPartitionFinalize (RemoveTriggerById)
	var clonedTrigs []*Trigger
	for _, trig := range c.triggersByRel[part.OID] {
		if parentTrig := c.triggers[trig.ParentTriggerOID]; parentTrig != nil && parentTrig.RelOID == parent.OID {
			clonedTrigs = append(clonedTrigs, trig)
		}
	}
	for _, trig := range clonedTrigs {
		c.removeTrigger(trig)
	}

	// Remove inheritance entry between part and parent.
	nInh := 0
	for _, e := range c.inhEntries {
		if e.InhRelID == part.OID && e.InhParent == parent.OID {
			continue
		}
		c.inhEntries[nInh] = e
		nInh++
	}
	c.inhEntries = c.inhEntries[:nInh]

	// Remove only the partition-to-parent relation dependency (preserve column/type/AM deps).
	nDep := 0
	for _, d := range c.deps {
		if d.ObjType == 'r' && d.ObjOID == part.OID && d.RefType == 'r' && d.RefOID == parent.OID {
			continue
		}
		c.deps[nDep] = d
		nDep++
	}
	c.deps = c.deps[:nDep]

	return nil
}

// atExecDetachPartitionFinalize handles ALTER TABLE ... DETACH PARTITION ... FINALIZE.
// PostgreSQL looks up the named child relation and verifies it is a partition
// of parent (reporting 42P01 when not) before detaching.
//
// pg: src/backend/commands/tablecmds.c — ATExecDetachPartitionFinalize
func (c *Catalog) atExecDetachPartitionFinalize(parent *Relation, pc *nodes.PartitionCmd) error {
	if pc.Name == nil {
		return errInvalidParameterValue("DETACH PARTITION requires a partition name")
	}
	_, part, err := c.findRelation(pc.Name.Schemaname, pc.Name.Relname)
	if err != nil {
		return err
	}
	if parent.PartitionInfo == nil || part.PartitionOf != parent.OID {
		return &Error{
			Code:    CodeUndefinedTable,
			Message: fmt.Sprintf("relation %q is not a partition of relation %q", part.Name, parent.Name),
		}
	}
	return c.atExecDetachPartition(parent, pc)
}

// renumberColumns rebuilds attnums and colByName after a column removal.
func (c *Catalog) renumberColumns(rel *Relation) {
	rel.colByName = make(map[string]int, len(rel.Columns))
	for i, col := range rel.Columns {
		col.AttNum = int16(i + 1)
		rel.colByName[col.Name] = i
	}
}

// checkChildColumnDrops refuses a DROP COLUMN that a descendant of rel would
// refuse: the descendant's column has no other parent or local definition,
// so it goes too, and it is in the descendant's partition key, or something
// depends on it and there is no CASCADE.
//
// pg: src/backend/commands/tablecmds.c — ATExecDropColumn deletes the
// column of every child within the same statement
func (c *Catalog) checkChildColumnDrops(rel *Relation, colName string, cascade bool) error {
	for _, childOID := range c.findChildRelations(rel.OID) {
		child := c.relationByOID[childOID]
		if child == nil {
			continue
		}
		idx, ok := child.colByName[colName]
		if !ok {
			continue
		}
		col := child.Columns[idx]
		if col.InhCount > 1 || col.InhCount == 1 && col.IsLocal {
			continue
		}
		if err := checkNotPartitionKey(child, col); err != nil {
			return err
		}
		if !cascade && hasNormalDependent(c.relationDependents(child.OID, col.AttNum)) {
			return errDependentObjects("column", colName)
		}
		if err := c.checkChildColumnDrops(child, colName, cascade); err != nil {
			return err
		}
	}
	return nil
}

// checkNotPartitionKey refuses dropping a column of rel's partition key.
//
// pg: src/backend/commands/tablecmds.c — ATExecDropColumn (has_partition_attrs)
func checkNotPartitionKey(rel *Relation, col *Column) error {
	if rel.PartitionInfo == nil {
		return nil
	}
	for _, keyAttNum := range rel.PartitionInfo.KeyAttNums {
		if keyAttNum == col.AttNum {
			return &Error{
				Code:    CodeInvalidTableDefinition,
				Message: fmt.Sprintf("cannot drop column %q because it is part of the partition key of relation %q", col.Name, rel.Name),
			}
		}
	}
	return nil
}

// shiftAttnumsAfterDrop moves the stored references to the columns that
// followed the dropped column attnum down by one, as renumberColumns moved
// the columns. PostgreSQL keeps a dropped column's attnum and renumbers
// nothing; the catalog compacts Columns instead, so every attnum it keeps
// for the relation (dependency entries, constraint and index keys, owned
// sequences, trigger columns, the partition key, column comments) must move
// with it. The dropped column's own comment goes with it.
//
// Slices are replaced rather than edited in place: a constraint cloned to a
// partition shares its parent's slices.
func (c *Catalog) shiftAttnumsAfterDrop(rel *Relation, attnum int16) {
	shift := func(a int16) int16 {
		if a > attnum {
			return a - 1
		}
		return a
	}
	shiftAll := func(as []int16) []int16 {
		if as == nil {
			return nil
		}
		out := make([]int16, len(as))
		for i, a := range as {
			out[i] = shift(a)
		}
		return out
	}

	// The dropped column's own entries go: those of its generation
	// expression, and any left on it after its dependents were dropped.
	n := 0
	for _, d := range c.deps {
		if d.ObjType == 'r' && d.ObjOID == rel.OID && d.ObjSubID == int32(attnum) ||
			d.RefType == 'r' && d.RefOID == rel.OID && d.RefSubID == int32(attnum) {
			continue
		}
		if d.RefType == 'r' && d.RefOID == rel.OID && d.RefSubID > int32(attnum) {
			d.RefSubID--
		}
		if d.ObjType == 'r' && d.ObjOID == rel.OID && d.ObjSubID > int32(attnum) {
			d.ObjSubID--
		}
		c.deps[n] = d
		n++
	}
	c.deps = c.deps[:n]
	for _, con := range c.consByRel[rel.OID] {
		con.Columns = shiftAll(con.Columns)
		con.IncludeColumns = shiftAll(con.IncludeColumns)
		con.FKDelSetCols = shiftAll(con.FKDelSetCols)
	}
	for _, con := range c.constraints {
		if con.Type == ConstraintFK && con.FRelOID == rel.OID {
			con.FColumns = shiftAll(con.FColumns)
		}
	}
	for _, idx := range c.indexesByRel[rel.OID] {
		idx.Columns = shiftAll(idx.Columns)
	}
	for _, seq := range c.sequenceByOID {
		if seq.OwnerRelOID == rel.OID {
			seq.OwnerAttNum = shift(seq.OwnerAttNum)
		}
	}
	for _, trig := range c.triggersByRel[rel.OID] {
		trig.Columns = shiftAll(trig.Columns)
	}
	for _, rule := range c.rules {
		if rule == nil || rule.bindings == nil {
			continue
		}
		for ref, cb := range rule.bindings.colByRef {
			if cb.relOID == rel.OID && cb.attNum > attnum {
				cb.attNum--
				rule.bindings.colByRef[ref] = cb
			}
		}
		for rt, cb := range rule.bindings.colByRT {
			if cb.relOID == rel.OID && cb.attNum > attnum {
				cb.attNum--
				rule.bindings.colByRT[rt] = cb
			}
		}
	}
	if rel.PartitionInfo != nil {
		rel.PartitionInfo.KeyAttNums = shiftAll(rel.PartitionInfo.KeyAttNums)
	}

	moved := make(map[commentKey]string)
	for k, text := range c.comments {
		if k.ObjType != 'r' || k.ObjOID != rel.OID || k.SubID < attnum {
			continue
		}
		delete(c.comments, k)
		if k.SubID > attnum {
			k.SubID--
			moved[k] = text
		}
	}
	for k, text := range moved {
		c.comments[k] = text
	}
}

// ExecAlterObjectSchemaStmt moves an object to a different schema (SET SCHEMA).
//
// pg: src/backend/commands/alter.c — ExecAlterObjectSchemaStmt
func (c *Catalog) ExecAlterObjectSchemaStmt(stmt *nodes.AlterObjectSchemaStmt) error {
	if nodes.ObjectType(stmt.ObjectType) == nodes.OBJECT_EXTENSION {
		return c.alterExtensionNamespace(stmt)
	}
	// PostgreSQL resolves the object and checks its kind before it reads the
	// target schema, and IF EXISTS skips a missing object before either. So
	// ALTER SEQUENCE on a table is 42809, not "schema does not exist".
	skip, err := c.checkSchemaMoveObject(stmt)
	if err != nil {
		return err
	}
	if skip {
		return nil
	}

	newSchema := c.schemaByName[stmt.Newschema]
	if newSchema == nil {
		return errUndefinedSchema(stmt.Newschema)
	}

	switch stmt.ObjectType {
	case nodes.OBJECT_TABLE, nodes.OBJECT_VIEW, nodes.OBJECT_MATVIEW, nodes.OBJECT_SEQUENCE, nodes.OBJECT_FOREIGN_TABLE:
		return c.alterRelationNamespace(stmt, newSchema)
	case nodes.OBJECT_FUNCTION, nodes.OBJECT_PROCEDURE, nodes.OBJECT_ROUTINE, nodes.OBJECT_AGGREGATE:
		return c.alterFunctionNamespace(stmt, newSchema)
	case nodes.OBJECT_TYPE, nodes.OBJECT_DOMAIN:
		return c.alterTypeNamespace(stmt, newSchema)
	case nodes.OBJECT_OPERATOR:
		return c.alterOperatorNamespace(stmt, newSchema)
	case nodes.OBJECT_OPCLASS:
		return c.alterOpClassNamespace(stmt, newSchema)
	case nodes.OBJECT_OPFAMILY:
		return c.alterOpFamilyNamespace(stmt, newSchema)
	case nodes.OBJECT_COLLATION:
		return c.alterCollationNamespace(stmt, newSchema)
	default:
		return nil // no-op for unsupported object types
	}
}

// checkSchemaMoveObject resolves the object a SET SCHEMA moves and checks
// that its kind is the one the statement names. A missing object under IF
// EXISTS skips the whole statement, before the target schema is read.
func (c *Catalog) checkSchemaMoveObject(stmt *nodes.AlterObjectSchemaStmt) (skip bool, err error) {
	var schemaName, name string
	if stmt.Relation != nil {
		schemaName = stmt.Relation.Schemaname
		name = stmt.Relation.Relname
	}
	switch stmt.ObjectType {
	case nodes.OBJECT_SEQUENCE:
		_, err := c.findSequence(schemaName, name)
		if err != nil {
			if stmt.MissingOk && missingObject(err) {
				return true, nil
			}
			return false, err
		}
	case nodes.OBJECT_TABLE, nodes.OBJECT_VIEW, nodes.OBJECT_MATVIEW, nodes.OBJECT_FOREIGN_TABLE:
		_, rel, err := c.findRelation(schemaName, name)
		if err != nil {
			if stmt.MissingOk && missingObject(err) {
				return true, nil
			}
			return false, err
		}
		switch stmt.ObjectType {
		case nodes.OBJECT_TABLE:
			if rel.RelKind != 'r' && rel.RelKind != 'p' && rel.RelKind != 'f' {
				return false, errWrongObjectType(name, "a table")
			}
		case nodes.OBJECT_VIEW:
			if rel.RelKind != 'v' {
				return false, errWrongObjectType(name, "a view")
			}
		case nodes.OBJECT_MATVIEW:
			if rel.RelKind != 'm' {
				return false, errWrongObjectType(name, "a materialized view")
			}
		case nodes.OBJECT_FOREIGN_TABLE:
			if rel.RelKind != 'f' {
				return false, errWrongObjectType(name, "a foreign table")
			}
		}
	case nodes.OBJECT_FUNCTION, nodes.OBJECT_PROCEDURE, nodes.OBJECT_ROUTINE, nodes.OBJECT_AGGREGATE:
		if owa, ok := stmt.Object.(*nodes.ObjectWithArgs); ok {
			if _, _, _, err := c.resolveRoutineTarget(stmt.ObjectType, owa); err != nil {
				if stmt.MissingOk && missingObject(err) {
					return true, nil
				}
				return false, err
			}
		}
	case nodes.OBJECT_TYPE, nodes.OBJECT_DOMAIN:
		sName, tName := extractObjectName(stmt.Object)
		var bt *BuiltinType
		if sName != "" {
			s, err := c.resolveTargetSchema(sName)
			if err != nil {
				if stmt.MissingOk && missingObject(err) {
					return true, nil
				}
				return false, err
			}
			bt = c.typeByName[typeKey{ns: s.OID, name: tName}]
		} else {
			for _, nsOID := range c.searchPathWithCatalog() {
				if found := c.typeByName[typeKey{ns: nsOID, name: tName}]; found != nil {
					bt = found
					break
				}
			}
		}
		if bt == nil {
			if stmt.MissingOk {
				return true, nil
			}
			return false, errUndefinedType(tName)
		}
		if stmt.ObjectType == nodes.OBJECT_DOMAIN && bt.Type != 'd' {
			return false, errWrongObjectType(tName, "a domain")
		}
	case nodes.OBJECT_OPERATOR:
		if owa, ok := stmt.Object.(*nodes.ObjectWithArgs); ok {
			if _, err := c.lookupUserOperator(owa); err != nil {
				if stmt.MissingOk && missingObject(err) {
					return true, nil
				}
				return false, err
			}
		}
	case nodes.OBJECT_OPCLASS:
		amName, opcSchema, opcName := extractOpClassObject(stmt.Object)
		am, err := c.lookupIndexAccessMethod(amName)
		if err != nil {
			return false, err
		}
		if _, err := c.lookupOpClass(am, opcSchema, opcName); err != nil {
			if stmt.MissingOk && missingObject(err) {
				return true, nil
			}
			return false, err
		}
	case nodes.OBJECT_OPFAMILY:
		amName, famSchema, famName := extractOpClassObject(stmt.Object)
		am, err := c.lookupIndexAccessMethod(amName)
		if err != nil {
			return false, err
		}
		if _, err := c.lookupOpFamily(am, famSchema, famName); err != nil {
			if stmt.MissingOk && missingObject(err) {
				return true, nil
			}
			return false, err
		}
	case nodes.OBJECT_COLLATION:
		if _, _, err := c.lookupUserCollation(stmt.Object); err != nil {
			if stmt.MissingOk && missingObject(err) {
				return true, nil
			}
			return false, err
		}
	}
	return false, nil
}

func (c *Catalog) renameCollation(stmt *nodes.RenameStmt) error {
	schema, uc, err := c.lookupUserCollation(stmt.Object)
	if err != nil {
		if (stmt.MissingOk || c.snapshot) && missingObject(err) {
			return nil
		}
		return err
	}
	if schema == nil || uc == nil {
		return nil
	}
	if stmt.Newname != uc.Name && schema.Collations[stmt.Newname] != nil {
		return errDuplicateObject("collation", stmt.Newname)
	}
	oldName := uc.Name
	delete(schema.Collations, oldName)
	uc.Name = stmt.Newname
	schema.Collations[stmt.Newname] = uc
	c.syncRenamedUserCollationRefs(uc.OID, schema.Name, stmt.Newname)
	return nil
}

func (c *Catalog) alterCollationNamespace(stmt *nodes.AlterObjectSchemaStmt, newSchema *Schema) error {
	oldSchema, uc, err := c.lookupUserCollation(stmt.Object)
	if err != nil {
		if (stmt.MissingOk || c.snapshot) && missingObject(err) {
			return nil
		}
		return err
	}
	if oldSchema == nil || uc == nil || oldSchema.OID == newSchema.OID {
		return nil
	}
	if newSchema.Collations != nil && newSchema.Collations[uc.Name] != nil {
		return errDuplicateObject("collation", uc.Name)
	}
	if newSchema.Collations == nil {
		newSchema.Collations = make(map[string]*UserCollation)
	}
	delete(oldSchema.Collations, uc.Name)
	newSchema.Collations[uc.Name] = uc
	c.syncRenamedUserCollationRefs(uc.OID, newSchema.Name, uc.Name)
	return nil
}

func (c *Catalog) syncRenamedUserCollationRefs(collOID uint32, schemaName, collName string) {
	qualSchema := ""
	if schemaName != "public" && schemaName != "pg_catalog" {
		qualSchema = schemaName
	}
	for _, rel := range c.relationByOID {
		for _, col := range rel.Columns {
			if col.UserCollationOID == collOID {
				col.CollationSchema = qualSchema
				col.CollationName = collName
			}
		}
	}
	for _, dt := range c.domainTypes {
		if dt != nil && dt.UserCollationOID == collOID {
			dt.CollationName = collName
		}
	}
	for _, rt := range c.rangeTypes {
		if rt != nil && rt.UserCollationOID == collOID {
			rt.CollationSchema = qualSchema
			rt.CollationName = collName
		}
	}
}

// alterRelationNamespace moves a relation (table/view/matview/sequence) to a new schema.
//
// pg: src/backend/commands/tablecmds.c — AlterTableNamespace
func (c *Catalog) alterRelationNamespace(stmt *nodes.AlterObjectSchemaStmt, newSchema *Schema) error {
	var schemaName, relName string
	if stmt.Relation != nil {
		schemaName = stmt.Relation.Schemaname
		relName = stmt.Relation.Relname
	}

	// Handle sequences.
	if stmt.ObjectType == nodes.OBJECT_SEQUENCE {
		seq, err := c.findSequence(schemaName, relName)
		if err != nil {
			if stmt.MissingOk && missingObject(err) {
				return nil
			}
			return err
		}
		if seq.Schema.OID == newSchema.OID {
			return nil
		}
		if _, exists := relationNamespaceKind(newSchema, seq.Name); exists {
			return errDuplicateTable(seq.Name)
		}
		delete(seq.Schema.Sequences, seq.Name)
		newSchema.Sequences[seq.Name] = seq
		seq.Schema = newSchema
		return nil
	}

	oldSchema, rel, err := c.findRelation(schemaName, relName)
	if err != nil {
		if stmt.MissingOk && missingObject(err) {
			return nil
		}
		return err
	}
	if oldSchema.OID == newSchema.OID {
		return nil
	}

	// Preflight relation, row/array types, indexes, and owned sequences in target schema.
	if _, exists := relationNamespaceKind(newSchema, rel.Name); exists {
		return errDuplicateTable(rel.Name)
	}
	if rel.RowTypeOID != 0 && c.typeByName[typeKey{ns: newSchema.OID, name: rel.Name}] != nil {
		return errDuplicateObject("type", rel.Name)
	}
	for _, idx := range c.indexesByRel[rel.OID] {
		if idx.Schema == oldSchema {
			if _, exists := relationNamespaceKind(newSchema, idx.Name); exists {
				return errDuplicateTable(idx.Name)
			}
		}
	}
	var ownedSeqs []*Sequence
	for _, seq := range c.sequenceByOID {
		if seq.OwnerRelOID == rel.OID && seq.Schema == oldSchema {
			if _, exists := relationNamespaceKind(newSchema, seq.Name); exists {
				return errDuplicateTable(seq.Name)
			}
			ownedSeqs = append(ownedSeqs, seq)
		}
	}
	if rel.ArrayOID != 0 {
		if at := c.typeByOID[rel.ArrayOID]; at != nil {
			if err := c.ensureArrayTypeNameFree(newSchema.OID, at.TypeName); err != nil {
				return err
			}
		}
	}

	// Move relation.
	delete(oldSchema.Relations, rel.Name)
	newSchema.Relations[rel.Name] = rel
	rel.Schema = newSchema

	// Move row type and array type namespace.
	if rt := c.typeByOID[rel.RowTypeOID]; rt != nil {
		delete(c.typeByName, typeKey{ns: oldSchema.OID, name: rt.TypeName})
		rt.Namespace = newSchema.OID
		c.typeByName[typeKey{ns: newSchema.OID, name: rt.TypeName}] = rt
	}
	if at := c.typeByOID[rel.ArrayOID]; at != nil {
		delete(c.typeByName, typeKey{ns: oldSchema.OID, name: at.TypeName})
		at.Namespace = newSchema.OID
		c.typeByName[typeKey{ns: newSchema.OID, name: at.TypeName}] = at
	}

	// Update constraint namespaces.
	for _, con := range c.consByRel[rel.OID] {
		con.Namespace = newSchema.OID
	}

	// Move indexes.
	for _, idx := range c.indexesByRel[rel.OID] {
		if idx.Schema == oldSchema {
			delete(oldSchema.Indexes, idx.Name)
			newSchema.Indexes[idx.Name] = idx
			idx.Schema = newSchema
		}
	}

	// Move owned sequences.
	for _, seq := range ownedSeqs {
		delete(oldSchema.Sequences, seq.Name)
		newSchema.Sequences[seq.Name] = seq
		seq.Schema = newSchema
	}

	return nil
}

// alterFunctionNamespace moves a routine to a new schema.
//
// pg: src/backend/commands/functioncmds.c — AlterFunctionNamespace
func (c *Catalog) alterFunctionNamespace(stmt *nodes.AlterObjectSchemaStmt, newSchema *Schema) error {
	if owa, ok := stmt.Object.(*nodes.ObjectWithArgs); ok {
		oldSchema, bp, up, err := c.resolveRoutineTarget(stmt.ObjectType, owa)
		if err != nil {
			if stmt.MissingOk && missingObject(err) {
				return nil
			}
			return err
		}
		if oldSchema.OID == newSchema.OID {
			return nil
		}
		for _, other := range c.findUserProcsByName(newSchema, up.Name) {
			if other.OID != up.OID && slices.Equal(c.procByOID[other.OID].ArgTypes, bp.ArgTypes) {
				return errDuplicateFunction(up.Name)
			}
		}
		up.Schema = newSchema
		return nil
	}

	schemaName, funcName := extractObjectName(stmt.Object)
	oldSchema, err := c.resolveTargetSchema(schemaName)
	if err != nil {
		if stmt.MissingOk {
			return nil
		}
		return err
	}

	procs := c.findUserProcsByName(oldSchema, funcName)
	if len(procs) == 0 {
		if stmt.MissingOk {
			return nil
		}
		return &Error{Code: CodeUndefinedFunction, Message: fmt.Sprintf("function %s does not exist", funcName)}
	}
	if len(procs) > 1 {
		return errAmbiguousFunction(funcName)
	}
	up := procs[0]
	if oldSchema.OID == newSchema.OID {
		return nil
	}
	bp := c.procByOID[up.OID]
	for _, other := range c.findUserProcsByName(newSchema, up.Name) {
		if other.OID != up.OID && bp != nil && slices.Equal(c.procByOID[other.OID].ArgTypes, bp.ArgTypes) {
			return errDuplicateFunction(up.Name)
		}
	}
	up.Schema = newSchema
	return nil
}

// alterTypeNamespace moves a type to a new schema.
//
// pg: src/backend/commands/typecmds.c — AlterTypeNamespace
func (c *Catalog) alterTypeNamespace(stmt *nodes.AlterObjectSchemaStmt, newSchema *Schema) error {
	schemaName, typeName := extractObjectName(stmt.Object)
	var oldSchema *Schema
	var bt *BuiltinType
	if schemaName != "" {
		var err error
		oldSchema, err = c.resolveTargetSchema(schemaName)
		if err != nil {
			if stmt.MissingOk && missingObject(err) {
				return nil
			}
			return err
		}
		bt = c.typeByName[typeKey{ns: oldSchema.OID, name: typeName}]
	} else {
		for _, nsOID := range c.searchPathWithCatalog() {
			if found := c.typeByName[typeKey{ns: nsOID, name: typeName}]; found != nil {
				bt = found
				oldSchema = c.schemas[nsOID]
				break
			}
		}
	}
	if bt == nil || oldSchema == nil {
		if stmt.MissingOk {
			return nil
		}
		return errUndefinedType(typeName)
	}
	if stmt.ObjectType == nodes.OBJECT_DOMAIN && bt.Type != 'd' {
		return errWrongObjectType(typeName, "a domain")
	}
	if oldSchema.OID == newSchema.OID {
		return nil
	}

	// Check for name conflicts (including composite backing relation).
	if c.typeByName[typeKey{ns: newSchema.OID, name: typeName}] != nil {
		return errDuplicateObject("type", typeName)
	}
	if bt.Type == 'c' && bt.RelID != 0 {
		if rel := c.relationByOID[bt.RelID]; rel != nil && rel.Schema == oldSchema {
			if _, exists := relationNamespaceKind(newSchema, rel.Name); exists {
				return errDuplicateTable(rel.Name)
			}
		}
	}
	if bt.Array != 0 {
		if at := c.typeByOID[bt.Array]; at != nil {
			if err := c.ensureArrayTypeNameFree(newSchema.OID, at.TypeName); err != nil {
				return err
			}
		}
	}

	// Move type.
	delete(c.typeByName, typeKey{ns: oldSchema.OID, name: typeName})
	bt.Namespace = newSchema.OID
	c.typeByName[typeKey{ns: newSchema.OID, name: typeName}] = bt

	// Move array type.
	if bt.Array != 0 {
		if at := c.typeByOID[bt.Array]; at != nil {
			delete(c.typeByName, typeKey{ns: oldSchema.OID, name: at.TypeName})
			at.Namespace = newSchema.OID
			c.typeByName[typeKey{ns: newSchema.OID, name: at.TypeName}] = at
		}
	}

	// Update range metadata namespace (PostgreSQL keeps the companion multirange
	// in its own namespace until moved explicitly).
	if bt.Type == 'r' {
		if rt := c.rangeTypes[bt.OID]; rt != nil {
			rt.Namespace = newSchema.OID
		}
	}

	// For composite types, move the backing relation too.
	if bt.Type == 'c' && bt.RelID != 0 {
		if rel := c.relationByOID[bt.RelID]; rel != nil && rel.Schema == oldSchema {
			delete(oldSchema.Relations, rel.Name)
			newSchema.Relations[rel.Name] = rel
			rel.Schema = newSchema
			for _, con := range c.consByRel[rel.OID] {
				con.Namespace = newSchema.OID
			}
		}
	}

	return nil
}

// extractObjectName extracts schema and name from an Object node (typically a *nodes.List or *nodes.String).
//
// (pgddl helper)
func extractObjectName(obj nodes.Node) (schema, name string) {
	switch n := obj.(type) {
	case *nodes.List:
		return qualifiedName(n)
	case *nodes.ObjectWithArgs:
		return qualifiedName(n.Objname)
	case *nodes.String:
		return "", n.Str
	default:
		return "", ""
	}
}

// transferACLs moves the grants on an object from its old owner to its new one,
// as PostgreSQL's aclnewowner does in both ACL positions.
func (c *Catalog) transferACLs(objType byte, objOID uint32, oldOwner, newOwner string) {
	if oldOwner == "" || newOwner == "" || oldOwner == newOwner {
		return
	}
	for i := range c.grants {
		if c.grants[i].ObjType != objType || c.grants[i].ObjOID != objOID {
			continue
		}
		if c.grants[i].Grantee == oldOwner {
			c.grants[i].Grantee = newOwner
		}
		if c.grants[i].Grantor == oldOwner {
			c.grants[i].Grantor = newOwner
		}
	}
}

// atAddInherit adds a parent to a table's inheritance list.
//
// pg: src/backend/commands/tablecmds.c — ATExecAddInherit
func (c *Catalog) atAddInherit(rel *Relation, rv *nodes.RangeVar) error {
	_, parent, err := c.findRelation(rv.Schemaname, rv.Relname)
	if err != nil {
		return err
	}
	if parent.RelKind != 'r' && parent.RelKind != 'p' {
		return errWrongObjectType(rv.Relname, "a table")
	}

	// Circularity check: an inherited table is already a child of itself,
	// and a parent that already has this child makes a cycle.
	if parent.OID == rel.OID || c.isAncestor(parent.OID, rel.OID) {
		return &Error{Code: CodeDuplicateTable, Message: "circular inheritance not allowed"}
	}

	// Merge parent columns into child (type must match, increment InhCount).
	for _, pcol := range parent.Columns {
		if existIdx, exists := rel.colByName[pcol.Name]; exists {
			childCol := rel.Columns[existIdx]
			if childCol.TypeOID != pcol.TypeOID {
				return errDatatypeMismatch(fmt.Sprintf(
					"column %q has a type conflict", pcol.Name,
				))
			}
			if pcol.NotNull {
				childCol.NotNull = true
			}
			childCol.InhCount++
		} else {
			// Add inherited column.
			col := &Column{
				AttNum:    int16(len(rel.Columns) + 1),
				Name:      pcol.Name,
				TypeOID:   pcol.TypeOID,
				TypeMod:   pcol.TypeMod,
				NotNull:   pcol.NotNull,
				Len:       pcol.Len,
				ByVal:     pcol.ByVal,
				Align:     pcol.Align,
				Storage:   pcol.Storage,
				Collation: pcol.Collation,
				IsLocal:   false,
				InhCount:  1,
			}
			if pcol.HasDefault {
				col.HasDefault = true
				col.Default = pcol.Default
			}
			rel.Columns = append(rel.Columns, col)
			rel.colByName[col.Name] = len(rel.Columns) - 1
		}
	}

	// Record inheritance entry.
	seqNo := int32(len(rel.InhParents) + 1)
	rel.InhParents = append(rel.InhParents, parent.OID)
	rel.InhCount++
	c.inhEntries = append(c.inhEntries, InhEntry{
		InhRelID:  rel.OID,
		InhParent: parent.OID,
		InhSeqNo:  seqNo,
	})
	c.recordDependency('r', rel.OID, 0, 'r', parent.OID, 0, DepNormal)

	return nil
}

// atDropInherit removes a parent from a table's inheritance list.
//
// pg: src/backend/commands/tablecmds.c — ATExecDropInherit
func (c *Catalog) atDropInherit(rel *Relation, rv *nodes.RangeVar) error {
	// Cannot use on partitions (must DETACH instead).
	if rel.PartitionOf != 0 {
		return errInvalidObjectDefinition("cannot drop inheritance from a partition; use DETACH PARTITION instead")
	}

	_, parent, err := c.findRelation(rv.Schemaname, rv.Relname)
	if err != nil {
		return err
	}

	// Verify this is actually a parent.
	found := false
	for i, pid := range rel.InhParents {
		if pid == parent.OID {
			rel.InhParents = append(rel.InhParents[:i], rel.InhParents[i+1:]...)
			found = true
			break
		}
	}
	if !found {
		return &Error{
			Code:    CodeUndefinedTable,
			Message: fmt.Sprintf("relation %q is not a parent of relation %q", parent.Name, rel.Name),
		}
	}
	rel.InhCount--

	// Decrement InhCount on inherited columns; if InhCount→0, set IsLocal=true.
	for _, pcol := range parent.Columns {
		if existIdx, exists := rel.colByName[pcol.Name]; exists {
			childCol := rel.Columns[existIdx]
			childCol.InhCount--
			if childCol.InhCount <= 0 {
				childCol.IsLocal = true
				childCol.InhCount = 0
			}
		}
	}

	// Remove inheritance entry.
	n := 0
	for _, e := range c.inhEntries {
		if e.InhRelID == rel.OID && e.InhParent == parent.OID {
			continue
		}
		c.inhEntries[n] = e
		n++
	}
	c.inhEntries = c.inhEntries[:n]

	// Remove dependency.
	c.removeDep('r', rel.OID, 'r', parent.OID)

	return nil
}

// isAncestor checks if ancestorOID is an ancestor of relOID in the inheritance tree.
func (c *Catalog) isAncestor(ancestorOID, relOID uint32) bool {
	for _, e := range c.inhEntries {
		if e.InhRelID == ancestorOID && e.InhParent == relOID {
			return true
		}
		if e.InhRelID == ancestorOID {
			if c.isAncestor(e.InhParent, relOID) {
				return true
			}
		}
	}
	return false
}

// removeDep removes a specific dependency entry.
func (c *Catalog) removeDep(objType byte, objOID uint32, refType byte, refOID uint32) {
	n := 0
	for _, dep := range c.deps {
		if dep.ObjType == objType && dep.ObjOID == objOID && dep.RefType == refType && dep.RefOID == refOID {
			continue
		}
		c.deps[n] = dep
		n++
	}
	c.deps = c.deps[:n]
}

// atClusterOn sets the clustered index on a relation.
//
// pg: src/backend/commands/tablecmds.c — ATExecClusterOn
func (c *Catalog) atClusterOn(rel *Relation, indexName string) error {
	// Find and validate the named index first before mutating existing flags.
	// PostgreSQL resolves the name in the relation namespace, so a table or
	// sequence of that name is 42809.
	idx, err := c.findNamedIndex(rel.Schema, indexName)
	if err != nil {
		return err
	}
	if idx.RelOID != rel.OID {
		return errUndefinedObject("index", indexName)
	}
	for _, existing := range c.indexesByRel[rel.OID] {
		existing.IsClustered = false
	}
	idx.IsClustered = true
	return nil
}

// atDropCluster clears the clustered index on a relation.
//
// pg: src/backend/commands/tablecmds.c — ATExecDropCluster
func (c *Catalog) atDropCluster(rel *Relation) error {
	for _, idx := range c.indexesByRel[rel.OID] {
		idx.IsClustered = false
	}
	return nil
}

// atReplicaIdentity sets the replica identity for a relation.
//
// pg: src/backend/commands/tablecmds.c — ATExecReplicaIdentity
func (c *Catalog) atReplicaIdentity(rel *Relation, atc *nodes.AlterTableCmd) error {
	var mode byte
	idxName := atc.Name
	if ri, ok := atc.Def.(*nodes.ReplicaIdentityStmt); ok && ri != nil {
		mode = ri.IdentityType
		if idxName == "" {
			idxName = ri.Name
		}
	}
	if mode == 'i' || idxName != "" {
		// USING INDEX variant — validate before clearing any existing flag.
		idx, err := c.findNamedIndex(rel.Schema, idxName)
		if err != nil {
			return err
		}
		if idx.RelOID != rel.OID {
			return errUndefinedObject("index", idxName)
		}
		if !idx.IsUnique {
			return errInvalidObjectDefinition(fmt.Sprintf("index %q is not a unique index", idxName))
		}
		for _, existing := range c.indexesByRel[rel.OID] {
			existing.IsReplicaIdent = false
		}
		rel.ReplicaIdentity = 'i'
		idx.IsReplicaIdent = true
		return nil
	}

	for _, existing := range c.indexesByRel[rel.OID] {
		existing.IsReplicaIdent = false
	}
	if mode == 'f' || mode == 'n' || mode == 'd' {
		rel.ReplicaIdentity = mode
	} else {
		rel.ReplicaIdentity = 'd'
	}
	return nil
}

// atSetCompression sets the compression method for a column.
//
// pg: src/backend/commands/tablecmds.c — ATExecSetCompression
func (c *Catalog) atSetCompression(rel *Relation, colName, compName string) error {
	idx, exists := rel.colByName[colName]
	if !exists {
		return errUndefinedColumn(colName)
	}
	col := rel.Columns[idx]
	method, err := c.resolveColumnCompression(c.typeByOID[col.TypeOID], compName)
	if err != nil {
		return err
	}
	col.Compression = method
	return nil
}

// atAddOf sets the typed table association (OF type).
//
// pg: src/backend/commands/tablecmds.c — ATExecAddOf
func (c *Catalog) atAddOf(rel *Relation, atc *nodes.AlterTableCmd) error {
	tn, ok := atc.Def.(*nodes.TypeName)
	if !ok {
		return errInvalidParameterValue("OF requires a type name")
	}
	typName := convertTypeNameToInternal(tn)
	typeOID, _, err := c.ResolveType(typName)
	if err != nil {
		return err
	}

	typeRel, err := c.checkOfType(typeOID)
	if err != nil {
		return err
	}

	// Verify columns match 1:1 with the composite type's relation.
	if typeRel != nil {
		if len(rel.Columns) != len(typeRel.Columns) {
			return errDatatypeMismatch(fmt.Sprintf("table has %d columns but type has %d", len(rel.Columns), len(typeRel.Columns)))
		}
		for i, tcol := range typeRel.Columns {
			rcol := rel.Columns[i]
			if rcol.Name != tcol.Name || rcol.TypeOID != tcol.TypeOID {
				return errDatatypeMismatch(fmt.Sprintf("table column %q does not match type column %q", rcol.Name, tcol.Name))
			}
		}
	}

	rel.OfTypeOID = typeOID
	c.recordDependency('r', rel.OID, 0, 't', typeOID, 0, DepNormal)
	return nil
}

// atDropOf removes the typed table association.
//
// pg: src/backend/commands/tablecmds.c — ATExecDropOf
func (c *Catalog) atDropOf(rel *Relation) error {
	if rel.OfTypeOID == 0 {
		return errWrongObjectType(rel.Name, "a typed table")
	}
	c.removeDep('r', rel.OID, 't', rel.OfTypeOID)
	rel.OfTypeOID = 0
	return nil
}

// atSetExpression updates a generated column's expression.
//
// pg: src/backend/commands/tablecmds.c — ATExecSetExpression
func (c *Catalog) atSetExpression(rel *Relation, colName string, expr nodes.Node) error {
	idx, exists := rel.colByName[colName]
	if !exists {
		return errUndefinedColumn(colName)
	}
	col := rel.Columns[idx]
	if col.Generated != 's' {
		return &Error{
			Code:    CodeObjectNotInPrerequisiteState,
			Message: fmt.Sprintf("column %q of relation %q is not a generated column", colName, rel.Name),
		}
	}
	analyzed, err := c.AnalyzeStandaloneExpr(expr, rel)
	if err != nil {
		if !c.installingSnapshot {
			return err
		}
		return nil
	}
	if analyzed != nil {
		if coerced, cerr := c.coerceToTargetType(analyzed, analyzed.exprType(), col.TypeOID, 'i'); cerr == nil && coerced != nil {
			analyzed = coerced
		} else if cerr != nil && !c.installingSnapshot {
			return cerr
		}
		col.DefaultAnalyzed = analyzed
		c.recordDependencyOnSingleRelExprForObject('r', rel.OID, int32(col.AttNum), analyzed, rel.OID,
			DepNormal, DepNormal)
		rte := c.buildRelationRTE(rel)
		col.GenerationExpr = c.DeparseExpr(analyzed, []*RangeTableEntry{rte}, false)
		col.Default = col.GenerationExpr
	}
	return nil
}

// atDropExpression drops the generated column expression.
//
// pg: src/backend/commands/tablecmds.c — ATExecDropExpression
func (c *Catalog) atDropExpression(rel *Relation, colName string, ifExists bool) error {
	idx, exists := rel.colByName[colName]
	if !exists {
		return errUndefinedColumn(colName)
	}
	col := rel.Columns[idx]
	if col.Generated != 's' {
		if ifExists {
			return nil
		}
		return &Error{
			Code:    CodeObjectNotInPrerequisiteState,
			Message: fmt.Sprintf("column %q of relation %q is not a generated column", colName, rel.Name),
		}
	}
	col.Generated = 0
	col.GenerationExpr = ""
	c.clearColumnDefaultDeps(rel, col)
	col.HasDefault = false
	col.Default = ""
	col.DefaultAnalyzed = nil
	return nil
}

// findChildRelations returns OIDs of all direct children (inheritance or partition) of a relation.
//
// (pgddl helper — scans pg_inherits entries)
func (c *Catalog) findChildRelations(parentOID uint32) []uint32 {
	var children []uint32
	for _, e := range c.inhEntries {
		if e.InhParent == parentOID {
			children = append(children, e.InhRelID)
		}
	}
	return children
}

func (c *Catalog) findPartitionChildRelations(parentOID uint32) []uint32 {
	var children []uint32
	for _, e := range c.inhEntries {
		if e.InhParent != parentOID {
			continue
		}
		child := c.relationByOID[e.InhRelID]
		if child != nil && child.PartitionOf == parentOID {
			children = append(children, e.InhRelID)
		}
	}
	return children
}

// shouldRecurse returns true if a given ALTER TABLE subcommand should be propagated
// to inheritance children.
//
// pg: src/backend/commands/tablecmds.c — ATSimpleRecursion
func shouldRecurse(subtype nodes.AlterTableType) bool {
	switch subtype {
	case nodes.AT_SetNotNull, nodes.AT_DropNotNull, nodes.AT_AddConstraint,
		nodes.AT_DropConstraint, nodes.AT_AddColumn, nodes.AT_DropColumn:
		return true
	}
	return false
}
