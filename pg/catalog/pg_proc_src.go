// checkInternalSymbol is fmgr_internal_validator: a LANGUAGE internal
// routine's AS string names a function the server is built with. It runs
// whatever check_function_bodies says, and an empty string means the
// routine's own name.
//
// pg: src/backend/catalog/pg_proc.c — fmgr_internal_validator
// pg: src/backend/commands/functioncmds.c — interpret_AS_clause
func checkInternalSymbol(prosrc, name string) error {
	if prosrc == "" {
		prosrc = name
	}
	if !internalSymbols()[prosrc] {
		return &Error{Code: CodeUndefinedFunction, Message: fmt.Sprintf("there is no built-in function named %q", prosrc)}
	}
	return nil
}

// internalSymbols is the server's table of built-in functions, fmgr_builtins:
// the prosrc of every built-in internal function.
//
// pg: src/backend/utils/Gen_fmgrtab.pl
var internalSymbols = sync.OnceValue(func() map[string]bool {
	syms := make(map[string]bool, len(BuiltinProcs))
	for i := range BuiltinProcs {
		p := &BuiltinProcs[i]
		if p.Lang != internalLanguageOID {
			continue
		}
		if src, ok := builtinProcSrc[p.OID]; ok {
			syms[src] = true
		} else {
			syms[p.Name] = true
		}
	}
	return syms
})

